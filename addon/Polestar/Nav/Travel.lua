-- replace: drop what was registered before (tests and tools use it).
function Nav.RegisterTravelData(d, replace)
	if type(d) ~= "table" then return end
	if replace then clearData() end
	Travel.build = d.build
	for _, t in ipairs(d.taxi or {}) do
		local node = point(t[9], t[2], t[3], t[4], t[5], t[6], t[7], "e")
		node.id, node.faction, node.short = t[1], t[8], shortName(t[9])
		taxi[node.id] = node
		taxiList[#taxiList + 1] = node
		local key = lower(node.name)
		taxiByName[key] = taxiByName[key] or {}
		local list = taxiByName[key]
		list[#list + 1] = node.id
	end
	local fl = d.flights or {}
	for i = 1, #fl - 2, 3 do
		local from = fl[i]
		local list = flights[from]
		if not list then
			list = {}
			flights[from] = list
		end
		list[#list + 1] = fl[i + 1]
		list[#list + 1] = fl[i + 2]
	end
	for _, t in ipairs(d.transports or {}) do
		local a, b = t.a, t.b
		transports[#transports + 1] = {
			id = t.id, kind = t.kind, faction = t.faction,
			a = point(a[1], a[2], a[3], a[4], a[5], a[6], a[7], a[8] or "e", a[9]),
			b = point(b[1], b[2], b[3], b[4], b[5], b[6], b[7], b[8] or "e", b[9]),
			ab = t.ab, ba = t.ba, waitA = t.waitA, waitB = t.waitB,
		}
	end
	-- Walk-in portals, one way a -> b: { id, name, faction, a = end, b = end, seconds }.
	for _, t in ipairs(d.portals or {}) do
		local a, b = t.a, t.b
		if type(a) == "table" and type(b) == "table" then
			portals[#portals + 1] = {
				id = t.id, kind = "portal", name = t.name, area = t.area, faction = t.faction or 3, seconds = t.seconds or 5,
				a = point(a[1], a[2], a[3], a[4], a[5], a[6], a[7], a[8] or "e", a[9]),
				b = point(b[1], b[2], b[3], b[4], b[5], b[6], b[7], b[8] or "e", b[9]),
			}
		end
	end
	for _, t in ipairs(d.inns or {}) do
		local inn = point(t.names[1], t.c, t.wx, t.wy, t.map, t.x, t.y, t.f)
		inn.npc, inn.names, inn.area = t.npc, t.names, t.area
		inns[#inns + 1] = inn
		innByNpc[inn.npc] = inn
		for _, name in ipairs(t.names) do innByName[lower(name)] = inn end
	end
end

-- Learned walking paths: { nodes = { c, wx, wy, gateway, uiMap, ... } } and
-- { edges = { a, b, yards, ... } } (node numbers count across calls).
function Nav.AddTravelPaths(chunk)
	if type(chunk) ~= "table" then return end
	local nodes = chunk.nodes
	if nodes then
		for i = 1, #nodes - 4, 5 do
			pathCount = pathCount + 1
			pathC[pathCount], pathX[pathCount], pathY[pathCount] = nodes[i], nodes[i + 1], nodes[i + 2]
			pathMap[pathCount] = nodes[i + 4]
		end
	end
	local edges = chunk.edges
	if edges then
		for i = 1, #edges - 2, 3 do
			local a, b, yards = edges[i], edges[i + 1], edges[i + 2]
			local la, lb = pathAdj[a] or {}, pathAdj[b] or {}
			pathAdj[a], pathAdj[b] = la, lb
			la[#la + 1], la[#la + 2] = b, yards
			lb[#lb + 1], lb[#lb + 2] = a, yards
		end
	end
end

-- Zone crossings. d = {
--   complete = true    the continents this set touches walk between zones only through crossing data
--   zones = { [uiMap] = { name, c, top, bottom, left, right } }   (Era frame: places points whose map is no zone)
--   wild = { uiMap, ... }   zones of those continents without crossing data (walked as before)
--   crossings = { { id, a = { map, c, wx, wy, r }, b = { ... }, ab = caption a->b, ba = caption b->a, oneWay }, ... }
--   open = { zoneA, zoneB, oneWay (0/1), ... }   shared borders walkable anywhere
--   chains = { { id, name, open = "mouth"|"both", nodes = { { map, c, wx, wy, r, caption, back }, ... } }, ... } }
-- Calls merge; an id seen before is skipped.
function Nav.RegisterCrossings(d)
	if type(d) ~= "table" then return end
	for map, z in pairs(d.zones or {}) do
		if type(z) == "table" then zoneInfo[map] = z end
	end
	for _, map in ipairs(d.wild or {}) do wildZone[map] = true end
	local touched = {}
	local function node(e)
		touched[e.c] = true
		return { map = e.map, c = e.c, wx = e.wx, wy = e.wy, r = e.r or REACH }
	end
	for _, e in ipairs(d.crossings or {}) do
		if type(e) == "table" and e.a and e.b and not crossIds[e.id or e] then
			crossIds[e.id or e] = true
			local a, b = node(e.a), node(e.b)
			a.partner, b.partner, a.caption, b.caption = b, a, e.ab, e.ba
			a.id, b.id, a.side, b.side = e.id, e.id, "a", "b"
			b.noCross = e.oneWay and true or nil
			crossEnds[#crossEnds + 1] = a
			crossEnds[#crossEnds + 1] = b
		end
	end
	local open = d.open or {}
	for i = 1, #open - 2, 3 do
		local a, b = open[i], open[i + 1]
		openPair[a] = openPair[a] or {}
		openPair[a][b] = true
		if open[i + 2] ~= 1 then
			openPair[b] = openPair[b] or {}
			openPair[b][a] = true
		end
		local z = zoneInfo[a]
		if z then touched[z.c] = true end
	end
	for _, ch in ipairs(d.chains or {}) do
		if type(ch) == "table" and type(ch.nodes) == "table" and #ch.nodes >= 2 and not crossIds[ch.id or ch] then
			crossIds[ch.id or ch] = true
			local chain = { id = ch.id, name = ch.name, open = ch.open == "both" and "both" or "mouth", nodes = {} }
			for k, e in ipairs(ch.nodes) do
				local n = node(e)
				n.caption, n.back, n.chain, n.idx = e.caption, e.back, chain, k
				chain.nodes[k] = n
			end
			chains[#chains + 1] = chain
		end
	end
	if d.complete then
		for c in pairs(touched) do covered[c] = true end
	end
	pathZone, zoneVersion = {}, zoneVersion + 1
	Travel.version = Travel.version + 1
end

-- Continents walked through crossing data, and what is loaded: crossing ends, open pairs, chains.
function Travel.CrossingCounts()
	local list = {}
	for c in pairs(covered) do list[#list + 1] = c end
	table.sort(list)
	local pairsN = 0
	for a, to in pairs(openPair) do
		for b in pairs(to) do
			if a < b or not (openPair[b] and openPair[b][a]) then pairsN = pairsN + 1 end
		end
	end
	return list, #crossEnds / 2, pairsN, #chains
end

function Travel.Counts()
	return #taxiList, #transports, #inns, pathCount
end

