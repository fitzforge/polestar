	local C = ns.Compat
	return C and C.IsOnTaxi and C.IsOnTaxi() or false
end

-- A ghost walks: no flights, rides, portals, hearth or teleports.
local function isGhost()
	return UnitIsGhost ~= nil and UnitIsGhost("player") == true
end
Travel.IsGhost = isGhost

local function transitNow()
	local X = ns.Transit
	if X and X.Now then return X.Now() end
	return GetServerTime and GetServerTime() or 0
end

-- The timetables' waits for the planner (Nav/Transit.lua), counted from when
-- the player gets to the dock; nil without them (the average waits). A
-- timetable that raises or answers nonsense never breaks planning: that
-- ride falls back to its average wait (review P0-1).
local function departureFn()
	local X = ns.Transit
	if not (X and X.NextDeparture) then return nil end
	local now = transitNow()
	local next = X.NextDeparture
	return function(t, side, after)
		local ok, wait, ride = pcall(next, t.kind, t.id, now + after, side)
		if ok and type(wait) == "number" and type(ride) == "number" and wait >= 0 and ride >= 0
			and wait < huge and ride < huge then
			return wait, ride
		end
		return nil
	end
end

-- Class teleports this character can cast now or soon (Nav/Transit.lua), or nil.
local function teleportList()
	local X = ns.Transit
	if not (X and X.Teleports) then return nil end
	local ok, list = pcall(X.Teleports, transitNow())
	return ok and type(list) == "table" and list or nil
end

-- Each leg's rest: the seconds after it.
local function setRests()
	local rest = 0
	for k = #legs, 1, -1 do
		legs[k].rest = rest
		rest = rest + legs[k].seconds
	end
end

-- Later rides' timetable waits again, from when the player now reaches their
-- docks: a walk before them priced by its path arrives earlier or later than
-- the plan's straight estimate did. The current leg counts whole.
local function retime()
	local dep = departureFn()
	if not dep then return end
	local after = legs[ci] and legs[ci].seconds or 0
	for k = ci + 1, #legs do
		local leg = legs[k]
		if leg.transport and leg.kind ~= "portal" then
			local wait, ride = dep(leg.transport, leg.side, after)
			if wait then leg.seconds = floor(wait + ride + 0.5) end
		end
		after = after + leg.seconds
	end
end

-- Walk legs after the current one take the measure of their engine path once
-- Nav/Walk.lua has searched it (Walk.LegPath): yards along it, seconds at run
-- speed; the rides after them are timed again (retime). Hand-made walks, the
-- pieces of a split walk and the last walk to a target after a guide `goto`
-- (walked straight from the mouth) keep theirs. -> true when a leg changed.
local function pricePaths()
	local W = Nav.walk
	if not (legs and W and W.LegPath) then return false end
	local changed = false
	local gotoLast = W.FollowsGoto and W.FollowsGoto(Nav.GetTarget())
	for k = ci + 1, #legs do
		local leg = legs[k]
		if leg.kind == "walk" and leg.engine ~= "path" and not leg.handmade and not leg.parent and not (gotoLast and k == #legs) then
			local yd = W.LegPath(leg.from, leg.to)
			if yd then
				leg.yards, leg.seconds, leg.engine = floor(yd + 0.5), floor(yd / RUN_SPEED + 0.5), "path"
				changed = true
			end
		end
	end
	if changed then
		retime()
		setRests()
	end
	return changed
end

-- A plan from where the player stands to the target, or nil; and where from.
local function plan(target)
	-- Handed to Shortest Path Forever (Nav/Handoff.lua): it plans the way; no route here.
	if not (target and ns.Get("nav.travel") and not Nav.HandedOff() and #taxiList + #transports + #portals + #inns + pathCount + #crossEnds + #chains > 0) then return nil end
	local tc, twx, twy = Nav.GetTargetWorld()
	local C = ns.Compat
	local pc, px, py
	if C and C.GetPlayerWorldPosition then pc, px, py = C.GetPlayerWorldPosition() end
	if not (tc and pc) then return nil end
	refreshFaction()
	planSpeed = runSpeed()
	lastHearth = hearthReady()
	local ghost = isGhost()
	local inn, bindName
	if lastHearth and not ghost then inn, bindName = bindInn() end
	-- The walks to the target the walking engine measured, and the places it measures next (Nav/Walk.lua).
	local W = Nav.walk
	local places = W and W.Measure and {} or nil
	local route = Nav.PlanRoute({
		c = pc, wx = px, wy = py, map = playerMap(),
		target = { c = tc, wx = twx, wy = twy, label = target.label, map = target.map, x = target.x, y = target.y, f = target.f, kind = target.kind },
		faction = playerFaction,
		known = knownNodes(),
		-- Walk edges are priced unmounted: straight lines may cross water, and a
		-- mount's speed would make swimming a sea look faster than the boat.
		-- planSpeed (the live speed) only scales the ETA of the current walk.
		speed = RUN_SPEED,
		hearth = inn,
		hearthName = bindName,
		noHearth = skipped.hearth,
		skip = skipped,
		teleports = not ghost and teleportList() or nil,
		departure = departureFn(),
		walkOnly = ghost,
		walkCost = W and W.Measured and W.Measured(tc, twx, twy, ghost) or nil,
		places = places,
	})
	if places then W.Measure(tc, twx, twy, ghost, places) end
	return route, pc, px, py
end

function Travel.Replan()
	if onTaxi() then
		dirty = true
		return
	end
	local old = legs
	legs, ci, boarded, dirty, progressYards, legSince, remeasureOwed = nil, 1, false, false, nil, GetTime(), false
	local target = Nav.GetTarget()
	if skipFor ~= target then
		skipFor = nil
		skipped = { hearth = false, spells = {}, transports = {}, taxi = {}, cross = {} }
	end
	local pc, px, py
	legs, pc, px, py = plan(target)
	if pc then planAt, planC, planX, planY = GetTime(), pc, px, py end
	pricePaths()
	Travel.version = Travel.version + 1
	if old or legs then ns.Fire("ROUTE_CHANGED", legs) end
end

-- Legs of the current route (read-only) and the current leg's index.
function Nav.GetRoute()
	return legs, legs and ci or nil
end

---------------------------------------------------------------------------
-- Estimates for other modules (the Engine picks the nearest trainer, vendor
-- or inn with it; Polestar.Nav.API.Estimate). Same costs as the live route:
-- known flights, transports, and the Hearthstone when it is ready and the
-- trip starts at the player. Never touches the active route or fires
-- messages. Each answer the cache lacks is a full plan (up to 40 ms), so:
-- cached per (start cell, destination) for a few seconds (a burst of ~10
-- calls on a step change plans each candidate once), the oldest entry
-- evicted when 64 are held. A `budgeted` call (only the public API's, for
-- other addons) starts no new plan once this frame has spent ESTIMATE_MS
-- planning estimates and answers nil, "busy" until the next frame; the plan
-- it does start may still run to its 40 ms cap (security L6). Polestar's own
-- callers are never refused: a ranking compares full plans only, bounded by
-- its own caps and the cache (second review P2).
---------------------------------------------------------------------------

local CACHE_SECONDS, CACHE_CELL, CACHE_MAX = 5, 25, 64
local ESTIMATE_MS = 25
local estimates, estimateOrder = {}, {}
local budgetFrame, budgetSpent = nil, 0

local function pointWorld(p)
	if type(p) ~= "table" then return nil end
	if p.c and p.wx and p.wy then return p.c, p.wx, p.wy end
	local C = ns.Compat
	if not (C and C.MapToWorld and p.map and p.x and p.y) then return nil end
	return C.MapToWorld(p.map, p.x, p.y, p.f)
end

-- from, to = { map, x, y, f } (from = nil: the player); budgeted = true: the public API's call
--   -> seconds | nil (unknown position or unreachable) | nil, "busy" (budgeted, this frame's budget is spent)
function Nav.EstimateTravel(from, to, budgeted)
	local tc, twx, twy = pointWorld(to)
	if not tc then return nil end
	local fc, fwx, fwy
	if from == nil then
		local C = ns.Compat
		if C and C.GetPlayerWorldPosition then fc, fwx, fwy = C.GetPlayerWorldPosition() end
	else
		fc, fwx, fwy = pointWorld(from)
	end
	if not fc then return nil end
	local key = format("%d:%d:%d>%d:%.1f:%.1f:%d", fc, floor(fwx / CACHE_CELL), floor(fwy / CACHE_CELL),
		tc, twx, twy, from == nil and 1 or 0)
	local now = GetTime()
	local hit = estimates[key]
	if hit and now - hit.at < CACHE_SECONDS then return hit.seconds end
	if budgetFrame ~= now then budgetFrame, budgetSpent = now, 0 end
	if budgeted and budgetSpent >= ESTIMATE_MS then return nil, "busy" end
	local clock = debugprofilestop
	local t0 = clock and clock()
	refreshFaction()
	local ghost = from == nil and isGhost()
	local inn, bindName
	if from == nil and not ghost and hearthReady() then inn, bindName = bindInn() end
	local plan = Nav.PlanRoute({
		c = fc, wx = fwx, wy = fwy, map = from == nil and playerMap() or from.map,
		target = { c = tc, wx = twx, wy = twy, map = to.map },
		faction = playerFaction,
		known = knownNodes(),
		speed = RUN_SPEED,
		hearth = inn,
		hearthName = bindName,
		teleports = from == nil and not ghost and teleportList() or nil,
		departure = departureFn(),
		walkOnly = ghost,
	})
	if t0 then budgetSpent = budgetSpent + (clock() - t0) end
	local seconds
	if plan then seconds = plan[1] and (plan[1].seconds + plan[1].rest) or 0 end
	if not hit then
		if #estimateOrder >= CACHE_MAX then estimates[table.remove(estimateOrder, 1)] = nil end
		estimateOrder[#estimateOrder + 1] = key
	end
	estimates[key] = { at = now, seconds = seconds }
	return seconds
end

-- A route worth following: more than one leg. A lone walk is the direct arrow.
