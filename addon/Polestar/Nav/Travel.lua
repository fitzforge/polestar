-- Planner (pure: everything it needs comes in `p`)
--
-- p = { c, wx, wy, map,                   player, world yards; map = the player's uiMap (its zone)
--       target = { c, wx, wy, label, map, x, y, f },
--       faction = 1 Alliance | 2 Horde | 0 other,
--       known = { [taxiNodeID] = true },
--       speed = yd/s,
--       hearth = inn point or nil, hearthName = bind location, noHearth = true: leave it out,
--       skip = { spells = { [id] = true }, transports = { [t] = true }, taxi = { [nodeID] = true },
--         cross = { [crossing end] = true } }: left out for this target (skipped legs;
--         a skipped crossing end lets a start nearer the partner than the ends
--         are to each other walk straight to the partner),
--       teleports = { { spell, name, to = point, cast, ready }, ... } or nil,
--       departure = function(transport, side, after) -> wait, ride (seconds, from
--         `after` seconds into the trip) or nil: the transports' average waits,
--       walkOnly = true: walking only (a ghost),
--       walkCost = function(c, wx, wy, start) -> running yards | nil: the
--         walking engine's measure of the walk from that place (the player when
--         start) to the target (Nav/Walk.lua Walk.Measured); nil keeps its
--         straight estimate,
--       places = {}: filled with the places a walk to the target can start
--         from on its continent { wx, wy, start }, for Walk.Measure }
-- -> legs or nil, reason
-- leg = { kind = "walk"|"fly"|"boat"|"zeppelin"|"tram"|"portal"|"hearth"|"teleport",
--         from = point, to = point, label, seconds, rest,   rest = seconds after this leg
--         radius = arrival yards at `to` (walk legs to a waypoint), waypoint = true
--         when `to` is a crossing or chain node, handmade = true on a walk the
--         crossing data lays out (never a walking-engine path), crossing, side =
--         the crossing id and the end walked from,
--         stops = { taxi node, ... } (fly: every node hopped, ends included),
--         transport, side = the transport or portal and the end boarded at ("a"|"b"),
--         item = the Hearthstone (hearth), spell = spell ID (teleport),
--         yards = straight hops (a walk x1.25), step = "crossing"|"chain"|"goto",
--         engine = "cost" (a walk priced by walkCost) | "path" (by its engine path) }
-- Travel.SplitWalk later adds walk pieces (step and choke = { kind, name },
-- parent, seg, tail) and lift rides (kind "lift", lift, side), or measures an
-- unsplit walk along the path (straightYards, straightSeconds: the estimate here);
-- Travel.PricePaths gives every later walk its searched path's measure.
-- seconds are real travel time; the search orders by a cost that adds
-- preferences (the Hearthstone's margin) on top.
---------------------------------------------------------------------------

local function allowed(mask, faction)
	return mask == 3 or (faction ~= 0 and mask == faction)
end

local function yards(c1, x1, y1, c2, x2, y2)
	if c1 ~= c2 then return huge end
	local dx, dy = x2 - x1, y2 - y1
	return sqrt(dx * dx + dy * dy)
end

-- The zone a point walks in on a continent with crossing data: its own map
-- when that is a zone the data knows, nil for a zone without crossing data
-- (walked as before), else the smallest known zone frame holding the point.
local function zoneOf(map, c, wx, wy)
	if map then
		local z = zoneInfo[map]
		if z and z.c == c then return map end
		if wildZone[map] then return nil end
	end
	local best, area
	for m, z in pairs(zoneInfo) do
		if z.c == c then
			local h, w = z.bottom - z.top, z.right - z.left
			if h ~= 0 and w ~= 0 then
				local fy, fx = (wx - z.top) / h, (wy - z.left) / w
				if fx >= 0 and fx <= 1 and fy >= 0 and fy <= 1 then
					local a = h * w
					if a < 0 then a = -a end
					if not area or a < area or (a == area and m < best) then best, area = m, a end
				end
			end
		end
	end
	return best
end
Travel.ZoneOf = zoneOf

local function pathZoneOf(i)
	local z = pathZone[i]
	if z == nil then
		z = zoneOf(pathMap[i], pathC[i], pathX[i], pathY[i]) or false
		pathZone[i] = z
	end
	return z or nil
end

-- May a straight walk go from zone a into zone b? (nil: no crossing data there)
local function zonesWalk(a, b)
	if a == nil or b == nil or a == b then return true end
	local o = openPair[a]
	return o ~= nil and o[b] == true
end

local function zoneName(map)
	local C = ns.Compat
	local name = C and C.GetMapName and C.GetMapName(map)
	if name then return name end
	local z = zoneInfo[map]
	return z and z.name or tostring(map)
end

-- The chain node past a mouth that a point is inside (within max(CAPTURE x radius, CAPTURE_MIN)), or nil.
local function insideChain(c, wx, wy)
	local best, bestD
	for _, ch in ipairs(chains) do
		local nodes = ch.nodes
		local last = ch.open == "both" and #nodes - 1 or #nodes
		for k = 2, last do
			local nd = nodes[k]
			if nd.c == c then
				local d = yards(c, wx, wy, nd.c, nd.wx, nd.wy)
				local cap = nd.r * CAPTURE
				if cap < CAPTURE_MIN then cap = CAPTURE_MIN end
				if d <= cap and (not bestD or d < bestD) then best, bestD = nd, d end
			end
		end
	end
	return best
end

