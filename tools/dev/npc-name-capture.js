'use strict';

// Prepare a batch of missing NPC names, then convert the addon's SavedVariables
// to Forge's observed-name format. All file selection and installation is explicit.
const fs = require('node:fs');
const path = require('node:path');
const { createHash } = require('node:crypto');
const { DATA, ROOT } = require('../lib/paths');
const { LOCALE_CODES, checkLocale } = require('../lib/i18n/locales');

const NPCS = path.join(DATA, 'codex', 'npcs.json');
const ID = /^[1-9][0-9]{0,9}$/;
const BUILD = /^[0-9]+(?:\.[0-9]+){3}$/;
const PLACEHOLDER = /\[(?:PH|TMP|UNUSED|NOT USED|DEPRECATED|NYI|DNT|INUTILIS[ÉE]|P[ÉE]RIM[ÉE]|OBSOLETO|VERALTET)\]|<(?:NYI|TXT|UNUSED|PH|TMP|DEPRECATED)>|\((?:PH|TMP|NYI|DNT|UNUSED|DEPRECATED|TEST|JEFFTEST|OLD[0-9]*|тест|시험용|测试|測試)\)|^zzOLD|\b(?:UNUSED|DEPRECATED)\b/iu;

function usable(name) {
	return typeof name === 'string' && name === name.trim() && name.length > 0 &&
		!/[\p{Cc}|]/u.test(name) && !PLACEHOLDER.test(name);
}

function captureTargets(codex, pack, observed) {
	const known = new Set(observed.names.filter(record => record.token.startsWith('npc:'))
		.map(record => Number(record.token.slice(4))));
	for (const [, chunk] of pack.matchAll(/^R\("npc", \d+, \d+, \[\[([\s\S]*?)\]\]\)/gm)) {
		for (const [, id] of chunk.matchAll(/^(\d+)\t/gm)) known.add(Number(id));
	}
	return new Map(Object.entries(codex)
		.filter(([id, npc]) => ID.test(id) && !known.has(Number(id)) && usable(npc?.name))
		.map(([id, npc]) => [Number(id), npc.name])
		.sort(([a], [b]) => a - b));
}

function targetsLua(locale, targets) {
	const rows = [...targets].map(([id, name]) => '\t\t{ ' + id + ', ' + JSON.stringify(name) + ' },');
	return [
		'-- Generated by npc-name-capture.js for a contributor capture run.',
		'PolestarNpcNameCaptureTargets = {',
		'\tlocale = ' + JSON.stringify(locale) + ',',
		'\tnpcs = {',
		...rows,
		'\t},',
		'}',
		'',
	].join('\n');
}

function parseCapture(text) {
	// Parse the restricted table the client writes, without running the file as Lua.
	const table = text.trim().match(/^PolestarNpcNameCaptureDB\s*=\s*\{([\s\S]*)\}$/);
	const invalid = () => new Error('Invalid PolestarNpcNameCapture SavedVariables file');
	if (!table) throw invalid();
	const fields = new Map();
	const names = new Map();
	let inNames = false;
	for (const line of table[1].split(/\r?\n/).map(line => line.trim()).filter(Boolean)) {
		if (inNames) {
			if (line === '},') {
				inNames = false;
				continue;
			}
			const row = line.match(/^\[([1-9][0-9]{0,9})\]\s*=\s*("(?:[^"\\]|\\["\\])*"),?$/);
			if (!row) throw invalid();
			const id = Number(row[1]);
			if (names.has(id)) throw new Error('SavedVariables contains duplicate NPC ' + id);
			names.set(id, JSON.parse(row[2]));
			continue;
		}
		const pair = line.match(/^\["(locale|build|names)"\]\s*=\s*(\{|"[A-Za-z0-9.]+"),?$/);
		if (!pair || fields.has(pair[1]) || (pair[1] === 'names') !== (pair[2] === '{')) throw invalid();
		inNames = pair[1] === 'names';
		fields.set(pair[1], inNames ? names : JSON.parse(pair[2]));
	}
	const locale = fields.get('locale');
	const build = fields.get('build');
	if (inNames || fields.size !== 3 || !LOCALE_CODES.includes(locale) || !BUILD.test(build)) throw invalid();
	return { locale, build, names };
}

function exportNames(capture, targets, existing, sha256, ref) {
	if (existing.locale !== capture.locale) throw new Error('Observed-name locale does not match the capture');
	if (!Number.isSafeInteger(ref) || ref < 1) throw new Error('Use a positive issue or PR number for ref');
	const added = [];
	const unresolved = [];
	const english = [];
	for (const [id, original] of targets) {
		const name = capture.names.get(id);
		if (name === original) {
			english.push(id);
		} else if (!usable(name)) {
			unresolved.push(id);
		} else {
			added.push({ token: 'npc:' + id, name, source: 'client-learning', build: capture.build, sha256, ref });
		}
	}
	const names = [...existing.names, ...added].sort((a, b) => a.token.localeCompare(b.token, 'en', { numeric: true }));
	return { document: { ...existing, names }, added: added.length, unresolved, english };
}

function readOptional(file) {
	return fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : '';
}

function checkoutInput(file) {
	const resolved = path.resolve(file);
	const canonical = fs.existsSync(resolved) ? fs.realpathSync(resolved) : resolved;
	const relative = path.relative(ROOT, canonical);
	if (relative === '..' || relative.startsWith('..' + path.sep) || path.isAbsolute(relative)) {
		throw new Error('Place input files inside the checkout, for example under data/local/.');
	}
	return canonical;
}

function loadTargets(locale, codexFile) {
	codexFile = checkoutInput(codexFile);
	checkLocale(locale);
	const pack = readOptional(path.join(ROOT, 'addon', 'Polestar_' + locale, 'Names.lua'));
	const observed = readOptional(path.join(ROOT, 'data', 'i18n', 'names-observed', locale + '.json'));
	const existing = observed ? JSON.parse(observed) : { schema: 1, locale, names: [] };
	if (existing.schema !== 1 || existing.locale !== locale || !Array.isArray(existing.names)) {
		throw new Error('Observed-name document does not match ' + locale);
	}
	if (!fs.existsSync(codexFile)) throw new Error('No NPC Codex at ' + codexFile + '. Run forge data codex or pass an NPC Codex file.');
	const codex = JSON.parse(fs.readFileSync(codexFile, 'utf8'));
	return { targets: captureTargets(codex, pack, existing), existing };
}

function formatDocument(document) {
	// Keep the same one-record-per-line layout as the checked-in name files.
	const { names, ...header } = document;
	const records = names.map(record => '\t\t' + JSON.stringify(record).replace(/"(?:[^"\\]|\\.)*"|[:,]/g,
		part => part === ':' || part === ',' ? part + ' ' : part));
	return JSON.stringify(header, null, '\t').slice(0, -2) + ',\n\t"names": [\n' + records.join(',\n') + '\n\t]\n}\n';
}

function main(args) {
	if (args[0] === 'targets' && (args.length === 2 || args.length === 3)) {
		const [, locale, codexFile = NPCS] = args;
		const { targets } = loadTargets(locale, codexFile);
		console.error('NPC targets for ' + locale + ': ' + targets.size);
		process.stdout.write(targetsLua(locale, targets));
		return;
	}
	if (args[0] === 'export' && (args.length === 3 || args.length === 4)) {
		const [, savedFile, ref, codexFile = NPCS] = args;
		const saved = fs.readFileSync(checkoutInput(savedFile));
		const capture = parseCapture(saved.toString('utf8'));
		const { existing, targets } = loadTargets(capture.locale, codexFile);
		const hash = createHash('sha256').update(saved).digest('hex');
		const result = exportNames(capture, targets, existing, hash, Number(ref));
		console.error('Added ' + result.added + ' NPC names for ' + capture.locale + '.');
		console.error('English fallback (' + result.english.length + '): ' + result.english.join(', '));
		console.error('Unresolved (' + result.unresolved.length + '): ' + result.unresolved.join(', '));
		process.stdout.write(formatDocument(result.document));
		return;
	}
	throw new Error('Usage: node tools/dev/npc-name-capture.js targets <locale> [npcs.json]\n' +
		'       node tools/dev/npc-name-capture.js export <SavedVariables.lua> <issue-or-pr> [npcs.json]');
}

if (require.main === module) {
	try {
		main(process.argv.slice(2));
	} catch (error) {
		console.error(error.message);
		process.exitCode = 1;
	}
}

module.exports = { captureTargets, exportNames, parseCapture, targetsLua };
