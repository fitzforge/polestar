'use strict';
// The guide pack contract shared by the compiler, lint and the pack commands.

const { header } = require('../generated');

// The pack format the compiler writes, and the first Polestar version that
// reads each format (written into the TOC as X-Polestar-Needs). Format 2
// adds `group` (docs/PACK_FORMAT.md, "Format 2"); format 4 adds a step's
// `when`, `label` and `along`, a level goal's `frac` and a `next` option's
// `when` (`nextWhen`); format 5 adds the `money` and `task` goals, the
// `money`, `dungeon`, `upgrade`, `done`, `skill`, `cooldown` and `group` when predicates and a step's `skipto`; a pack is written in the first format its guides
// need (formatFor): a pack without any stays readable by Polestar 0.2.5.
const FORMAT = 3;
const WHEN_FORMAT = 4;
const MONEY_TASK_FORMAT = 5;
const NEEDS = { 1: '0.1.0', 2: '0.2.4', 3: '0.2.5', 4: '0.2.6', 5: '0.3.0' };

// A step with `label` or `along` (an older Polestar would stop at an along step).
const usesAlong = (s) => s.label !== undefined || s.along !== undefined;

// A `level` goal with `frac` (a point inside the level) needs format 4:
// an older Polestar would count it done at the start of the level.
const usesLevelFrac = (g) => (g.steps || []).some((s) => (s.goals || []).some((goal) => goal.t === 'level' && goal.frac));

// The `money` and `task` goals, the `money`, `dungeon`, `upgrade`, `done`,
// `skill`, `cooldown` and `group` when predicates (on a step or a `next` option) and a
// step's `skipto` need format 5: a 0.2.6 client would accept a format-4 pack
// but refuse these with "unknown verb" or "bad when" rather than "needs
// Polestar 0.3.0", and would never take a `skipto` jump.
const MONEY_TASK_VERBS = new Set(['money', 'task']);
const FORMAT5_WHEN = new Set(['money', 'dungeon', 'upgrade', 'done', 'skill', 'cooldown', 'group']);
const needs5 = (list) => (list || []).some((p) => FORMAT5_WHEN.has(p.k));
const usesMoneyTask = (g) => (g.steps || []).some((s) =>
	(s.goals || []).some((goal) => MONEY_TASK_VERBS.has(goal.t)) || needs5(s.when) || (Array.isArray(s.skipto) && s.skipto.length)) ||
	Object.values(g.nextWhen || {}).some(needs5);

// The format a pack's compiled guides need: MONEY_TASK_FORMAT when a guide
// uses money/task goals, a money, dungeon, upgrade, done, skill, cooldown or group when predicate or a
// `skipto`, WHEN_FORMAT when a step
// has `when`, `label` or `along`, a level goal has `frac`, or a `next`
// option has `when` (`nextWhen`), else FORMAT.
function formatFor(guides) {
	if ((guides || []).some(usesMoneyTask)) return MONEY_TASK_FORMAT;
	const uses = (guides || []).some((g) => (g.steps || []).some((s) => (Array.isArray(s.when) && s.when.length) || usesAlong(s)));
	if (uses || (guides || []).some(usesLevelFrac)) return WHEN_FORMAT;
	const nextWhen = (guides || []).some((g) => g.nextWhen && Object.keys(g.nextWhen).length);
	if (nextWhen) return WHEN_FORMAT;
	return FORMAT;
}

const PACK_ID_RE = /^[a-z0-9][a-z0-9-]{1,31}$/;
const FOLDER_RE = /^[A-Za-z0-9_-]{1,64}$/;
const RESERVED_IDS = new Set(['guides', 'forever', 'lookup', 'draft', 'polestar', 'imported']);

// A folder we generated says so in its TOC (and the old layout in Pack.xml):
// only such a folder is ever replaced by compile, install or dev.
const GENERATED_MARKER = 'Generated by `node tools/polestar.js compile`';
// The TOC's comment line carrying the marker.
const TOC_MARKER = header('guide', 'compile', 'pack.json and the .guide files');
// What a community addon's TOC Title starts with, so the AddOns list reads it
// as one (Core/Guides.lua drops it again for the Community guides page).
// Community addons built before the rename carry the legacy prefix.
const TOC_TITLE_PREFIX = 'Polestar Community: ';
const LEGACY_TOC_TITLE_PREFIX = 'Polestar Pack: ';

// Our pack `guides` owns forever/ and draft/; every other pack owns `<id>/`.
function ownsGuideId(packId, guideId) {
	const id = String(guideId);
	if (packId === 'guides') return id.startsWith('forever/') || id.startsWith('draft/');
	return id.startsWith(`${packId}/`);
}

// "Joe's Routes" -> "PolestarPack_JoesRoutes"; a title with no letters or
// digits falls back to the id ("joe-routes" -> "PolestarPack_JoeRoutes").
function defaultFolder(title, id) {
	const camel = (s) =>
		String(s || '')
			.replace(/['\u2019]/g, '')
			.split(/[^A-Za-z0-9]+/)
			.filter(Boolean)
			.map((w) => w[0].toUpperCase() + w.slice(1))
			.join('');
	const name = camel(title) || camel(id);
	return `PolestarPack_${name}`.slice(0, 64);
}

// The line `new` writes into LICENSE for a licence it has no text for; lint
// warns while the pack's LICENSE still holds it.
const LICENSE_PLACEHOLDER = 'replace this line with the full text of that licence';

function placeholderLicense(license) {
	return `Licensed under ${license}: ${LICENSE_PLACEHOLDER}.\n`;
}

module.exports = { FORMAT, WHEN_FORMAT, MONEY_TASK_FORMAT, NEEDS, formatFor, PACK_ID_RE, FOLDER_RE, RESERVED_IDS, GENERATED_MARKER, TOC_MARKER, TOC_TITLE_PREFIX, LEGACY_TOC_TITLE_PREFIX, LICENSE_PLACEHOLDER, ownsGuideId, defaultFolder, placeholderLicense };
