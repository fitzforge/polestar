'use strict';
// Dungeon advice for the addon (docs/SIMULATION.md, "Dungeon advice"): what
// each dungeon is worth to a party of 1 to 5 on the searched route, from the
// `sim weave --party N --draws K` results in data/sim/weave/, written to
// addon/Polestar/Dungeons/AdviceData.lua. The guide window offers a dungeon
// that pays for the player's party when they reach the level the weave runs
// it at (Dungeons/Advice.lua).
//
// Per faction and party size, over the races with a weave (the faction's
// starts): the minutes a dungeon saves to 60 at the mean parameters (negative:
// it costs time; the mean over the draws is pulled by a few draws where the
// party's run goes badly), the share of draws where it saves time (without
// draws: 1 or 0) and the level it is run at (the median).

const fs = require('node:fs');
const path = require('node:path');

const SIZES = [1, 2, 3, 4, 5];
// <faction>-<race>-<class>-party<N>.json: plain weaves only (no other tag).
const FILE_RE = /^(alliance|horde)-([a-z]+)-([a-z]+)-party([1-5])\.json$/;

const median = (xs) => {
	const s = [...xs].sort((a, b) => a - b);
	const m = s.length >> 1;
	return s.length % 2 ? s[m] : (s[m - 1] + s[m]) / 2;
};
const mean = (xs) => xs.reduce((a, b) => a + b, 0) / xs.length;

// weaves: [{ faction, partySize, race, dungeons, uncertainty }]; keyOf(name)
// -> the dungeon's key (dungeons.json) or null.
// -> { [faction]: { [size]: [{ key, name, level, minutes, pays, races }] } },
// most minutes saved first; and the names no key was found for.
function advise(weaves, keyOf) {
	const out = {};
	const unknown = new Set();
	const groups = new Map();
	for (const w of weaves) {
		const k = `${w.faction}|${w.partySize}`;
		if (!groups.has(k)) groups.set(k, []);
		groups.get(k).push(w);
	}
	for (const [k, list] of groups) {
		const [faction, size] = k.split('|');
		const rows = new Map();
		for (const w of list) {
			const draws = new Map((w.uncertainty || []).map((u) => [u.name, u]));
			for (const d of w.dungeons) {
				if (d.delta == null || d.level == null) continue; // not run on this route
				const key = keyOf(d.name);
				if (!key) {
					unknown.add(d.name);
					continue;
				}
				const u = draws.get(d.name);
				if (!rows.has(key)) rows.set(key, { key, name: d.name, levels: [], minutes: [], pays: [] });
				const r = rows.get(key);
				r.levels.push(d.level);
				r.minutes.push(-d.delta / 60);
				r.pays.push(u ? u.saves : d.delta < 0 ? 1 : 0);
			}
		}
		const list2 = [...rows.values()].map((r) => ({
			key: r.key,
			name: r.name,
			level: Math.round(median(r.levels) * 10) / 10,
			minutes: Math.round(mean(r.minutes)),
			pays: Math.round(mean(r.pays) * 100) / 100,
			races: r.levels.length,
		}));
		list2.sort((a, b) => b.minutes - a.minutes || a.key.localeCompare(b.key));
		if (!out[faction]) out[faction] = {};
		out[faction][Number(size)] = list2;
	}
	return { advice: out, unknown: [...unknown] };
}

// The weaves in simDir/weave -> the list advise() reads.
function readWeaves(simDir) {
	const dir = path.join(simDir, 'weave');
	if (!fs.existsSync(dir)) return [];
	const out = [];
	for (const f of fs.readdirSync(dir).sort()) {
		const m = FILE_RE.exec(f);
		if (!m) continue;
		const w = JSON.parse(fs.readFileSync(path.join(dir, f), 'utf8'));
		out.push({ faction: w.faction, partySize: w.partySize || Number(m[4]), race: w.race, dungeons: w.dungeons || [], uncertainty: w.uncertainty || null, file: f });
	}
	return out;
}

const luaStr = (s) => JSON.stringify(s);

function adviceLua(advice, sources) {
	const lines = [
		'-- Generated by `node tools/polestar.js sim advice` from data/sim/weave/. Do not edit: rebuild with that command.',
		'-- What each dungeon is worth on the simulator\'s searched route, per faction and party size',
		'-- (docs/SIMULATION.md, "Dungeon advice"): the level it is run at, the minutes it saves to 60',
		'-- (negative: it costs time) and the share of parameter draws where it saves time.',
		`-- Weaves: ${sources.join(', ')}.`,
		'',
		'local ADDON, ns = ...',
		'local D = ns.Dungeons',
		'if not (D and D.RegisterAdvice) then return end',
		'',
		'D.RegisterAdvice({',
		'\t-- [faction] = { [party size] = { { key, level, minutes, pays }, ... } }, most minutes first',
	];
	for (const faction of Object.keys(advice).sort()) {
		lines.push(`\t${faction} = {`);
		for (const size of SIZES) {
			const rows = advice[faction][size];
			if (!rows) continue;
			lines.push(`\t\t[${size}] = {`);
			for (const r of rows) lines.push(`\t\t\t{ ${luaStr(r.key)}, ${r.level}, ${r.minutes}, ${r.pays} }, -- ${r.name}`);
			lines.push('\t\t},');
		}
		lines.push('\t},');
	}
	lines.push('})', '');
	return lines.join('\n');
}

function command(args, o) {
	const { ROOT } = require('../paths');
	const simDir = o.simDir || path.join(ROOT, 'data', 'sim');
	const dataDir = o.dataDir || path.join(ROOT, 'data', 'forever');
	const dungeons = JSON.parse(fs.readFileSync(path.join(dataDir, 'dungeons.json'), 'utf8')).dungeons;
	const byName = new Map(dungeons.map((d) => [d.name, d.key]));
	const weaves = readWeaves(simDir);
	if (!weaves.length) {
		console.error('sim advice: no weaves in data/sim/weave/: run `sim weave --faction F --race R --party N --draws K` first');
		return 1;
	}
	const { advice, unknown } = advise(weaves, (name) => byName.get(name) || null);
	for (const n of unknown) console.error(`sim advice: no dungeon named "${n}" in dungeons.json; left out`);
	const out = path.resolve(args.lua || path.join(ROOT, 'addon', 'Polestar', 'Dungeons', 'AdviceData.lua'));
	fs.writeFileSync(out, adviceLua(advice, weaves.map((w) => w.file)));
	for (const faction of Object.keys(advice).sort()) {
		for (const size of SIZES) {
			const rows = (advice[faction][size] || []).filter((r) => r.minutes > 0 && r.pays >= 0.5);
			console.log(`${faction}, party of ${size}: ${rows.map((r) => `${r.name} ${r.minutes} min (${Math.round(r.pays * 100)}%)`).join(', ') || 'no dungeon pays'}`);
		}
	}
	console.log(`wrote ${path.relative(process.cwd(), out)}`);
	return 0;
}

module.exports = { advise, readWeaves, adviceLua, command };
