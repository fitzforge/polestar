'use strict';
// The spells a class trainer teaches, per class, from the Forever client's
// own tables (wago.tools): SkillLineAbility puts a spell on a class skill
// line (SkillLine CategoryID 7 with flag 1024: the specialisations, Frost or
// Affliction; not Engraving, Runes or a pet's line) for a class mask, learned at a trainer
// (AcquireMethod 0), and for a racial one a race mask; the rank it replaces
// is the class's spell of the same name learned before it (this client leaves
// SupercedesSpell empty); SpellLevels (DifficultyID 0) gives the level it is
// learned at (SpellLevel; BaseLevel is 0 on some). A spell with no level
// (talents, effects) is left out. Home's class training card lists the ones
// at or under the character's level it does not know yet.
//
//   buildClassSpells({ SkillLineAbility, SkillLine, SpellLevels, SpellName })
//     -> { CLASS: [{ spell, level, prev, races }, ...] } in level, then id order
//   emitClassSpells(byClass, build) -> Lua text (Core/ClassSpells.lua)

const { CLASSES } = require('../game/races');

const CLASS_CATEGORY = '7';
const SPEC_LINE = 1024; // SkillLine Flags bit of the class specialisations
const TRAINED = '0';

function buildClassSpells({ SkillLineAbility, SkillLine, SpellLevels, SpellName }) {
	const classLines = new Set(SkillLine.filter((r) => r.CategoryID === CLASS_CATEGORY && (Number(r.Flags) & SPEC_LINE)).map((r) => r.ID));
	const levels = new Map();
	for (const r of SpellLevels) {
		if (r.DifficultyID !== '0') continue;
		const lv = Math.max(Number(r.SpellLevel) || 0, Number(r.BaseLevel) || 0);
		if (lv > 0) levels.set(r.SpellID, lv);
	}
	const names = new Map(SpellName.filter((r) => r.Name_lang).map((r) => [r.ID, r.Name_lang]));
	const out = {};
	for (const c of Object.values(CLASSES)) {
		const seen = new Map();
		for (const r of SkillLineAbility) {
			if (!(Number(r.ClassMask) & c.bit) || !classLines.has(r.SkillLine) || r.AcquireMethod !== TRAINED) continue;
			const level = levels.get(r.Spell);
			if (!level || !names.has(r.Spell) || seen.has(r.Spell)) continue;
			const races = Number(r.RaceMasks_0) || null;
			seen.set(r.Spell, { spell: Number(r.Spell), level, prev: Number(r.SupercedesSpell) || null, races, name: names.get(r.Spell) });
		}
		const list = [...seen.values()].sort((a, b) => a.level - b.level || a.spell - b.spell);
		// Ranks: each spell replaces the last one of its name before it.
		const last = new Map();
		for (const s of list) {
			if (!s.prev && last.has(s.name)) s.prev = last.get(s.name);
			last.set(s.name, s.spell);
			delete s.name;
		}
		out[c.file] = list;
	}
	return out;
}

function emitClassSpells(byClass, build) {
	const lines = [
		`-- Generated by \`node tools/polestar.js trainers spells\` from the Forever client's SkillLineAbility, SkillLine, SpellLevels and SpellName tables (build ${build}, wago.tools). Do not edit: rebuild with that command.`,
		'-- Per class: { spell, level learned, rank it replaces or 0, race mask or 0 }, in level order.',
		'local ADDON, ns = ...',
		'',
		'ns.RegisterClassSpells({',
	];
	for (const cls of Object.keys(byClass).sort()) {
		const list = byClass[cls];
		if (!list.length) continue;
		lines.push(`\t${cls} = {`);
		for (const s of list) lines.push(`\t\t{ ${s.spell}, ${s.level}, ${s.prev || 0}, ${s.races || 0} },`);
		lines.push('\t},');
	}
	lines.push('})', '');
	return lines.join('\n');
}

module.exports = { buildClassSpells, emitClassSpells };
