#!/usr/bin/env node
'use strict';
// Writes addon/Polestar/Core/LegacySteps.lua: for each leveling guide, the
// steps earlier releases had that the current guides no longer have, as the
// Engine names a step (Own.stepParts: "turnin:783,accept:7"), keyed by the
// hash a character's save stores for it (CharState().stepKeys, Own.hash).
// An update that changes a step loses the check-offs, skips and saved view the
// save holds for it unless the Engine knows that step's goals; with these it
// carries them to the step of the new guide that has the same goal (Own.remap,
// #1353 upgrade). Run it at a release whose leveling guides changed, with the
// guide sources of each earlier release players may update from:
//
//   git archive v0.3.5 guides | tar -x -C /tmp/v035
//   node tools/legacy-steps.js --old /tmp/v034/guides --old /tmp/v035/guides
//
// Needs reference data (data/forever, or --data). Writes nothing else.

const fs = require('node:fs');
const path = require('node:path');
const { findGuideFiles, compileSources } = require('./lib/dsl/project');
const { loadData } = require('./lib/dsl/data');
const { Diagnostics } = require('./lib/dsl/diag');
const { ROOT, DATA } = require('./lib/paths');

const args = process.argv.slice(2);
const olds = [];
let dataDir = DATA;
let out = path.join(ROOT, 'addon/Polestar/Core/LegacySteps.lua');
let current = path.join(ROOT, 'guides');
for (let i = 0; i < args.length; i++) {
	if (args[i] === '--old') olds.push(args[++i]);
	else if (args[i] === '--data') dataDir = args[++i];
	else if (args[i] === '--out') out = args[++i];
	else if (args[i] === '--current') current = args[++i];
	else {
		console.error(`unknown option ${args[i]}`);
		process.exit(2);
	}
}
if (!olds.length) {
	console.error('usage: node tools/legacy-steps.js --old <guides dir> [--old <dir> ...] [--data <dir>] [--out <file>]');
	process.exit(2);
}

const data = loadData(dataDir);
const FACTIONS = ['Alliance', 'Horde'];

function leveling(dir) {
	const files = findGuideFiles(dir).filter((f) => /^forever\/(horde|alliance)\//.test(f));
	const sources = files.map((rel) => ({ source: rel, file: path.join(dir, rel), text: fs.readFileSync(path.join(dir, rel), 'utf8') }));
	const { guides } = compileSources(sources, data, new Diagnostics(), {});
	return guides.filter((g) => (g.category == null || g.category === 'Leveling') && FACTIONS.includes(g.faction));
}

// Lua's tostring of a goal's value, and `or`: only nil and false are false.
const luaStr = (v) => (typeof v === 'number' ? (Number.isInteger(v) ? String(v) : String(v)) : String(v));
const ID_KEYS = ['quest', 'npc', 'item', 'spell', 'object', 'faction', 'achievement', 'level', 'location', 'map'];
function part(step) {
	return step.goals
		.map((g) => {
			let id = '';
			for (const k of ID_KEYS) {
				if (g[k] != null && g[k] !== false) {
					id = luaStr(g[k]);
					break;
				}
			}
			return `${g.t}:${id}`;
		})
		.join(',');
}
// Own.hash: djb2 over the bytes, mod 2^32.
function hash(str) {
	let h = 5381;
	for (const b of Buffer.from(str, 'utf8')) h = (h * 33 + b) % 4294967296;
	return h;
}

// A quest goal's id as Own.goalId names it, and the ids a guide has as
// optional only and as blocking.
const goalId = (goal) => part({ goals: [goal] });
function optionality(g) {
	const opt = new Set();
	const req = new Set();
	for (const st of g.steps) {
		for (const goal of st.goals) {
			if (goal.quest == null) continue;
			(goal.optional ? opt : req).add(goalId(goal));
		}
	}
	for (const x of req) opt.delete(x);
	return { opt, req };
}

// Guides renamed since an earlier release (the current pack's renamed.json,
// `forge guide renumber`): that release's guide is this one under its new id.
const renamedFile = path.join(current, 'renamed.json');
const renamed = fs.existsSync(renamedFile) ? JSON.parse(fs.readFileSync(renamedFile, 'utf8')) : {};
const idNow = (id) => (Object.hasOwn(renamed, id) ? renamed[id] : id);

const now = new Map();
const nowReq = new Map();
for (const g of leveling(current)) {
	now.set(g.id, new Set(g.steps.map(part)));
	nowReq.set(g.id, optionality(g).req);
}
const legacy = new Map(); // id -> Map(hash -> part)
// id -> the quest goals an earlier release had as optional only that block now:
// a player could have passed them, so an update must not send them back there.
const required = new Map();
for (const dir of olds) {
	for (const g of leveling(dir)) {
		const id = idNow(g.id);
		const keep = now.get(id);
		if (!keep) continue;
		const m = legacy.get(id) || legacy.set(id, new Map()).get(id);
		for (const st of g.steps) {
			const p = part(st);
			if (p && !keep.has(p)) m.set(hash(p), p);
		}
		const r = required.get(id) || required.set(id, new Set()).get(id);
		for (const x of optionality(g).opt) if (nowReq.get(id).has(x)) r.add(x);
	}
}

const lua = (s) => '"' + s.replace(/\\/g, '\\\\').replace(/"/g, '\\"') + '"';
const lines = [
	'-- Generated by tools/legacy-steps.js from earlier releases\' leveling guides. Do not edit.',
	'-- Per guide, the steps those releases had that these guides no longer have: the hash a',
	'-- save stores for a step (CharState().stepKeys) -> its goals as the Engine names them',
	'-- (Own.stepParts). Own.remap carries a changed step\'s check-offs, skips and saved view',
	'-- to the step that now has the same goal. `required`: quest goals an earlier release had',
	'-- as optional only that block now (Own.noteAdded passes them behind the player). A function: its table is built only when an',
	'-- update changed a saved guide (Own.legacy), and the Engine drops it once the saved tabs',
	'-- are mapped, so a session without an update keeps none of it.',
	'local _, ns = ...',
	'ns.LegacyStepsLoad = function() return {',
];
let n = 0;
for (const id of [...new Set([...legacy.keys(), ...required.keys()])].sort()) {
	const m = legacy.get(id) || new Map();
	const r = [...(required.get(id) || [])].sort();
	if (!m.size && !r.length) continue;
	lines.push(`\t[${lua(id)}] = {`);
	if (r.length) lines.push(`\t\trequired = ${lua(r.join(','))},`);
	for (const h of [...m.keys()].sort((a, b) => a - b)) {
		lines.push(`\t\t[${h}] = ${lua(m.get(h))},`);
		n++;
	}
	lines.push('\t},');
}
lines.push('} end', '');
fs.writeFileSync(out, lines.join('\n'));
console.log(`wrote ${path.relative(process.cwd(), out)}: ${n} steps of ${legacy.size} guides`);
