/// `luaStr`: a double-quoted Lua string.
pub fn lua_str(s: &str) -> String {
	let mut out = String::with_capacity(s.len() + 2);
	out.push('"');
	for ch in s.chars() {
		match ch {
			'\\' => out.push_str("\\\\"),
			'"' => out.push_str("\\\""),
			'\n' => out.push_str("\\n"),
			'\r' => out.push_str("\\r"),
			c => out.push(c),
		}
	}
	out.push('"');
	out
}

/// generated.js header('lua', command, sources).
pub fn header(command: &str, sources: &str) -> String {
	format!("-- Generated by `node tools/polestar.js {command}` from {sources}. Do not edit: rebuild with that command.")
}

#[cfg(test)]
mod tests {
	use super::*;
	use forge_guide::js::parse_json;

	#[test]
	fn lua_strings_escape_like_lua_str() {
		assert_eq!(lua_str("a\\b\"c\nd\re"), "\"a\\\\b\\\"c\\nd\\re\"");
	}

	#[test]
	fn round_drops_negative_zero() {
		assert_eq!(geo::round(-0.04, 1).to_bits(), 0f64.to_bits());
		assert_eq!(geo::round(1.005, 2), 1.0);
		assert_eq!(geo::round(-2.5, 0), -2.0);
	}

	#[test]
	fn crossings_are_validated_with_named_errors() {
		let era =
			parse_json(r#"{"1429":{"c":0,"left":1535.42,"right":-1935.42,"top":-7939.58,"bottom":-10254.17},"1436":{"c":0,"left":3016.67,"right":-483.333,"top":-9400,"bottom":-11733.3}}"#).unwrap();
		let zones = parse_json(r#"{"1429":{"name":"Elwynn Forest","type":3},"1436":{"name":"Westfall","type":3}}"#).unwrap();
		let frames = geo::Frames::new(&era, &zones);
		let doc = parse_json(r#"{"schema":1,"crossings":[{"id":"Bad","a":{"map":1429,"x":10,"y":90,"radius":20},"b":{"map":1436,"x":120,"y":10,"radius":20}}],"open":[{"a":1429,"b":1429}]}"#).unwrap();
		let (errors, set) = crossings::validate_crossings(&doc, &frames);
		assert_eq!(
			errors,
			vec![
				"crossings[0] (Bad): id \"Bad\" must be lower-case letters, digits and dashes".to_string(),
				"crossings[0] (Bad).b: x 120 outside 0-100 (set \"offMap\": true for a point past the map edge)".to_string(),
				"open[0]: a zone is not a pair with itself".to_string(),
			]
		);
		assert!(set.crossings.is_empty() && set.open.is_empty());
	}
}
