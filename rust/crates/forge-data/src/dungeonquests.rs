//! `forge data dungeonquests`: which dungeon's journal page each quest is on, for the addon's hand-in plan
//! (Core/RoutePlan.lua keeps a dungeon's quests in the log without a dungeon guide open) ->
//! addon/Polestar/Dungeons/QuestKeys.lua. Same inputs give byte-identical output.
//!
//! The quests are the pages' own (`quests` of data/forever/codex/journal.json, the ones a dungeon's hand-in plan
//! takes from the log), not their chains' earlier quests. The Codex pack holds the pages but loads on demand, so
//! this small always-loaded file answers without it.
//!
//! One string, one line per dungeon in key order: `key|map|name|ids`, ids fixed-width decimal, ascending. The
//! addon keeps it as that string and searches it in place (Dungeons.QuestDungeon): no table at login.

use std::collections::{BTreeMap, BTreeSet};
use std::path::Path;

pub const COMMAND: &str = "forge data dungeonquests";
/// Digits an id takes in the string (ids under 1,000,000).
pub const WIDTH: usize = 6;

/// A dungeon's line: its instance map, its English name and its page quests.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Page {
	pub map: i64,
	pub name: String,
	pub quests: BTreeSet<i64>,
}

/// The pages of a journal (data/forever/codex/journal.json's value): key -> page.
pub fn pages(journal: &serde_json::Value) -> Result<BTreeMap<String, Page>, String> {
	let dungeons = journal.get("dungeons").and_then(|d| d.as_object()).ok_or("journal.json has no dungeons")?;
	let mut out = BTreeMap::new();
	for (key, d) in dungeons {
		let map = d.get("map").and_then(|m| m.as_i64()).ok_or_else(|| format!("{key}: no map"))?;
		let name = d.get("name").and_then(|n| n.as_str()).ok_or_else(|| format!("{key}: no name"))?.to_string();
		let quests: BTreeSet<i64> = d.get("quests").and_then(|q| q.as_array()).into_iter().flatten().filter_map(|q| q.get("id").and_then(|i| i.as_i64())).filter(|i| *i > 0).collect();
		for (what, s) in [("key", key.as_str()), ("name", name.as_str())] {
			if s.contains(['|', '\n', ']']) {
				return Err(format!("{key}: its {what} holds a separator ({s:?})"));
			}
		}
		out.insert(key.clone(), Page { map, name, quests });
	}
	Ok(out)
}

/// The Lua file: `D.RegisterQuestKeys(WIDTH, [[lines]])`.
pub fn emit(pages: &BTreeMap<String, Page>) -> String {
	let quests: BTreeSet<i64> = pages.values().flat_map(|p| p.quests.iter().copied()).collect();
	let mut l = vec![
		forge_guide::emit::header("lua", COMMAND, "data/forever/codex/journal.json"),
		"-- The dungeon journal pages' quests, a line per dungeon: key|map|name|ids, the ids".into(),
		format!(
			"-- {WIDTH} digits each, ascending. {} dungeons, {} quests ({} distinct) (rust/crates/forge-data/src/dungeonquests.rs).",
			pages.len(),
			pages.values().map(|p| p.quests.len()).sum::<usize>(),
			quests.len()
		),
		String::new(),
		"local ADDON, ns = ...".into(),
		"local D = ns.Dungeons".into(),
		"if not (D and D.RegisterQuestKeys) then return end".into(),
		String::new(),
		format!("D.RegisterQuestKeys({WIDTH}, [["),
	];
	for (key, p) in pages {
		let ids: String = p
			.quests
			.iter()
			.map(|id| {
				assert!(id.to_string().len() <= WIDTH, "quest id {id} is wider than {WIDTH} digits");
				format!("{id:0WIDTH$}")
			})
			.collect();
		l.push(format!("{key}|{}|{}|{ids}", p.map, p.name));
	}
	l.push("]])".into());
	l.join("\n") + "\n"
}

/// QuestKeys.lua from data/forever/codex/journal.json. -> (the pages, the Lua)
pub fn build(data: &Path) -> Result<(BTreeMap<String, Page>, String), String> {
	let file = data.join("codex").join("journal.json");
	let text = std::fs::read_to_string(&file).map_err(|_| format!("missing {} (run: forge data codex)", file.display()))?;
	let journal: serde_json::Value = serde_json::from_str(&text).map_err(|e| format!("{}: {e}", file.display()))?;
	let pages = pages(&journal)?;
	let lua = emit(&pages);
	Ok((pages, lua))
}

#[cfg(test)]
mod tests {
	use super::*;
	use serde_json::json;

	#[test]
	fn each_dungeon_is_a_line_of_its_page_quests_fixed_width_and_ascending() {
		let journal = json!({ "dungeons": {
			"wailing-caverns": { "name": "Wailing Caverns", "map": 43, "quests": [ { "id": 959 }, { "id": 865 }, { "id": 959 } ], "chain": [ 886 ] },
			"deadmines": { "name": "The Deadmines", "map": 36, "quests": [ { "id": 166 } ] }
		}});
		let lua = emit(&pages(&journal).unwrap());
		assert!(lua.starts_with("-- Generated by `forge data dungeonquests`"), "{lua}");
		assert!(lua.contains("2 dungeons, 3 quests (3 distinct)"), "{lua}");
		assert!(lua.contains("D.RegisterQuestKeys(6, [[\ndeadmines|36|The Deadmines|000166\nwailing-caverns|43|Wailing Caverns|000865000959\n]])\n"), "{lua}");
	}

	#[test]
	fn a_separator_in_a_name_is_refused() {
		let journal = json!({ "dungeons": { "x": { "name": "A|B", "map": 1, "quests": [] } } });
		assert!(pages(&journal).unwrap_err().contains("separator"));
	}
}
