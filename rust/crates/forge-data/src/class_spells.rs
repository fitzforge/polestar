//! `data classspells`: addon/Polestar/QoL/ClassSpells.lua, the spells each class trainer teaches per
//! level (the level-up card, QoL/LevelUp.lua). From the Forever TDB extract's sniffed class training
//! lists (<sources>/forever-tdb/extract.json `trainingSpells`: class -> level -> [[spell, cost]],
//! written by [`crate::tdb`]) and the Forever client's SpellName, Spell (NameSubtext: "Rank N") and
//! SkillLineAbility (ClassMask, RaceMasks_0) tables, cached from wago.tools.
//!
//! Per class one string, so the addon unpacks only the character's own:
//! `<level>=<spell>:<cost>:<rank>[:<previous rank>[:<race mask>]],...;...`. Rank 0: the spell has
//! none. The previous rank is the same-named spell one rank lower for the class (one the class's
//! trainers teach first, else the lowest id); 0 when there is none. The race mask is the
//! SkillLineAbility rows' RaceMasks_0 for the class, ORed, when none of them is 0 or -1 (every race).

use std::collections::{BTreeMap, BTreeSet};
use std::path::Path;

use rustc_hash::FxHashMap;

use crate::jsv::{col_num, col_str, Row};
use crate::tables::{self, Source};

fn class_bit(c: &str) -> Option<i64> {
	Some(match c {
		"WARRIOR" => 1,
		"PALADIN" => 2,
		"HUNTER" => 4,
		"ROGUE" => 8,
		"PRIEST" => 16,
		"SHAMAN" => 64,
		"MAGE" => 128,
		"WARLOCK" => 256,
		"DRUID" => 1024,
		_ => return None,
	})
}

/// "Rank 3" -> 3; anything else 0.
fn rank_of(subtext: &str) -> i64 {
	subtext.strip_prefix("Rank ").and_then(|n| n.parse::<i64>().ok()).filter(|n| *n > 0).unwrap_or(0)
}

/// ClassSpells.lua's text and the number of spells in it.
pub fn class_spells_lua(training: &serde_json::Value, spell_name: &[Row], spell: &[Row], sla: &[Row]) -> Result<(String, usize), String> {
	let classes = training.as_object().ok_or("extract.json: trainingSpells is not an object")?;
	let mut name: FxHashMap<i64, &str> = FxHashMap::default();
	for r in spell_name {
		name.insert(col_num(r, "ID") as i64, col_str(r, "Name_lang"));
	}
	let mut rank: FxHashMap<i64, i64> = FxHashMap::default();
	for r in spell {
		let n = rank_of(col_str(r, "NameSubtext_lang"));
		if n > 0 {
			rank.insert(col_num(r, "ID") as i64, n);
		}
	}
	// spell -> [(ClassMask, RaceMasks_0)]
	let mut abil: FxHashMap<i64, Vec<(i64, i64)>> = FxHashMap::default();
	for r in sla {
		abil.entry(col_num(r, "Spell") as i64).or_default().push((col_num(r, "ClassMask") as i64, col_num(r, "RaceMasks_0") as i64));
	}
	// (name, rank) -> ids, ascending
	let mut by_name: BTreeMap<(&str, i64), Vec<i64>> = BTreeMap::new();
	for (&id, &r) in &rank {
		if let Some(&n) = name.get(&id) {
			by_name.entry((n, r)).or_default().push(id);
		}
	}
	for v in by_name.values_mut() {
		v.sort_unstable();
	}
	let for_class = |id: i64, bit: i64| abil.get(&id).is_some_and(|rows| rows.iter().any(|(cm, _)| *cm == 0 || cm & bit != 0));

	let mut out = String::new();
	out.push_str("-- Generated by `forge data classspells` from the Forever TDB extract's class training lists (sniffed,\n");
	out.push_str("-- advocaite/TrinityCore `forever`, GPL-2.0, used as facts) and the Forever client's SpellName, Spell and\n");
	out.push_str("-- SkillLineAbility tables. Do not edit: rebuild with that command.\n");
	out.push_str("-- Per class: \"<level>=<spell>:<cost>:<rank>[:<previous rank>[:<race mask>]],...;...\" (rank 0: none).\n");
	out.push_str("local ADDON, ns = ...\n\nns.QoL.SetClassSpells({\n");
	let mut count = 0;
	let sorted: BTreeSet<&String> = classes.keys().collect();
	for cls in sorted {
		let Some(bit) = class_bit(cls) else { continue };
		let levels = classes[cls].as_object().ok_or_else(|| format!("extract.json: trainingSpells.{cls} is not an object"))?;
		let mut by_level: BTreeMap<i64, Vec<(i64, i64)>> = BTreeMap::new();
		for (l, list) in levels {
			let lvl: i64 = l.parse().map_err(|_| format!("extract.json: trainingSpells.{cls}: level {l}"))?;
			let mut v: Vec<(i64, i64)> = list.as_array().map(|a| a.iter().filter_map(|e| Some((e.get(0)?.as_f64()? as i64, e.get(1)?.as_f64()? as i64))).collect()).unwrap_or_default();
			v.sort_unstable();
			by_level.insert(lvl, v);
		}
		let trained: BTreeSet<i64> = by_level.values().flatten().map(|(s, _)| *s).collect();
		let mut parts = Vec::new();
		for (lvl, list) in &by_level {
			let mut es = Vec::new();
			for &(s, cost) in list {
				let r = rank.get(&s).copied().unwrap_or(0);
				let mut prev = 0;
				if r > 1 {
					if let Some(cands) = name.get(&s).and_then(|n| by_name.get(&(*n, r - 1))) {
						let ok: Vec<i64> = cands.iter().copied().filter(|x| for_class(*x, bit)).collect();
						prev = ok.iter().copied().find(|x| trained.contains(x)).or_else(|| ok.first().copied()).unwrap_or(0);
					}
				}
				let rows: Vec<i64> = abil.get(&s).map(|rows| rows.iter().filter(|(cm, _)| *cm == 0 || cm & bit != 0).map(|(_, rm)| *rm).collect()).unwrap_or_default();
				let races = if !rows.is_empty() && !rows.iter().any(|rm| *rm == 0 || *rm == -1) { rows.iter().fold(0, |a, rm| a | rm) } else { 0 };
				let mut e = format!("{s}:{cost}:{r}");
				if prev != 0 || races != 0 {
					e.push_str(&format!(":{prev}"));
				}
				if races != 0 {
					e.push_str(&format!(":{races}"));
				}
				es.push(e);
				count += 1;
			}
			parts.push(format!("{lvl}={}", es.join(",")));
		}
		out.push_str(&format!("\t{cls} = \"{}\",\n", parts.join(";")));
	}
	out.push_str("})\n");
	Ok((out, count))
}

/// `data classspells`: (ClassSpells.lua text, spells, client build) from `sources` (data/sources).
pub fn run(sources: &Path, build: Option<&str>) -> Result<(String, usize, String), String> {
	let file = sources.join("forever-tdb").join("extract.json");
	let text = std::fs::read_to_string(&file).map_err(|e| format!("{}: {e} (run `forge data build --kb` with the Forever TDB first)", file.display()))?;
	let extract: serde_json::Value = serde_json::from_str(&text).map_err(|e| format!("{}: {e}", file.display()))?;
	let training = extract.get("trainingSpells").ok_or_else(|| format!("{}: no trainingSpells", file.display()))?;
	let t = tables::load(sources, &tables::CLASS_SPELLS, build, &Source::Wago, &|_| {})?;
	let get = |n: &str| t.get(n).map(Vec::as_slice).unwrap_or(&[]);
	let (lua, n) = class_spells_lua(training, get("SpellName"), get("Spell"), get("SkillLineAbility"))?;
	Ok((lua, n, t.build))
}
