//! `trainers build` (trainers.json, Core/ClassTrainers.lua) against the JavaScript's output on the
//! data golden plus synthetic guides and recordings: rust/tests/golden/trainers (README there).

use crate::common;

#[test]
fn trainers_match_golden() {
	let g = common::golden("trainers");
	let input = g.join("input");
	let (json, lua, _) = forge_data::trainers::run(&common::golden("data").join("expected"), Some(&input.join("guides")), &input.join("recordings")).unwrap();
	let want = g.join("expected");
	let mut check = common::Check::new();
	check.file("trainers.json", &json, &want.join("trainers.json"));
	check.file("ClassTrainers.lua", &lua, &want.join("ClassTrainers.lua"));
	check.all_of(&want, &["trainers.json".into(), "ClassTrainers.lua".into()]);
	check.finish("trainers build");
}

/// A guide in the compiler fixtures' layout (rust's forge-guide tests and tests/fixtures/dsl).
pub fn guide_text(lines: &[&str]) -> String {
	format!("guide t/main\ntitle Test\nfaction Alliance\nlevels 1-10\nzone Elwynn Forest\n\n{}\n", lines.join("\n"))
}

pub fn dsl_data_copy(name: &str) -> std::path::PathBuf {
	let d = common::scratch(name);
	common::copy_tree(&std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../../tests/fixtures/dsl/data"), &d);
	d
}

/// Trainers from guide goals, recordings and the curated list on the compiler's fixture data: verified
/// on their maps, a two-class goal and a trainer two classes opened ignored, the same file twice.
#[test]
fn trainers_from_guides_recordings_and_the_curated_list_verified_and_deterministic() {
	let guides = common::scratch("trainers-guides");
	std::fs::write(
		guides.join("a.guide"),
		guide_text(&["step S", "  train 3153 only Warrior", "  train 198 only Mage", "  train 911 only Warrior,Paladin", "  train 2329", "step T", "  only Rogue", "  train 152"]),
	)
	.unwrap();
	let recs = common::scratch("trainers-recordings");
	let session = |cls: &str, events: &str| format!(r#"{{"schema":1,"char":{{"name":"T","class":"{cls}"}},"events":{events}}}"#);
	std::fs::write(recs.join("a.json"), session("MAGE", r#"[{"t":1,"e":"trainer","npc":5479,"npcName":"Wu Shen"},{"t":2,"e":"trainer","npc":3175},{"t":3,"e":"trainer","npc":6928}]"#)).unwrap();
	std::fs::write(recs.join("b.json"), session("WARRIOR", r#"[{"t":1,"e":"trainer","npc":6928}]"#)).unwrap();
	let data = dsl_data_copy("trainers-data");
	let (json, lua, rep) = forge_data::trainers::run(&data, Some(&guides), &recs).unwrap();
	assert!(rep.unverified.iter().any(|(c, n, m)| c == "WARRIOR" && n == "Lyria Du Lac" && *m == 1429), "{:?}", rep.unverified);
	let t: serde_json::Value = serde_json::from_str(&json).unwrap();
	let rows: Vec<serde_json::Value> = t.as_object().unwrap().values().map(|x| serde_json::json!([x["id"], x["classes"], x["sources"]])).collect();
	assert_eq!(
		rows,
		serde_json::json!([
			[152, ["ROGUE"], ["guide"]],
			[198, ["MAGE"], ["curated", "guide"]],
			[911, ["WARRIOR"], ["curated"]],
			[3153, ["WARRIOR"], ["curated", "guide"]],
			[5479, ["WARRIOR", "MAGE"], ["curated", "record"]]
		])
		.as_array()
		.unwrap()
		.clone(),
		"a step's `only Rogue` counts; the two-class goal is ignored"
	);
	for id in ["3175", "6928", "2329"] {
		assert!(t.get(id).is_none(), "{id}: a profession trainer, or one two classes opened, is no class trainer");
	}
	let (again, lua2, _) = forge_data::trainers::run(&data, Some(&guides), &recs).unwrap();
	assert_eq!((again, lua2), (json, lua.clone()), "deterministic");
	assert!(lua.starts_with("-- Generated by `forge data trainers`"));
}

#[test]
fn trainers_read_the_pack_guides_only_not_drafts_or_dist() {
	let guides = common::scratch("trainers-drafts");
	std::fs::write(guides.join("a.guide"), guide_text(&["step S", "  train 152 only Rogue"])).unwrap();
	for dir in ["drafts", "dist"] {
		std::fs::create_dir_all(guides.join(dir)).unwrap();
		std::fs::write(guides.join(dir).join("x.guide"), guide_text(&["step S", "  train 3175 only Warrior"])).unwrap();
	}
	let data = dsl_data_copy("trainers-drafts-data");
	let (json, _, rep) = forge_data::trainers::run(&data, Some(&guides), &common::scratch("trainers-drafts-recs")).unwrap();
	assert_eq!(rep.guide, 1, "from guides 1 goals");
	let t: serde_json::Value = serde_json::from_str(&json).unwrap();
	assert_eq!(t["152"]["sources"], serde_json::json!(["guide"]));
	assert!(t.get("3175").is_none());
}

/// Recorded trainer visits from the recording server, under recordings.rs "Trust": a trainer another
/// source lists takes a class only from three established players, each counted once however many
/// installs it has; a trainer no source lists is filled by one; a new player counts for nothing.
#[test]
fn recorded_trainers_from_the_server_follow_the_trust_rules() {
	let data = dsl_data_copy("trainers-trust-data");
	let guides = common::scratch("trainers-trust-guides");
	// (file, contributor, install, days since first seen, class, trainer)
	let run = |name: &str, sessions: &[(&str, &str, &str, f64, &str, i64)]| -> serde_json::Value {
		let recs = common::scratch(name);
		for (file, who, install, days, cls, npc) in sessions {
			let received = 1_800_000_000.0;
			let since = received - days * 86400.0;
			let text = format!(
				r#"{{"schema":2,"session":"{file}","contributor":"{who}","install":"{install}","contributorSince":{since},"contributorChunks":50,"uploadDays":3,"received":{received},"char":{{"class":"{cls}"}},"events":[{{"t":1,"e":"trainer","npc":{npc}}}]}}"#
			);
			std::fs::write(recs.join(format!("{file}.json")), text).unwrap();
			// Play (recordings.rs `establish`): positions and kills, in a class-less session, so no trainer.
			let events = [r#"{"t":1,"e":"pos","map":1420,"x":1,"y":1}"#; 10].into_iter().chain([r#"{"t":2,"e":"kill"}"#; 5]).collect::<Vec<_>>().join(",");
			let play = format!(r#"{{"schema":2,"session":"{who}-play","contributor":"{who}","install":"play","events":[{events}]}}"#);
			std::fs::write(recs.join(format!("{who}-play.json")), play).unwrap();
		}
		let (json, _, _) = forge_data::trainers::run(&data, Some(&guides), &recs).unwrap();
		serde_json::from_str(&json).unwrap()
	};
	let (a, b, d, new) = ("aaaaaaaaaaaaaaaa", "bbbbbbbbbbbbbbbb", "dddddddddddddddd", "cccccccccccccccc");
	// 911 is a curated Warrior trainer; 6928 is in no source.
	let t = run("trainers-trust-one", &[("a1", a, "i1", 30.0, "MAGE", 911), ("a2", a, "i2", 30.0, "MAGE", 911), ("a3", a, "i1", 30.0, "MAGE", 6928), ("c1", new, "i3", 1.0, "WARRIOR", 6928)]);
	assert_eq!(t["911"]["classes"], serde_json::json!(["WARRIOR"]), "one player on two installs does not change a curated trainer");
	assert_eq!((&t["6928"]["classes"], &t["6928"]["sources"]), (&serde_json::json!(["MAGE"]), &serde_json::json!(["record"])), "one player fills a gap; a new player's second class does not hide it");
	let t = run("trainers-trust-two", &[("a1", a, "i1", 30.0, "MAGE", 911), ("b1", b, "i2", 30.0, "MAGE", 911)]);
	assert_eq!(t["911"]["classes"], serde_json::json!(["WARRIOR"]), "two players do not add a class");
	let t = run("trainers-trust-three", &[("a1", a, "i1", 30.0, "MAGE", 911), ("b1", b, "i2", 30.0, "MAGE", 911), ("d1", d, "i3", 30.0, "MAGE", 911)]);
	assert_eq!(t["911"]["classes"], serde_json::json!(["WARRIOR", "MAGE"]), "three established players add a class");
	let t = run("trainers-trust-new", &[("a1", a, "i1", 30.0, "MAGE", 911), ("b1", b, "i2", 30.0, "MAGE", 911), ("c1", new, "i3", 1.0, "MAGE", 911)]);
	assert_eq!(t["911"]["classes"], serde_json::json!(["WARRIOR"]), "a new player does not make the third");
}
