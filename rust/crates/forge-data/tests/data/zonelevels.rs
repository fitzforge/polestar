//! `forge data maps build`: each zone's level range from data/forever (the spawn-weighted P10..P90
//! of normal hostile creatures, critters far under the median dropped; too little wildlife or a
//! city: none; Forever-only zones on the sparse thresholds) and ZoneLevels.lua.

use std::path::Path;

use serde_json::{json, Value};

fn pts(n: usize, x: f64, y: f64) -> Value {
	json!((0..n).map(|i| [x + (i % 5) as f64, y + (i / 5) as f64]).collect::<Vec<_>>())
}

fn npc(id: u32, name: &str, level: u32, level_max: Option<u32>, faction: Option<&str>, rank: Option<u32>, zone: u32, p: Value) -> (String, Value) {
	let mut n = json!({ "id": id, "name": name, "level": level, "faction": faction, "spawns": { zone.to_string(): { "f": "e", "pts": p } } });
	if let Some(m) = level_max {
		n["levelMax"] = json!(m);
	}
	if let Some(r) = rank {
		n["rank"] = json!(r);
	}
	(id.to_string(), n)
}

/// Greenvale (1): levels 10..20 in bulk, critters at 1, an elite, a friendly guard. Capital (2): many
/// friendly NPCs and a few rats. Quietmarsh (3): `toads` hostile spawns only. Mainland (10): a continent.
fn world(dir: &Path, toads: usize, forever_only: &[u32]) {
	let npcs: serde_json::Map<String, Value> = [
		npc(100, "Wolf", 10, Some(11), None, None, 1, pts(40, 20.0, 20.0)),
		npc(101, "Bandit", 14, None, None, None, 1, pts(60, 40.0, 40.0)),
		npc(102, "Ogre", 18, Some(20), None, None, 1, pts(30, 60.0, 60.0)),
		npc(103, "Rabbit", 1, None, None, None, 1, pts(25, 80.0, 10.0)),
		npc(104, "Ogre Lord", 30, None, None, Some(1), 1, pts(50, 70.0, 70.0)),
		npc(105, "Guard", 55, None, Some("AH"), None, 1, pts(10, 50.0, 50.0)),
		npc(200, "Citizen", 30, None, Some("A"), None, 2, pts(300, 10.0, 10.0)),
		npc(201, "Sewer Rat", 5, None, None, None, 2, pts(120, 30.0, 30.0)),
		npc(300, "Toad", 30, None, None, None, 3, pts(toads, 50.0, 50.0)),
	]
	.into_iter()
	.collect();
	let zones = json!({
		"1": { "id": 1, "name": "Greenvale", "type": 3 }, "2": { "id": 2, "name": "Capital", "type": 3 },
		"3": { "id": 3, "name": "Quietmarsh", "type": 3 }, "10": { "id": 10, "name": "Mainland", "type": 2 }
	});
	let forever: serde_json::Map<String, Value> = forever_only.iter().map(|z| (z.to_string(), json!({}))).collect();
	let frames = json!({ "era": { "1": {}, "2": {} }, "forever": forever });
	std::fs::create_dir_all(dir).unwrap();
	std::fs::write(dir.join("npcs.json"), Value::Object(npcs).to_string()).unwrap();
	std::fs::write(dir.join("zones.json"), zones.to_string()).unwrap();
	std::fs::write(dir.join("map-frames.json"), frames.to_string()).unwrap();
}

fn ranges(lua: &str) -> Vec<(u32, String)> {
	lua.lines().filter_map(|l| l.strip_prefix("\t[")?.split_once("] = ")).map(|(id, rest)| (id.parse().unwrap(), rest.to_string())).collect()
}

#[test]
fn the_range_is_p10_to_p90_of_normal_hostile_creatures_and_needs_enough_wildlife() {
	let d = crate::common::scratch("zonelevels");
	world(&d, 20, &[]);
	let (n, lua) = forge_data::worldmap::zone_levels(&d).unwrap();
	let r = ranges(&lua);
	assert_eq!(n, 1);
	// 155 spawns: 25 rabbits at 1, 20 at 10, 20 at 11, 60 at 14, 10 each at 18..20. The median is 14,
	// so the 15-level gap keeps the rabbits (P10 = 1); P90 = 19. The level 30 elite never counts.
	assert_eq!(r.len(), 1, "Capital (hostile share 120/420), Quietmarsh (20 points) and the continent get none");
	let (id, rest) = &r[0];
	assert_eq!(*id, 1);
	let nums: Vec<f64> = rest.trim_start_matches("{ ").split(" },").next().unwrap().split(", ").map(|s| s.parse().unwrap()).collect();
	assert_eq!((nums[0], nums[1]), (1.0, 19.0));
	assert!((20.0..=85.0).contains(&nums[2]) && (10.0..=75.0).contains(&nums[3]), "the label point is a weighted median of the kept spawns: {nums:?}");
	assert!(rest.ends_with("-- Greenvale"));
	let npcs: std::collections::BTreeMap<u32, forge_world::data::Entity> = serde_json::from_str(&std::fs::read_to_string(d.join("npcs.json")).unwrap()).unwrap();
	let zones: std::collections::BTreeMap<u32, forge_world::data::Zone> = serde_json::from_str(&std::fs::read_to_string(d.join("zones.json")).unwrap()).unwrap();
	assert_eq!(forge_world::zonelevels::zone_levels(&npcs, &zones, &[])[&1].weight, 155.0, "hostile normal spawn points, rabbits included");
	assert!(lua.starts_with("-- Generated by `forge data maps build` from data/forever/npcs.json."));
	assert!(lua.contains("\nM.RegisterZoneLevels({\n") && lua.ends_with("})\n"));
}

#[test]
fn forever_only_zones_pass_on_the_sparse_thresholds_the_rest_keep_the_strict_ones() {
	let d = crate::common::scratch("zonelevels-sparse");
	world(&d, 40, &[3]);
	let r = ranges(&forge_data::worldmap::zone_levels(&d).unwrap().1);
	let ids: Vec<u32> = r.iter().map(|x| x.0).collect();
	assert_eq!(ids, [1, 3], "Quietmarsh has Forever frames only: 40 points pass; Capital stays held to the strict share");
	assert!(r[1].1.starts_with("{ 30, 30,"));
	world(&d, 20, &[3]);
	assert_eq!(ranges(&forge_data::worldmap::zone_levels(&d).unwrap().1).len(), 1, "20 is under the sparse minimum of 30");
	world(&d, 40, &[]);
	assert_eq!(ranges(&forge_data::worldmap::zone_levels(&d).unwrap().1).len(), 1, "not Forever-only: 40 is under the strict 100");
}

/// The committed ZoneLevels.lua against the data/forever it was built from: a check for the maintainer after a
/// data refresh, not for every checkout (another build of data/forever gives other ranges).
#[test]
#[ignore = "needs the data/forever the committed ZoneLevels.lua was built from (FORGE_DATA or <checkout>/data/forever)"]
fn zone_levels_lua_is_up_to_date_with_data_forever() {
	let repo = super::fixture_build::repo();
	let data = std::env::var_os("FORGE_DATA").map(std::path::PathBuf::from).unwrap_or_else(|| repo.join("data/forever"));
	assert!(data.join("npcs.json").exists() && data.join("zones.json").exists(), "no data/forever (npcs.json, zones.json) at {}", data.display());
	let (_, lua) = forge_data::worldmap::zone_levels(&data).unwrap();
	assert_eq!(std::fs::read_to_string(repo.join("addon/Polestar/Maps/ZoneLevels.lua")).unwrap(), lua, "run: forge data maps build");
	let r: std::collections::BTreeMap<u32, String> = ranges(&lua).into_iter().collect();
	assert!(r[&1429].starts_with("{ 1, 10,"), "Elwynn Forest");
	assert!(!r.contains_key(&1453), "Stormwind City");
	assert!(r.contains_key(&2521) && r.contains_key(&2482), "Forever-only zones with data have ranges (Zephras Isle, Mount Hyjal)");
}
