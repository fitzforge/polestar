//! `data classspells` (QoL/ClassSpells.lua) on synthetic client rows: ranks from "Rank N", the previous rank of
//! the same name for the class (one its trainers teach first), race masks only when not every race.

use forge_data::class_spells::class_spells_lua;
use forge_data::jsv::Row;

fn row(pairs: &[(&str, &str)]) -> Row {
	pairs.iter().map(|(k, v)| (k.to_string(), v.to_string())).collect()
}

#[test]
fn ranks_previous_ranks_and_race_masks_per_class() {
	let training = serde_json::json!({
		"PRIEST": { "10": [[594, 300], [2944, 300], [586, 300]], "4": [[589, 100]] },
		"MAGE": { "4": [[116, 100]] },
		"NOBODY": { "4": [[1, 1]] },
	});
	let names = vec![
		row(&[("ID", "589"), ("Name_lang", "Shadow Word: Pain")]),
		row(&[("ID", "594"), ("Name_lang", "Shadow Word: Pain")]),
		row(&[("ID", "9589"), ("Name_lang", "Shadow Word: Pain")]),
		row(&[("ID", "2944"), ("Name_lang", "Devouring Plague")]),
		row(&[("ID", "586"), ("Name_lang", "Fade")]),
		row(&[("ID", "116"), ("Name_lang", "Frostbolt")]),
	];
	let spell = vec![
		row(&[("ID", "589"), ("NameSubtext_lang", "Rank 1")]),
		row(&[("ID", "594"), ("NameSubtext_lang", "Rank 2")]),
		// Another class's Shadow Word: Pain 1: not the Priest's previous rank.
		row(&[("ID", "9589"), ("NameSubtext_lang", "Rank 1")]),
		row(&[("ID", "2944"), ("NameSubtext_lang", "Rank 1")]),
		row(&[("ID", "586"), ("NameSubtext_lang", "")]),
		row(&[("ID", "116"), ("NameSubtext_lang", "Rank 1")]),
	];
	let sla = vec![
		row(&[("Spell", "589"), ("ClassMask", "16"), ("RaceMasks_0", "0")]),
		row(&[("Spell", "594"), ("ClassMask", "16"), ("RaceMasks_0", "-1")]),
		row(&[("Spell", "9589"), ("ClassMask", "128"), ("RaceMasks_0", "0")]),
		row(&[("Spell", "2944"), ("ClassMask", "16"), ("RaceMasks_0", "16")]),
		row(&[("Spell", "586"), ("ClassMask", "16"), ("RaceMasks_0", "0")]),
		row(&[("Spell", "116"), ("ClassMask", "128"), ("RaceMasks_0", "0")]),
	];
	let (lua, n) = class_spells_lua(&training, &names, &spell, &sla).unwrap();
	assert_eq!(n, 5, "{lua}");
	assert!(lua.contains("\tMAGE = \"4=116:100:1\",\n"), "{lua}");
	assert!(lua.contains("\tPRIEST = \"4=589:100:1;10=586:300:0,594:300:2:589,2944:300:1:0:16\",\n"), "{lua}");
	assert!(!lua.contains("NOBODY"), "{lua}");
	assert!(lua.starts_with("-- Generated by `forge data classspells`"));
	assert!(lua.ends_with("})\n"));
}
