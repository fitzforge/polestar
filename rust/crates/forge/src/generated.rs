//! Generated guides: the seed Forge starts from, the guides it writes into the checkout, and the
//! check that neither is edited by hand.
//!
//! - **The seed** (`forge/seed/guides/`, cut once by `forge guide seed`): the leveling guides
//!   (`guides/forever/horde/**`, `guides/forever/alliance/**`) as they were when Forge took them
//!   over, with `forge/seed/SEED.json` (the commit they were cut from and every file's SHA-256).
//!   From then on a build reads its text and order from the seed, never from its own output.
//! - **The generated guides** (`forge guide publish --from <out>/guides`, [`publish`]): the
//!   leveling guides of every start's written tree, copied into `guides/` with [`HEADER`] on top
//!   and listed in `guides/GENERATED.json` (SHA-256 of each): the shared route once per faction,
//!   each start guide from its own start, one copy per race where two starts share a folder, a
//!   race's lead-in merged into the shared guide of its zone. Every other file under `guides/`
//!   (class, professions, ... and the translations) stays hand-written.
//! - **The check** ([`check`]; `forge guide check-generated`, and `tests/generated-guides.test.js`
//!   in CI): every listed file still has its hash, so a hand edit fails and says where the fix goes.
//!
//! With a seed in the checkout, `forge build` reads `guides/` with each generated file replaced by
//! its seed ([`input_guides`]).

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use serde_json::{json, Value};
use sha2::{Digest, Sha256};

pub const SEED_DIR: &str = "forge/seed/guides";
pub const SEED_MANIFEST: &str = "forge/seed/SEED.json";
pub const GENERATED: &str = "guides/GENERATED.json";
/// The first line of every generated guide.
pub const HEADER: &str = "# Generated by forge build from forge/seed and the checkout's fixes. Do not edit: see docs/FORGE.md, \"Fixing a generated guide\".";

/// Where a fix goes instead of a generated guide (the check's message).
pub const WHERE_FIXES_GO: &str = "Put the fix where every build applies it:
  - a quest fact (giver, turn-in, prerequisite, objective, XP, races), an NPC's or object's place
    or rank, a wrong drop: forever-db/corrections (quests.json, npcs.json, objects.json, items.json)
  - how a quest is done (an item from a chest, a delayed offer, an object to click):
    forever-db/corrections/mechanics.json
  - whether the route takes a quest, or an order players asked for: data/route-fixes.json
  - the check that pins the fix: tests/guides-reported.test.js
A step's wording, tip or arrow point has no record file yet: describe the fix on the issue and the
maintainer applies it. docs/FORGE.md, \"Fixing a generated guide\", has the details.";

fn sha256(bytes: &[u8]) -> String {
	let d = Sha256::digest(bytes);
	d.iter().map(|b| format!("{b:02x}")).collect()
}

fn rel(p: &Path, base: &Path) -> String {
	p.strip_prefix(base).unwrap_or(p).components().map(|c| c.as_os_str().to_string_lossy()).collect::<Vec<_>>().join("/")
}

fn files(dir: &Path) -> Vec<PathBuf> {
	let mut out = Vec::new();
	let mut stack = vec![dir.to_path_buf()];
	while let Some(d) = stack.pop() {
		for e in std::fs::read_dir(&d).into_iter().flatten().flatten() {
			let p = e.path();
			if p.is_dir() {
				stack.push(p);
			} else if p.extension().is_some_and(|x| x == "guide") {
				out.push(p);
			}
		}
	}
	out.sort();
	out
}

/// The leveling guides of a guides folder (relative to it): what Forge generates.
pub fn leveling_guides(guides: &Path) -> Vec<String> {
	["forever/horde", "forever/alliance"].iter().flat_map(|sub| files(&guides.join(sub))).map(|p| rel(&p, guides)).collect()
}

fn git(dir: &Path, args: &[&str]) -> Option<String> {
	let o = std::process::Command::new("git").arg("-C").arg(dir).args(args).output().ok()?;
	o.status.success().then(|| String::from_utf8_lossy(&o.stdout).trim().to_string())
}

fn read(p: &Path) -> Result<Vec<u8>, String> {
	std::fs::read(p).map_err(|e| format!("{}: {e}", p.display()))
}

fn write(p: &Path, b: &[u8]) -> Result<(), String> {
	if let Some(d) = p.parent() {
		std::fs::create_dir_all(d).map_err(|e| format!("{}: {e}", d.display()))?;
	}
	std::fs::write(p, b).map_err(|e| format!("{}: {e}", p.display()))
}

/// `text` without the generated header (a guide published earlier), as the seed holds it.
fn without_header(text: &[u8]) -> &[u8] {
	let h = HEADER.as_bytes();
	if text.starts_with(h) {
		let rest = &text[h.len()..];
		rest.strip_prefix(b"\r\n").or_else(|| rest.strip_prefix(b"\n")).unwrap_or(rest)
	} else {
		text
	}
}

/// The seed's manifest: relative path -> SHA-256 (None: the checkout has no seed).
pub fn seed_files(checkout: &Path) -> Result<Option<BTreeMap<String, String>>, String> {
	let m = checkout.join(SEED_MANIFEST);
	if !m.is_file() {
		return Ok(None);
	}
	let v: Value = serde_json::from_slice(&read(&m)?).map_err(|e| format!("{}: {e}", m.display()))?;
	Ok(Some(v["files"].as_object().into_iter().flatten().map(|(k, v)| (k.clone(), v.as_str().unwrap_or("").to_string())).collect()))
}

/// `forge guide seed`: cuts the seed from the checkout's leveling guides. Refuses when a seed
/// exists (a re-seed resets what every route is measured against) unless `force`.
pub fn cut_seed(checkout: &Path, force: bool) -> Result<usize, String> {
	let guides = checkout.join("guides");
	if checkout.join(SEED_MANIFEST).is_file() && !force {
		return Err(format!("{} already has a seed ({SEED_MANIFEST}): re-seeding resets every route's baseline; pass --force to cut it again", checkout.display()));
	}
	if checkout.join(GENERATED).is_file() {
		return Err(format!("{GENERATED} exists: guides/ holds generated guides, which are no seed"));
	}
	let list = leveling_guides(&guides);
	if list.is_empty() {
		return Err(format!("no leveling guides under {}/forever/{{horde,alliance}}", guides.display()));
	}
	let seed = checkout.join(SEED_DIR);
	let _ = std::fs::remove_dir_all(&seed);
	let mut hashes = BTreeMap::new();
	for f in &list {
		let b = read(&guides.join(f))?;
		write(&seed.join(f), &b)?;
		hashes.insert(f.clone(), sha256(&b));
	}
	let doc = json!({
		"about": "The leveling guides Forge starts from, cut from guides/ by `forge guide seed` once, when Forge took them over (a re-seed resets every route's baseline). Never edit them: a fix goes into the checkout's fix records (docs/FORGE.md, \"Fixing a generated guide\"). files: path under forge/seed/guides -> SHA-256.",
		"from": { "commit": git(checkout, &["rev-parse", "HEAD"]) },
		"files": hashes,
	});
	write(&checkout.join(SEED_MANIFEST), (serde_json::to_string_pretty(&doc).map_err(|e| e.to_string())? + "\n").as_bytes())?;
	Ok(list.len())
}

/// The guides a build reads: `guides` itself, or, when it is the checkout's own `guides/` and the
/// checkout has a seed, a copy (in `stage`) with every generated file replaced by its seed.
pub fn input_guides(checkout: &Path, guides: &Path, stage: &Path) -> Result<(PathBuf, Option<usize>), String> {
	let Some(seed) = seed_files(checkout)? else { return Ok((guides.to_path_buf(), None)) };
	let same = |a: &Path, b: &Path| a.canonicalize().ok().zip(b.canonicalize().ok()).is_some_and(|(a, b)| a == b);
	if !same(guides, &checkout.join("guides")) {
		return Ok((guides.to_path_buf(), None));
	}
	let _ = std::fs::remove_dir_all(stage);
	let mut stack = vec![guides.to_path_buf()];
	while let Some(d) = stack.pop() {
		for e in std::fs::read_dir(&d).map_err(|e| format!("{}: {e}", d.display()))?.flatten() {
			let p = e.path();
			if p.is_dir() {
				stack.push(p);
			} else {
				write(&stage.join(rel(&p, guides)), &read(&p)?)?;
			}
		}
	}
	for f in seed.keys() {
		let src = checkout.join(SEED_DIR).join(f);
		write(&stage.join(f), &read(&src)?)?;
	}
	// A guide only publish wrote (a race's own copy of a start guide, a guide the writer added) is
	// output, never input: it goes. A guide added by hand after the cut stays as written.
	for f in generated_files(checkout)? {
		if f.ends_with(".guide") && !seed.contains_key(&f) {
			let _ = std::fs::remove_file(stage.join(&f));
		}
	}
	Ok((stage.to_path_buf(), Some(seed.len())))
}

/// The files `guides/GENERATED.json` lists (empty: none published yet).
fn generated_files(checkout: &Path) -> Result<Vec<String>, String> {
	let m = checkout.join(GENERATED);
	if !m.is_file() {
		return Ok(Vec::new());
	}
	let v: Value = serde_json::from_slice(&read(&m)?).map_err(|e| format!("{}: {e}", m.display()))?;
	Ok(v["files"].as_object().into_iter().flatten().map(|(k, _)| k.clone()).collect())
}

/// What [`publish`] wrote.
#[derive(Debug, Default)]
pub struct Published {
	/// Guides written into `guides/`.
	pub guides: usize,
	/// Start guides several starts wrote, published once per race: (the written id, the races' ids).
	pub split: Vec<(String, Vec<String>)>,
	/// Race lead-ins merged into the shared guide of their zone: (the shared id, the lead-ins' ids).
	pub merged: Vec<(String, Vec<String>)>,
	/// Guides with baked legs in the merged `legs.json`.
	pub legs: usize,
}

/// One start's written tree, its faction's leveling guides (path -> text without the header).
struct Tree {
	start: &'static str,
	race: &'static str,
	files: BTreeMap<String, Vec<u8>>,
	legs: Option<Value>,
}

/// Who publishes a written guide.
enum Owner {
	/// No `race` header naming a start of the faction: the shared route, the same in every tree.
	Shared,
	/// The guide of one start (index into the faction's trees).
	One(usize),
	/// A start guide two or more starts wrote (Orc and Troll's Durotar): one copy per race.
	Split(Vec<usize>),
}

/// The races a guide's `race` header names (empty: none).
fn header_races(text: &[u8]) -> Vec<String> {
	let text = String::from_utf8_lossy(text);
	for l in text.lines() {
		if l.starts_with("step") {
			break;
		}
		if let Some(r) = l.strip_prefix("race ") {
			return r.split(',').map(|r| r.trim().to_string()).filter(|r| !r.is_empty()).collect();
		}
	}
	Vec::new()
}

/// Where a race's copy of a split start guide goes: its folder named for the race
/// (`forever/horde/orc-troll/01-durotar.guide` -> `forever/horde/orc/01-durotar.guide`).
fn split_rel(rel: &str, race: &str) -> String {
	let p = Path::new(rel);
	let file = p.file_name().map(|f| f.to_string_lossy().into_owned()).unwrap_or_default();
	let folder = p.parent().and_then(Path::parent).map(|d| d.to_string_lossy().into_owned()).unwrap_or_default();
	format!("{folder}/{}/{file}", race.to_lowercase())
}

fn guide_id(rel: &str) -> &str {
	rel.strip_suffix(".guide").unwrap_or(rel)
}

/// A header key's value (before the first step).
fn header_value<'a>(text: &'a str, key: &str) -> Option<&'a str> {
	text.lines().take_while(|l| !l.starts_with("step")).find_map(|l| l.strip_prefix(key).and_then(|r| r.strip_prefix(' '))).map(str::trim)
}

/// A guide's text compiled on its own (for its legs' places).
fn compile_guide(rel: &str, text: &str, d: &forge_guide::data::Data) -> Option<forge_guide::js::V> {
	let src = forge_guide::project::Source { source: rel.to_string(), file: rel.to_string(), text: text.to_string() };
	forge_guide::project::resolve_sources(&[src], d, &mut forge_guide::diag::Diagnostics::new(), None, None).into_iter().next()
}

/// `text` with every whole guide id of `ids` (old -> new) replaced.
fn replace_ids(text: &str, ids: &[(String, String)]) -> String {
	let id_char = |c: char| c.is_alphanumeric() || matches!(c, '_' | '-' | '/');
	let mut out = text.to_string();
	for (old, new) in ids {
		let mut s = String::with_capacity(out.len());
		let mut last = 0;
		for (i, _) in out.match_indices(old.as_str()) {
			let before = out[..i].chars().next_back();
			let after = out[i + old.len()..].chars().next();
			if before.is_some_and(id_char) || after.is_some_and(id_char) {
				continue;
			}
			s.push_str(&out[last..i]);
			s.push_str(new);
			last = i + old.len();
		}
		s.push_str(&out[last..]);
		out = s;
	}
	out
}

/// Quest id -> (race mask, 0 for any race; whether Forever's own quest store gave it).
type QuestRaces = BTreeMap<u32, (f64, bool)>;

fn quest_races(data: &Path) -> Result<QuestRaces, String> {
	let p = data.join("quests.json");
	let v: Value = serde_json::from_slice(&read(&p)?).map_err(|e| format!("{}: {e}", p.display()))?;
	let mut out = QuestRaces::new();
	for (k, q) in v.as_object().into_iter().flatten() {
		let Ok(id) = k.parse::<u32>() else { continue };
		let forever = q["source"].as_array().is_some_and(|s| s.iter().any(|s| s.as_str().is_some_and(|s| s.starts_with("questie"))));
		out.insert(id, (q["races"].as_f64().unwrap_or(0.0), forever));
	}
	Ok(out)
}

/// Whether a quest of that race mask is for the race on that side, as the compiler reads masks
/// (forge_guide::conditions::mask_excludes: a Skyborne bit only from Forever's own store).
fn mask_admits((mask, forever): (f64, bool), race: &str, side: &str) -> bool {
	use forge_guide::races::{has_bit, RACES};
	if mask == 0.0 {
		return true;
	}
	RACES
		.iter()
		.filter(|r| r.name.eq_ignore_ascii_case(race) || r.file.eq_ignore_ascii_case(race))
		.flat_map(|r| r.sides)
		.any(|&(s, bit)| s == side && (has_bit(mask, bit) || (bit >= 4294967296.0 && !forever)))
}

/// A race's copy of a start guide written for several races (`Orc,Troll`): its header says `race
/// <race>`, and what never shows to that race goes: a goal whose `only` names other races alone
/// (`accept 1 only Troll,Warrior`) or whose quest the race cannot take (Glyphic Memorandum, a
/// Gnome's, in the Dwarves' copy), a step whose `only` names other races alone, and a step left
/// without goals. The steps' places change with them: [`publish`] re-keys the baked legs.
fn race_copy(text: &str, race: &str, side: &str, quests: &QuestRaces) -> String {
	use forge_guide::conditions::Audience;
	use forge_guide::lexer::lex_line;
	let excludes = |list: &str| !Audience::parse(list).race_in(race);
	// (A goal line's own `only` list and quests.)
	let goal_dropped = |body: &str| -> Option<bool> {
		let lex = lex_line(body);
		let t = &lex.tokens;
		if !(body.starts_with([' ', '\t']) && t.first().is_some_and(|v| !v.quoted && forge_guide::parse::VERBS.contains(&v.text.as_str()))) {
			return None;
		}
		if t.iter().enumerate().skip(1).find(|(_, v)| v.text == "only" && !v.quoted).and_then(|(i, _)| t.get(i + 1)).is_some_and(|l| excludes(&l.text)) {
			return Some(true);
		}
		let mut ids: Vec<u32> = Vec::new();
		if matches!(t[0].text.as_str(), "accept" | "turnin" | "complete" | "abandon") {
			ids.extend(t.get(1).and_then(|v| v.text.parse::<u32>().ok()));
		}
		for w in t.windows(2) {
			if w[0].text == "quest" && !w[0].quoted {
				ids.extend(w[1].text.split('.').next().and_then(|q| q.parse::<u32>().ok()));
			}
		}
		Some(ids.iter().filter_map(|q| quests.get(q)).any(|&m| !mask_admits(m, race, side)))
	};
	let mut out = String::with_capacity(text.len());
	let mut in_steps = false;
	// The step being read: its lines, whether it goes, whether it had goals and kept one.
	let mut step: Vec<&str> = Vec::new();
	let (mut drop_step, mut had_goal, mut kept_goal) = (false, false, false);
	let flush = |out: &mut String, step: &mut Vec<&str>, drop: bool| {
		if !drop {
			out.extend(step.iter().copied());
		} else {
			// (Its section comments and blank lines stay; one blank line between steps.)
			for l in step.iter().filter(|l| !l.starts_with("step") && !l.starts_with([' ', '\t'])) {
				if !(l.trim().is_empty() && (out.ends_with("\n\n") || out.is_empty())) {
					out.push_str(l);
				}
			}
		}
		step.clear();
	};
	for raw in text.split_inclusive('\n') {
		let body = raw.trim_end_matches(['\n', '\r']);
		if body.starts_with("step") {
			if in_steps {
				flush(&mut out, &mut step, drop_step || (had_goal && !kept_goal));
			}
			in_steps = true;
			(drop_step, had_goal, kept_goal) = (false, false, false);
			step.push(raw);
			continue;
		}
		if !in_steps {
			if body.starts_with("race ") {
				out.push_str(&format!("race {race}{}", &raw[body.len()..]));
			} else {
				out.push_str(raw);
			}
			continue;
		}
		let code = body.split(" -- ").next().unwrap_or(body);
		if let Some(list) = code.trim_start().strip_prefix("only ").filter(|_| body.starts_with([' ', '\t']) && !had_goal) {
			drop_step |= excludes(list.trim());
		}
		match goal_dropped(body) {
			Some(true) => had_goal = true,
			Some(false) => {
				(had_goal, kept_goal) = (true, true);
				step.push(raw);
			}
			None => step.push(raw),
		}
	}
	flush(&mut out, &mut step, drop_step || (had_goal && !kept_goal));
	out
}

/// A split guide's baked legs (`{hash, steps}`, baked on the guide as written, `old`) for its
/// race's copy (`new`): each of the copy's legs that runs between the same two places as one of the
/// written guide's takes that leg; the hash is the copy's.
fn rekey_legs(legs: &Value, old: &forge_guide::js::V, new: &forge_guide::js::V, frames: &forge_guide::js::V) -> Value {
	use forge_guide::bake::{guide_hash, step_targets, World};
	let key = |a: &World, b: &World| (a.c.to_js_string(), a.wx.round() as i64, a.wy.round() as i64, b.wx.round() as i64, b.wy.round() as i64);
	let mut had: Vec<(_, &Value)> = step_targets(old, frames).iter().filter_map(|(s, a, b)| Some((key(a, b), legs["steps"].get(s.to_string())?))).collect();
	let mut steps = serde_json::Map::new();
	for (s, a, b) in step_targets(new, frames) {
		let k = key(&a, &b);
		if let Some(i) = had.iter().position(|(x, _)| *x == k) {
			steps.insert(s.to_string(), had.remove(i).1.clone());
		}
	}
	json!({ "hash": guide_hash(new, frames), "steps": steps })
}

/// A compiled guide's steps as the bake reads them: whether a goal of the step has a place (it
/// ends or begins a leg, forge_guide::bake::step_targets), and the races its `only` names (None:
/// every race).
fn step_audiences(g: &forge_guide::js::V, frames: &forge_guide::js::V) -> Vec<(bool, Option<Vec<String>>)> {
	g.get("steps")
		.items()
		.iter()
		.map(|s| {
			let placed = s.get("goals").items().iter().any(|goal| goal.get("t").as_str() != Some("note") && forge_guide::bake::goal_world(goal, frames).is_some());
			let races: Vec<String> = s.get("only").get("races").items().iter().map(|r| r.to_js_string()).collect();
			(placed, (!races.is_empty()).then_some(races))
		})
		.collect()
}

/// The steps (1-based) whose leg in starts at the last placed step before them, when some race
/// that sees the step never sees that one (a step for Orcs and Trolls after the Trolls' own).
fn legs_across_races(steps: &[(bool, Option<Vec<String>>)]) -> Vec<usize> {
	use forge_guide::conditions::same_race;
	let mut out = Vec::new();
	let mut last: Option<&Option<Vec<String>>> = None;
	for (i, (placed, races)) in steps.iter().enumerate() {
		if !placed {
			continue;
		}
		let seen = match (last, races) {
			(None | Some(None), _) => true,
			(Some(Some(_)), None) => false,
			(Some(Some(from)), Some(to)) => to.iter().all(|r| from.iter().any(|f| same_race(f, r))),
		};
		if !seen {
			out.push(i + 1);
		}
		last = Some(races);
	}
	out
}

/// `forge guide publish --from <out>/guides`: the leveling guides of a build's written trees, one
/// per start (`<from>/<Start>/`, as forge build writes them; every start is needed), into the
/// checkout's `guides/` with the header, `guides/GENERATED.json` listing them:
///
/// - a guide without a `race` header for one of the faction's starts (the shared route from the
///   Barrens and Westfall on) once per faction; every start must have written it byte for byte the
///   same, else nothing is written;
/// - a start guide from its own start's tree (the other trees carry the seed's copy);
/// - a start guide two starts share (`orc-troll/`, `dwarf-gnome/`) once per race, from each race's
///   tree, in a folder named for the race (`orc/`, `troll/`) with `race <Race>` and the ids
///   between those guides rewritten ([`race_copy`]); the shared ids go into `guides/retired.json`,
///   so a saved tab on one opens the race's leveling guide;
/// - a race's guide whose `next` is a shared guide of the same `zone` (its lead-in: the Orcs' and
///   Trolls' Barrens before the shared Barrens) merged into that guide as its races' opening steps
///   ([`crate::lead_in::merge_lead_ins`]); the guides that led to it lead to the shared guide, and
///   its id goes into `guides/retired.json`. (Not the Night Elves' Darkshore: it hands over to
///   Westfall.)
///
/// The trees' baked legs (`legs.json`) become one `guides/legs.json`, per published guide id:
/// the shared route's must agree between the starts, and all trees must be baked on one grid.
/// Every seed guide must be among the written ones; files an earlier publish wrote and this one
/// does not are removed.
pub fn publish(checkout: &Path, from: &Path, data: &Path) -> Result<Published, String> {
	use forge_guide::conditions::same_race;
	let seed = seed_files(checkout)?.ok_or_else(|| format!("{} has no seed ({SEED_MANIFEST}): run `forge guide seed` first", checkout.display()))?;
	let missing: Vec<&str> = crate::ALL_STARTS.iter().map(|s| s.0).filter(|s| !from.join(s).join("forever").is_dir()).collect();
	if !missing.is_empty() {
		return Err(format!("{} has no written tree for {} (<Start>/forever, as forge build writes them): publish takes every start", from.display(), missing.join(", ")));
	}
	let mut out: BTreeMap<String, Vec<u8>> = BTreeMap::new();
	let mut legs_out = serde_json::Map::new();
	let mut grid: Option<(Value, &str)> = None;
	let mut errors: Vec<String> = Vec::new();
	let mut published = Published::default();
	let mut quests: Option<QuestRaces> = None;
	// (The guide data, for a split copy's legs: loaded when one needs them.)
	let mut gdata: Option<forge_guide::data::Data> = None;
	let mut seen_seed: std::collections::BTreeSet<String> = Default::default();
	for faction in [forge_core::Faction::Horde, forge_core::Faction::Alliance] {
		let sub = format!("forever/{}", faction.lower());
		let mut trees = Vec::new();
		for &(start, race, _) in crate::ALL_STARTS.iter().filter(|s| s.2 == faction) {
			let root = from.join(start);
			let mut files_of = BTreeMap::new();
			for p in files(&root.join(&sub)) {
				files_of.insert(rel(&p, &root), without_header(&read(&p)?).to_vec());
			}
			let l = root.join(crate::bake::LEGS_FILE);
			let legs: Option<Value> = if l.is_file() { Some(serde_json::from_slice(&read(&l)?).map_err(|e| format!("{}: {e}", l.display()))?) } else { None };
			if let Some(g) = legs.as_ref().map(|l| l["grid"].clone()) {
				match &grid {
					Some((g0, s0)) if *g0 != g => errors.push(format!("{start}'s legs are baked on {g}, {s0}'s on {g0}: bake every start on one grid")),
					Some(_) => {}
					None => grid = Some((g, start)),
				}
			}
			trees.push(Tree { start, race, files: files_of, legs });
		}
		let leg = |t: &Tree, id: &str| t.legs.as_ref().and_then(|l| l["legs"].get(id)).cloned();
		let rels: std::collections::BTreeSet<&String> = trees.iter().flat_map(|t| t.files.keys()).collect();
		let mut owners: Vec<(&String, Owner)> = Vec::new();
		for r in rels {
			let any = trees.iter().find_map(|t| t.files.get(r)).expect("a tree has it");
			let races = header_races(any);
			let own: Vec<usize> = (0..trees.len()).filter(|&i| races.iter().any(|x| same_race(x, trees[i].race))).collect();
			owners.push((
				r,
				match own.len() {
					0 => Owner::Shared,
					1 => Owner::One(own[0]),
					_ => Owner::Split(own),
				},
			));
		}
		// Per race, its split guides' ids (written -> its own).
		let renames = |i: usize| -> Vec<(String, String)> {
			let mut v: Vec<(String, String)> =
				owners.iter().filter(|(_, o)| matches!(o, Owner::Split(s) if s.contains(&i))).map(|(r, _)| (guide_id(r).to_string(), guide_id(&split_rel(r, trees[i].race)).to_string())).collect();
			v.sort_by_key(|(old, _)| std::cmp::Reverse(old.len()));
			v
		};
		for (r, owner) in &owners {
			let id = guide_id(r);
			match owner {
				Owner::Shared => {
					// The starts grouped by what they wrote, in start order.
					let mut by: Vec<(Option<&Vec<u8>>, Vec<&str>)> = Vec::new();
					for t in &trees {
						let b = t.files.get(*r);
						match by.iter_mut().find(|(x, _)| *x == b) {
							Some((_, s)) => s.push(t.start),
							None => by.push((b, vec![t.start])),
						}
					}
					if by.len() > 1 {
						let groups: Vec<String> = by.iter().map(|(b, s)| format!("{}{}", s.join(", "), if b.is_none() { " (missing)" } else { "" })).collect();
						errors.push(format!("{r}: the shared route differs between starts ({})", groups.join(" | ")));
						continue;
					}
					let legs: Vec<Value> = trees.iter().filter_map(|t| leg(t, id)).collect();
					if legs.iter().any(|l| *l != legs[0]) {
						errors.push(format!("{r}: its baked legs differ between starts (bake them again)"));
					}
					if let Some(l) = legs.into_iter().next() {
						legs_out.insert(id.to_string(), l);
					}
					out.insert((*r).clone(), trees[0].files[*r].clone());
					seen_seed.insert((*r).clone());
				}
				Owner::One(i) => {
					let t = &trees[*i];
					if let Some(b) = t.files.get(*r) {
						out.insert((*r).clone(), b.clone());
						seen_seed.insert((*r).clone());
						if let Some(l) = leg(t, id) {
							legs_out.insert(id.to_string(), l);
						}
					}
				}
				Owner::Split(own) => {
					if quests.is_none() {
						quests = Some(quest_races(data)?);
					}
					let mut ids = Vec::new();
					for &i in own {
						let t = &trees[i];
						let Some(b) = t.files.get(*r) else { continue };
						let to = split_rel(r, t.race);
						let text = replace_ids(&String::from_utf8_lossy(b), &renames(i));
						let copy = race_copy(&text, t.race, faction.name(), quests.as_ref().expect("loaded"));
						if let Some(l) = leg(t, id) {
							// (Steps or goals gone: the legs move to the copy's steps.)
							let l = if copy.lines().count() == text.lines().count() {
								l
							} else {
								if gdata.is_none() {
									gdata = Some(forge_guide::project::load_project_data(data, &mut forge_guide::diag::Diagnostics::new())?);
								}
								let d = gdata.as_ref().expect("loaded");
								match (compile_guide(r, &String::from_utf8_lossy(b), d), compile_guide(r, &copy, d)) {
									(Some(old), Some(new)) => rekey_legs(&l, &old, &new, &d.map_frames),
									_ => return Err(format!("{r}: {}'s copy does not compile", t.race)),
								}
							};
							legs_out.insert(guide_id(&to).to_string(), l);
						}
						let text = copy;
						ids.push(guide_id(&to).to_string());
						out.insert(to, text.into_bytes());
					}
					if !ids.is_empty() {
						seen_seed.insert((*r).clone());
						published.split.push((id.to_string(), ids));
					}
				}
			}
		}
		// A race's lead-in that hands over to the shared guide of its zone (the Orcs' and Trolls'
		// Barrens): merged into that guide (crate::lead_in), its id retired.
		let in_faction = |f: &str| f.starts_with(&format!("{sub}/"));
		let mut into: BTreeMap<String, Vec<(usize, String)>> = BTreeMap::new();
		for (f, b) in out.iter().filter(|(f, _)| in_faction(f)) {
			let Some(order) = header_races(b).first().and_then(|x| trees.iter().position(|t| same_race(x, t.race))) else { continue };
			let t = String::from_utf8_lossy(b);
			let Some(s) = header_value(&t, "next").and_then(|n| n.split_whitespace().next()).map(|n| format!("{n}.guide")) else { continue };
			let Some(st) = out.get(&s).filter(|sb| header_races(sb).is_empty()).map(|sb| String::from_utf8_lossy(sb)) else { continue };
			let zone = header_value(&t, "zone").filter(|z| !z.is_empty());
			if zone.is_some() && zone == header_value(&st, "zone") {
				into.entry(s).or_default().push((order, f.clone()));
			}
		}
		for (s, mut leads) in into {
			leads.sort();
			let shared_text = String::from_utf8_lossy(&out[&s]).into_owned();
			let lead_texts: Vec<(Vec<String>, String)> = leads.iter().map(|(_, f)| (header_races(&out[f]), String::from_utf8_lossy(&out[f]).into_owned())).collect();
			let Some(merged) = crate::lead_in::merge_lead_ins(&shared_text, &lead_texts) else { continue };
			let sid = guide_id(&s).to_string();
			let lead_ids: Vec<String> = leads.iter().map(|(_, f)| guide_id(f).to_string()).collect();
			// (The legs move to the merged guide's steps between the same two places; a step whose
			// leg in starts at a step some of its players never see has none: Orcs at the Crossroads
			// do not come from the Trolls' own step before it.)
			let sources: Vec<(Value, &str)> = std::iter::once((legs_out.remove(&sid), shared_text.as_str()))
				.chain(lead_ids.iter().zip(&lead_texts).map(|(id, (_, t))| (legs_out.remove(id), t.as_str())))
				.filter_map(|(l, t)| l.map(|l| (l, t)))
				.collect();
			if !sources.is_empty() {
				if gdata.is_none() {
					gdata = Some(forge_guide::project::load_project_data(data, &mut forge_guide::diag::Diagnostics::new())?);
				}
				let d = gdata.as_ref().expect("loaded");
				let new = compile_guide(&s, &merged, d).ok_or_else(|| format!("{s}: the guide with its lead-ins merged does not compile"))?;
				let mut steps = serde_json::Map::new();
				for (l, t) in &sources {
					let old = compile_guide(&s, t, d).ok_or_else(|| format!("{s}: a lead-in merged into it does not compile"))?;
					for (k, v) in rekey_legs(l, &old, &new, &d.map_frames)["steps"].as_object().into_iter().flatten() {
						steps.entry(k.clone()).or_insert_with(|| v.clone());
					}
				}
				for k in legs_across_races(&step_audiences(&new, &d.map_frames)) {
					steps.remove(&k.to_string());
				}
				legs_out.insert(sid.clone(), json!({ "hash": forge_guide::bake::guide_hash(&new, &d.map_frames), "steps": steps }));
			}
			for (_, f) in &leads {
				out.remove(f);
			}
			out.insert(s.clone(), merged.into_bytes());
			// (The guides that led to a lead-in lead to the shared guide.)
			let ids: Vec<(String, String)> = lead_ids.iter().map(|i| (i.clone(), sid.clone())).collect();
			for (_, b) in out.iter_mut().filter(|(f, _)| in_faction(f)) {
				let t = String::from_utf8_lossy(b).into_owned();
				let n = replace_ids(&t, &ids);
				if n != t {
					*b = n.into_bytes();
				}
			}
			published.merged.push((sid, lead_ids));
		}
	}
	for f in seed.keys().filter(|f| !seen_seed.contains(*f)) {
		errors.push(format!("{f}: a seed guide no start's tree has"));
	}
	if !errors.is_empty() {
		return Err(format!("nothing published:\n  {}", errors.join("\n  ")));
	}
	let guides = checkout.join("guides");
	// What an earlier publish wrote, or the seed left in guides/, and this one does not write.
	let old: std::collections::BTreeSet<String> = generated_files(checkout)?.into_iter().chain(seed.keys().cloned()).filter(|f| f.ends_with(".guide")).collect();
	for f in old.iter().filter(|f| !out.contains_key(*f)) {
		let p = guides.join(f);
		if std::fs::remove_file(&p).is_ok() {
			let _ = p.parent().map(std::fs::remove_dir);
		}
	}
	let mut hashes = BTreeMap::new();
	for (f, body) in &out {
		let mut b = Vec::with_capacity(HEADER.len() + 1 + body.len());
		b.extend_from_slice(HEADER.as_bytes());
		b.push(b'\n');
		b.extend_from_slice(body);
		write(&guides.join(f), &b)?;
		hashes.insert(f.clone(), sha256(&b));
	}
	published.guides = out.len();
	published.legs = legs_out.len();
	let legs = guides.join(crate::bake::LEGS_FILE);
	match grid {
		Some((g, _)) if !legs_out.is_empty() => {
			let b = serde_json::to_string_pretty(&json!({ "schema": 1, "grid": g, "legs": legs_out })).map_err(|e| e.to_string())?;
			write(&legs, b.as_bytes())?;
			hashes.insert(crate::bake::LEGS_FILE.to_string(), sha256(b.as_bytes()));
		}
		_ => {
			let _ = std::fs::remove_file(&legs);
		}
	}
	// The ids the races' copies replaced and the lead-ins merged away, for saved tabs
	// (docs/PACK_FORMAT.md, "Retired guides").
	let retired_file = guides.join("retired.json");
	let mut retired: std::collections::BTreeSet<String> =
		if retired_file.is_file() { serde_json::from_slice(&read(&retired_file)?).map_err(|e| format!("{}: {e}", retired_file.display()))? } else { Default::default() };
	retired.extend(published.split.iter().map(|(id, _)| id.clone()));
	retired.extend(published.merged.iter().flat_map(|(_, ids)| ids.iter().cloned()));
	retired.retain(|id| !out.contains_key(&format!("{id}.guide")));
	if !retired.is_empty() {
		write(&retired_file, (serde_json::to_string_pretty(&retired).map_err(|e| e.to_string())? + "\n").as_bytes())?;
	}
	let doc = json!({
		"about": "Guides written by forge build (`forge guide publish`), each with its SHA-256. Never edit them, or this file: CI fails a pull request that does (tests/generated-guides.test.js). docs/FORGE.md, \"Fixing a generated guide\", says where a fix goes.",
		"files": hashes,
	});
	write(&checkout.join(GENERATED), (serde_json::to_string_pretty(&doc).map_err(|e| e.to_string())? + "\n").as_bytes())?;
	Ok(published)
}

/// Every generated guide or seed file whose bytes no longer match its manifest, as
/// `"<path>: edited"` or `"<path>: missing"` (empty: nothing was edited).
pub fn check(checkout: &Path) -> Result<Vec<String>, String> {
	let mut out = Vec::new();
	for (manifest, base) in [(GENERATED, "guides"), (SEED_MANIFEST, SEED_DIR)] {
		let m = checkout.join(manifest);
		if !m.is_file() {
			continue;
		}
		let v: Value = serde_json::from_slice(&read(&m)?).map_err(|e| format!("{}: {e}", m.display()))?;
		for (f, h) in v["files"].as_object().into_iter().flatten() {
			let p = checkout.join(base).join(f);
			match std::fs::read(&p) {
				Err(_) => out.push(format!("{base}/{f}: missing")),
				Ok(b) if Some(sha256(&b).as_str()) != h.as_str() => out.push(format!("{base}/{f}: edited")),
				Ok(_) => {}
			}
		}
	}
	Ok(out)
}

