#[test]
fn recompiling_replaces_the_old_pack_xml_layout_and_keeps_files_compile_does_not_own() {
	for marker in ["Generated by `node tools/polestar.js compile`", "Generated by `forge guide compile`"] {
		let out = tmp("relayout");
		std::fs::create_dir_all(out.join("Guides/old")).unwrap();
		std::fs::write(out.join("Guides/old/gone.lua"), "-- stale\n").unwrap();
		std::fs::write(out.join("Pack.xml"), format!("<Ui>\n\t<!-- {marker}. Do not edit. -->\n</Ui>\n")).unwrap();
		std::fs::write(out.join("Polestar_Guides.toc"), "## Title: old\n\nPack.xml\n").unwrap();
		std::fs::write(out.join("README.txt"), "kept\n").unwrap();
		let o = out.to_str().unwrap();
		let r = forge(&["compile", "--guides", &guides_dir(), "--data", &data_dir(), "--out", o]);
		assert_eq!(r.status, 0, "{marker}: {}", r.stderr);
		assert!(!out.join("Guides").exists());
		assert!(!out.join("Pack.xml").exists());
		assert!(re(r"(?m)^## X-Polestar-Pack: guides$").is_match(&std::fs::read_to_string(out.join("Polestar_Guides.toc")).unwrap()));
		assert_eq!(std::fs::read_to_string(out.join("README.txt")).unwrap(), "kept\n");
		// Recompiling into the folder it generated works.
		assert_eq!(forge(&["compile", "--guides", &guides_dir(), "--data", &data_dir(), "--out", o]).status, 0);
	}
}

