/// Heights: compile reports how many NPC and object goals, candidates and spawn spots got z;
/// LICENSE-DATA.txt then names classic-db (forge-guide tests/dsl_heights.rs has the rest).
#[test]
fn compile_reports_how_many_npc_and_object_goals_candidates_and_spawn_spots_got_z_license_data_then_names_classic_db() {
	let data = tmp("heights-data");
	for e in std::fs::read_dir(data_dir()).unwrap().flatten() {
		std::fs::copy(e.path(), data.join(e.file_name())).unwrap();
	}
	let d = data.to_str().unwrap();
	let none_out = tmp("heights-none");
	let none = forge(&["compile", "--guides", &guides_dir(), "--data", d, "--out", none_out.to_str().unwrap()]);
	assert_eq!(none.status, 0, "{}", none.stderr);
	assert!(none.stdout.ends_with("\nheights: none (no spawnz.json in the reference data; `forge data build` writes it)\n"), "{}", none.stdout);
	assert!(!std::fs::read_to_string(none_out.join("LICENSE-DATA.txt")).unwrap().contains("classic-db"));
	// Marshal McBride's world point (forge-guide heights::world_point of 48.92,41.61 on uiMap 1429).
	let fixture = forge_guide::data::load_data(Path::new(&data_dir())).unwrap();
	let p = forge_guide::heights::world_point(&fixture, &forge_guide::js::parse_json(r#"{"map":1429,"x":48.92,"y":41.61,"f":"e"}"#).unwrap());
	std::fs::write(data.join("spawnz.json"), format!(r#"{{"npc":{{"197":[[1415,{},{},12.3]]}},"object":{{}}}}"#, p.get("wx").num(), p.get("wy").num())).unwrap();
	let z_out = tmp("heights-z");
	let some = forge(&["compile", "--guides", &guides_dir(), "--data", d, "--out", z_out.to_str().unwrap()]);
	assert_eq!(some.status, 0, "{}", some.stderr);
	let m = re(r"\nheights: (\d+) of (\d+) NPC or object goals?, (\d+) of (\d+) smart-target candidates? and (\d+) of (\d+) spawn spots? got z \(spawnz\.json\)\n$")
		.captures(&some.stdout)
		.unwrap_or_else(|| panic!("{}", some.stdout));
	let (got, of): (u32, u32) = (m[1].parse().unwrap(), m[2].parse().unwrap());
	assert!(got > 0 && got < of, "{got} of {of}");
	let notice = std::fs::read_to_string(z_out.join("LICENSE-DATA.txt")).unwrap();
	assert!(
		re(
			r"CMaNGOS classic-db: creature and gameobject spawn heights\n-+\nURL: https://raw\.githubusercontent\.com/cmangos/classic-db/[\s\S]*License: GPL-3\.0; spawn heights \(z\) only, used as facts"
		)
		.is_match(&notice),
		"{notice}"
	);
	assert_eq!(notice.matches("CMaNGOS classic-db").count(), 1, "named once");
}

