//! `forge guide compile|lint` on the compiler's fixtures (tests/fixtures/dsl): output byte-identical across
//! runs, errors block writes, drafts only on request, the old layout replaced and a folder that is not a
//! generated addon refused, lint's checks and exit codes, the missing-data error, --no-data, and the
//! compile summary lines.

use std::path::{Path, PathBuf};
use std::process::{Command, Output};

fn repo() -> PathBuf {
	Path::new(env!("CARGO_MANIFEST_DIR")).join("../../..").canonicalize().unwrap()
}

fn guides_dir() -> String {
	repo().join("tests/fixtures/dsl/guides").to_string_lossy().into_owned()
}

fn data_dir() -> String {
	repo().join("tests/fixtures/dsl/data").to_string_lossy().into_owned()
}

/// A fresh scratch folder.
fn tmp(name: &str) -> PathBuf {
	let d = Path::new(env!("CARGO_TARGET_TMPDIR")).join("guide-cli").join(name);
	let _ = std::fs::remove_dir_all(&d);
	std::fs::create_dir_all(&d).unwrap();
	d
}

struct Run {
	status: i32,
	stdout: String,
	stderr: String,
}

fn forge(args: &[&str]) -> Run {
	let Output { status, stdout, stderr } = Command::new(env!("CARGO_BIN_EXE_forge")).current_dir(repo()).arg("guide").args(args).output().unwrap();
	Run { status: status.code().unwrap_or(-1), stdout: String::from_utf8(stdout).unwrap(), stderr: String::from_utf8(stderr).unwrap() }
}

fn tree(dir: &Path) -> std::collections::BTreeMap<String, Vec<u8>> {
	fn walk(d: &Path, base: &Path, out: &mut std::collections::BTreeMap<String, Vec<u8>>) {
		for e in std::fs::read_dir(d).unwrap().flatten() {
			let p = e.path();
			if p.is_dir() {
				walk(&p, base, out);
			} else {
				out.insert(p.strip_prefix(base).unwrap().to_string_lossy().replace('\\', "/"), std::fs::read(&p).unwrap());
			}
		}
	}
	let mut out = Default::default();
	walk(dir, dir, &mut out);
	out
}

fn re(p: &str) -> regex::Regex {
	regex::Regex::new(p).unwrap()
}

#[test]
fn compile_output_is_byte_identical_across_runs_and_skips_drafts() {
	let (a, b) = (tmp("same-a"), tmp("same-b"));
	for out in [&a, &b] {
		// Our pack's folder by its name, so its faction part is written beside it.
		let r = forge(&["compile", "--guides", &guides_dir(), "--data", &data_dir(), "--out", out.join("Polestar_Guides").to_str().unwrap()]);
		assert_eq!(r.status, 0, "{}{}", r.stderr, r.stdout);
	}
	let (ta, tb) = (tree(&a), tree(&b));
	assert_eq!(
		ta.keys().collect::<Vec<_>>(),
		[
			"Polestar_Guides/Guides.lua",
			"Polestar_Guides/LICENSE-DATA.txt",
			"Polestar_Guides/MapFrames.lua",
			"Polestar_Guides/Pack.lua",
			"Polestar_Guides/Polestar_Guides.toc",
			"Polestar_Guides_Alliance/Guides.lua",
			"Polestar_Guides_Alliance/LICENSE-DATA.txt",
			"Polestar_Guides_Alliance/Polestar_Guides_Alliance.toc",
		]
	);
	// The Alliance guides are in the Alliance part (format 8).
	let guides = String::from_utf8_lossy(&ta["Polestar_Guides_Alliance/Guides.lua"]);
	assert!(re(r"-- Source: forever/alliance/human/01-northshire\.guide\n[\s\S]*-- Source: forever/alliance/human/02-elwynn\.guide\n").is_match(&guides));
	assert_eq!(ta, tb, "the files differ between runs");
	// Every file names the forge command that rebuilds it.
	assert!(String::from_utf8_lossy(&ta["Polestar_Guides/Polestar_Guides.toc"]).contains("# Generated by `forge guide compile` from pack.json and the .guide files."));
}

