#[test]
fn without_reference_data_lint_and_compile_stop_with_one_error_before_reading_any_guide() {
	let missing = tmp("nodata").join("nope");
	let empty = tmp("nodata-empty");
	for dir in [&missing, &empty] {
		let d = dir.to_str().unwrap();
		let lint = forge(&["lint", "--guides", &guides_dir(), "--data", d]);
		assert_eq!(lint.status, 1, "{}", lint.stderr);
		assert_eq!(lint.stdout, "");
		let errors: Vec<&str> = lint.stderr.lines().filter(|l| l.contains("error:")).collect();
		assert_eq!(errors.len(), 1, "{}", lint.stderr);
		let what = if dir == &missing { "does not exist" } else { "holds none of quests.json" };
		// The folder as the diagnostics show it: relative to the working directory (the checkout) when inside it.
		let shown = dir.strip_prefix(repo()).map_or(d.to_string(), |r| r.to_string_lossy().into_owned());
		assert!(errors[0].starts_with(&format!("{shown}: error: no reference data: the folder {what}")), "{}", errors[0]);
		assert!(lint.stderr.contains("hint: run `forge data build`, or pass --data <dir>; --no-data"), "{}", lint.stderr);
		assert!(lint.stderr.ends_with("\nlint failed: no reference data\n"), "{}", lint.stderr);
		assert!(!lint.stderr.contains(".guide"));
	}
	let out = tmp("nodata-out");
	let c = forge(&["compile", "--guides", &guides_dir(), "--data", missing.to_str().unwrap(), "--out", out.to_str().unwrap(), "--format", "json"]);
	assert_eq!(c.status, 1, "{}", c.stderr);
	let doc: serde_json::Value = serde_json::from_str(&c.stdout).unwrap();
	assert_eq!([&doc["ok"], &doc["errors"], &doc["warnings"]], [&serde_json::json!(false), &serde_json::json!(1), &serde_json::json!(0)]);
	assert_eq!(doc["diagnostics"].as_array().unwrap().len(), 1);
	let shown = missing.strip_prefix(repo()).map_or(missing.to_string_lossy().into_owned(), |r| r.to_string_lossy().into_owned());
	assert_eq!(doc["diagnostics"][0]["file"], shown.as_str());
	assert_eq!(std::fs::read_dir(&out).unwrap().count(), 0);
}

