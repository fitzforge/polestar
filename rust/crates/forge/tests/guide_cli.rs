/// The `dataHash` lint expects of a world built now from `data` (forge_world::inputs, the checkout's other
/// inputs).
fn data_hash(data: &Path) -> String {
	let mut inputs = forge_world::inputs::world_inputs(&repo()).unwrap();
	for (k, v) in inputs.iter_mut() {
		if forge_world::inputs::WORLD_DATA_FILES.iter().any(|f| format!("{f}.json") == *k) {
			*v = std::fs::read(data.join(&*k)).map(|b| forge_core::content_key(&b)).unwrap_or_else(|_| "-".into());
		}
	}
	forge_world::inputs::inputs_hash(&inputs)
}

#[test]
fn lint_applies_the_solo_policy_from_the_cached_world_in_sim_built_from_the_same_data_by_the_current_builder() {
	let sim = tmp("sim");
	let world = |hash: &str| format!(r#"{{"dataHash":"{hash}","excluded":[{{"id":5261,"title":"Eagan Peltskinner","reason":"dungeon quest","category":"dungeon"}}]}}"#);
	std::fs::write(sim.join("world-alliance.json"), world(&data_hash(Path::new(&data_dir())))).unwrap();
	let lint = |more: &[&str]| {
		let mut a = vec!["lint", "--guides", guides_dir_str(), "--data", data_dir_str()];
		a.extend_from_slice(more);
		forge(&a)
	};
	let r = lint(&["--sim", sim.to_str().unwrap()]);
	assert_eq!(r.status, 0, "{}", r.stderr);
	assert!(re(r"01-northshire\.guide:14: warning: quest 5261 \(Eagan Peltskinner\) is excluded from solo leveling \(dungeon: dungeon quest\)").is_match(&r.stderr), "{}", r.stderr);
	// Without --sim, other data never reads the default cache.
	assert!(!lint(&[]).stderr.contains("excluded from solo"));
	// A world built from other data is skipped (no warning from it).
	std::fs::write(sim.join("world-alliance.json"), world("stale")).unwrap();
	assert!(!lint(&["--sim", sim.to_str().unwrap()]).stderr.contains("excluded from solo"));
}

