//! `forge guide renumber` on a small checkout (a git repository in a scratch folder): the table from the guides'
//! route and titles, the dry run that lists every change and writes nothing, the change itself (files moved with
//! git, every reference rewritten, a fragment both factions have told apart by its file, line or the lines above,
//! the generated guides' and the seed's manifests re-hashed, guides/renamed.json written, released history and
//! the compiled addon left alone), and a second run that changes nothing.

use std::path::{Path, PathBuf};
use std::process::Command;

fn tmp(name: &str) -> PathBuf {
	let d = Path::new(env!("CARGO_TARGET_TMPDIR")).join("guide-renumber").join(name);
	let _ = std::fs::remove_dir_all(&d);
	std::fs::create_dir_all(&d).unwrap();
	d
}

fn write(dir: &Path, rel: &str, text: &str) {
	let p = dir.join(rel);
	std::fs::create_dir_all(p.parent().unwrap()).unwrap();
	std::fs::write(p, text).unwrap();
}

fn read(dir: &Path, rel: &str) -> String {
	std::fs::read_to_string(dir.join(rel)).unwrap_or_else(|e| panic!("{rel}: {e}"))
}

fn sha256(text: &str) -> String {
	use sha2::Digest;
	sha2::Sha256::digest(text.as_bytes()).iter().map(|b| format!("{b:02x}")).collect()
}

fn git(dir: &Path, args: &[&str]) -> String {
	let o = Command::new("git").arg("-C").arg(dir).args(["-c", "user.name=Test", "-c", "user.email=test@example.invalid", "-c", "commit.gpgsign=false"]).args(args).output().unwrap();
	assert!(o.status.success(), "git {args:?}: {}", String::from_utf8_lossy(&o.stderr));
	String::from_utf8(o.stdout).unwrap()
}

struct Run {
	status: i32,
	stdout: String,
	stderr: String,
}

fn forge(dir: &Path, args: &[&str]) -> Run {
	let o = Command::new(env!("CARGO_BIN_EXE_forge")).current_dir(dir).arg("guide").arg("renumber").args(args).output().unwrap();
	Run { status: o.status.code().unwrap_or(-1), stdout: String::from_utf8(o.stdout).unwrap(), stderr: String::from_utf8(o.stderr).unwrap() }
}

fn guide(id: &str, title: &str, head: &str, body: &str) -> String {
	format!("# Generated by forge build.\nguide {id}\ntitle {title}\n{head}levels 10-20\nzone {title}\n\nstep One\n{body}  accept 7\n")
}

/// The checkout: Horde's start hands over to 03-pinewood, then 02-plains, then the band's 02-hills and 01-marsh;
/// the Alliance's start to 02-coast and their band's 01-marsh, which stays. Translations, seed copies, fix records,
/// a test, the changelog and a compiled file name the guides.
fn checkout(name: &str) -> PathBuf {
	let d = tmp(name);
	write(&d, "forever-db/corrections/quests.json", "{}\n");
	write(&d, "guides/pack.json", "{\"id\": \"guides\"}\n");
	write(&d, "guides/retired.json", "[\n  \"forever/horde/orc/02-old\"\n]\n");
	let guides = [
		("forever/horde/orc/01-valley", guide("forever/horde/orc/01-valley", "Valley", "race Orc\nnext forever/horde/03-pinewood\n", "")),
		("forever/horde/03-pinewood", guide("forever/horde/03-pinewood", "Pinewood", "next forever/horde/02-plains\n", "  tip Then 02-plains, the next guide.\n")),
		("forever/horde/02-plains", guide("forever/horde/02-plains", "The Plains", "next forever/horde/30-40/02-hills\n", "")),
		("forever/horde/30-40/02-hills", guide("forever/horde/30-40/02-hills", "Hills & Pinewood Forest", "next forever/horde/30-40/01-marsh\n", "  tip 30-40/01-marsh comes next.\n")),
		("forever/horde/30-40/01-marsh", guide("forever/horde/30-40/01-marsh", "Marsh", "", "")),
		("forever/alliance/human/01-shire", guide("forever/alliance/human/01-shire", "Shire", "race Human\nnext forever/alliance/02-coast\n", "")),
		("forever/alliance/02-coast", guide("forever/alliance/02-coast", "Coast", "next forever/alliance/30-40/01-marsh\n", "  tip 30-40/01-marsh next.\n")),
		("forever/alliance/30-40/01-marsh", guide("forever/alliance/30-40/01-marsh", "Marsh", "", "")),
	];
	let mut generated = String::from("{\n  \"about\": \"Generated guides.\",\n  \"files\": {\n");
	let mut seed = String::from("{\n  \"about\": \"The seed.\",\n  \"from\": {\n    \"commit\": \"abc\"\n  },\n  \"files\": {\n");
	let mut sorted: Vec<&(&str, String)> = guides.iter().collect();
	sorted.sort_by_key(|(id, _)| format!("{id}.guide"));
	for (i, (id, text)) in sorted.iter().enumerate() {
		write(&d, &format!("guides/{id}.guide"), text);
		write(&d, &format!("forge/seed/guides/{id}.guide"), text);
		let comma = if i + 1 < sorted.len() { "," } else { "" };
		generated.push_str(&format!("    \"{id}.guide\": \"{}\"{comma}\n", sha256(text)));
		seed.push_str(&format!("    \"{id}.guide\": \"{}\"{comma}\n", sha256(text)));
	}
	generated.push_str("  }\n}\n");
	seed.push_str("  }\n}\n");
	write(&d, "guides/GENERATED.json", &generated);
	write(&d, "forge/seed/SEED.json", &seed);
	write(
		&d,
		"guides/locales/deDE/forever/horde/03-pinewood.lua",
		"-- German (deDE): the guide forever/horde/03-pinewood (forever/horde/03-pinewood.guide).\nreturn {\n\t[\"Then 02-plains, the next guide.\"] = \"Dann 02-plains, der nächste Guide.\",\n}\n",
	);
	write(
		&d,
		"data/route-fixes.json",
		"{\n\t\"fixes\": [\n\t\t{\n\t\t\t\"guide\": \"forever/horde/02-plains\",\n\t\t\t\"faction\": \"Horde\",\n\t\t\t\"why\": \"On 30-40/01-marsh first.\",\n\t\t\t\"note\": \"After horde/03-pinewood.\"\n\t\t},\n\t\t{\n\t\t\t\"why\": \"30-40/01-marsh, by either side.\"\n\t\t}\n\t]\n}\n",
	);
	write(
		&d,
		"tests/route.test.js",
		"test('horde', () => {\n\tconst H = (g) => `forever/horde/${g}.guide`;\n\tcheck(H('30-40/01-marsh'));\n\tcheck('forever/horde/03-pinewood.guide');\n});\ntest('alliance', () => {\n\tconst A = (g) => `forever/alliance/${g}.guide`;\n\tcheck(A('30-40/01-marsh'));\n});\n",
	);
	write(&d, "CHANGELOG.md", "## 0.3.0\n- forever/horde/03-pinewood: shipped under this id.\n");
	write(&d, "addon/Polestar_Guides_Horde/Guides.lua", "-- compiled: forever/horde/03-pinewood\n");
	git(&d, &["init", "-q"]);
	git(&d, &["add", "-A"]);
	git(&d, &["commit", "-q", "-m", "fixture"]);
	d
}

const TABLE: [(&str, &str); 5] = [
	("forever/horde/03-pinewood", "forever/horde/01-pinewood"),
	("forever/horde/02-plains", "forever/horde/02-the-plains"),
	("forever/horde/30-40/02-hills", "forever/horde/30-40/01-hills-pinewood"),
	("forever/horde/30-40/01-marsh", "forever/horde/30-40/02-marsh"),
	("forever/alliance/02-coast", "forever/alliance/01-coast"),
];

#[test]
fn the_plan_numbers_each_folder_in_route_order_and_names_the_title_s_zones() {
	let d = checkout("plan");
	let r = forge(&d, &["--plan", "--out", "renames.json"]);
	assert_eq!(r.status, 0, "{}", r.stderr);
	assert!(r.stdout.contains("  forever/horde/orc/01-valley\n") && r.stdout.contains("  forever/horde/03-pinewood -> forever/horde/01-pinewood\n"), "{}", r.stdout);
	let doc: serde_json::Value = serde_json::from_str(&read(&d, "renames.json")).unwrap();
	let table: Vec<(String, String)> = doc["renames"].as_object().unwrap().iter().map(|(k, v)| (k.clone(), v.as_str().unwrap().to_string())).collect();
	assert_eq!(table, TABLE.iter().map(|(a, b)| (a.to_string(), b.to_string())).collect::<Vec<_>>(), "Horde, then the Alliance, in route order");
	// --check: the same guides match; a title changed since does not.
	assert_eq!(forge(&d, &["--plan", "--check", "renames.json"]).status, 0);
	let p = d.join("guides/forever/alliance/02-coast.guide");
	std::fs::write(&p, read(&d, "guides/forever/alliance/02-coast.guide").replace("title Coast", "title Coast & Marsh")).unwrap();
	let r = forge(&d, &["--plan", "--check", "renames.json"]);
	assert_eq!(r.status, 1);
	assert!(r.stdout.contains("differs: forever/alliance/02-coast: renames.json says forever/alliance/01-coast, the guides now forever/alliance/01-coast-marsh"), "{}", r.stdout);
}

#[test]
fn the_map_moves_rewrites_and_records_in_one_go_the_dry_run_lists_it_and_a_second_run_changes_nothing() {
	let d = checkout("apply");
	assert_eq!(forge(&d, &["--plan", "--out", "renames.json"]).status, 0);
	git(&d, &["add", "renames.json"]);
	git(&d, &["commit", "-q", "-m", "table"]);
	// The dry run: every change listed, nothing written.
	let dry = forge(&d, &["--map", "renames.json", "--dry-run"]);
	assert_eq!(dry.status, 0, "{}", dry.stderr);
	for line in [
		"move   guides/forever/horde/03-pinewood.guide -> guides/forever/horde/01-pinewood.guide",
		"move   guides/locales/deDE/forever/horde/03-pinewood.lua -> guides/locales/deDE/forever/horde/01-pinewood.lua",
		"move   forge/seed/guides/forever/horde/03-pinewood.guide -> forge/seed/guides/forever/horde/01-pinewood.guide",
		"edit   guides/forever/horde/01-pinewood.guide:2: forever/horde/03-pinewood -> forever/horde/01-pinewood",
		"edit   guides/forever/horde/01-pinewood.guide:4: forever/horde/02-plains -> forever/horde/02-the-plains",
		"edit   guides/forever/horde/01-pinewood.guide:9: 02-plains -> 02-the-plains",
		"edit   guides/forever/horde/30-40/01-hills-pinewood.guide:9: 30-40/01-marsh -> 30-40/02-marsh (by the path)",
		"edit   data/route-fixes.json:6: 30-40/01-marsh -> 30-40/02-marsh (by line 5)",
		"edit   data/route-fixes.json:7: horde/03-pinewood -> horde/01-pinewood",
		"edit   tests/route.test.js:3: 30-40/01-marsh -> 30-40/02-marsh (by line 2)",
		"update guides/GENERATED.json: 5 paths renamed, 7 hashes updated",
		"update forge/seed/SEED.json: 5 paths renamed, 7 hashes updated",
		"update guides/renamed.json: 5 renamed ids",
		"left   data/route-fixes.json:10: 30-40/01-marsh names forever/alliance/30-40/01-marsh or forever/horde/30-40/01-marsh",
	] {
		assert!(dry.stdout.contains(line), "missing {line:?} in:\n{}", dry.stdout);
	}
	assert!(!dry.stdout.contains("guides/forever/alliance/30-40/01-marsh.guide"), "the Alliance's 01-marsh stays: {}", dry.stdout);
	assert!(!dry.stdout.contains("CHANGELOG.md") && !dry.stdout.contains("addon/Polestar_Guides_Horde"), "released history and the compiled addon stay: {}", dry.stdout);
	assert_eq!(git(&d, &["status", "--porcelain"]), "", "the dry run writes nothing");
	// The change.
	let r = forge(&d, &["--map", "renames.json"]);
	assert_eq!(r.status, 0, "{}", r.stderr);
	assert_eq!(r.stdout, dry.stdout, "the run does what the dry run listed");
	let status = git(&d, &["status", "--porcelain"]);
	assert!(status.contains("guides/forever/horde/03-pinewood.guide -> guides/forever/horde/01-pinewood.guide"), "{status}");
	assert!(read(&d, "guides/forever/horde/orc/01-valley.guide").contains("\nnext forever/horde/01-pinewood\n"));
	let pine = read(&d, "guides/forever/horde/01-pinewood.guide");
	assert!(pine.contains("\nguide forever/horde/01-pinewood\n") && pine.contains("\nnext forever/horde/02-the-plains\n") && pine.contains("tip Then 02-the-plains, the next guide."), "{pine}");
	assert!(!d.join("guides/forever/alliance/02-coast.guide").exists());
	assert!(read(&d, "guides/forever/alliance/01-coast.guide").contains("\nnext forever/alliance/30-40/01-marsh\n"), "the Alliance's band guide keeps its id");
	assert!(read(&d, "guides/forever/alliance/01-coast.guide").contains("tip 30-40/01-marsh next."), "the Alliance's fragment, told by the path");
	assert_eq!(
		read(&d, "guides/locales/deDE/forever/horde/01-pinewood.lua"),
		"-- German (deDE): the guide forever/horde/01-pinewood (forever/horde/01-pinewood.guide).\nreturn {\n\t[\"Then 02-the-plains, the next guide.\"] = \"Dann 02-the-plains, der nächste Guide.\",\n}\n"
	);
	let fixes = read(&d, "data/route-fixes.json");
	assert!(fixes.contains("\"guide\": \"forever/horde/02-the-plains\"") && fixes.contains("\"On 30-40/02-marsh first.\"") && fixes.contains("\"After horde/01-pinewood.\"") && fixes.contains("\"30-40/01-marsh, by either side.\""), "{fixes}");
	let test = read(&d, "tests/route.test.js");
	assert!(test.contains("check(H('30-40/02-marsh'));\n\tcheck('forever/horde/01-pinewood.guide');") && test.contains("check(A('30-40/01-marsh'));"), "{test}");
	assert!(read(&d, "CHANGELOG.md").contains("forever/horde/03-pinewood: shipped under this id."));
	assert_eq!(read(&d, "addon/Polestar_Guides_Horde/Guides.lua"), "-- compiled: forever/horde/03-pinewood\n");
	assert_eq!(read(&d, "guides/retired.json"), "[\n  \"forever/horde/orc/02-old\"\n]\n");
	let renamed: serde_json::Value = serde_json::from_str(&read(&d, "guides/renamed.json")).unwrap();
	assert_eq!(renamed["forever/horde/30-40/01-marsh"], "forever/horde/30-40/02-marsh");
	assert_eq!(renamed.as_object().unwrap().len(), 5);
	// The manifests: the new paths, sorted, each with its file's hash; check-generated passes.
	let generated: serde_json::Value = serde_json::from_str(&read(&d, "guides/GENERATED.json")).unwrap();
	let keys: Vec<&String> = generated["files"].as_object().unwrap().keys().collect();
	let mut sorted = keys.clone();
	sorted.sort();
	assert_eq!(keys, sorted);
	assert_eq!(generated["files"]["forever/horde/01-pinewood.guide"], sha256(&pine));
	let seed: serde_json::Value = serde_json::from_str(&read(&d, "forge/seed/SEED.json")).unwrap();
	assert_eq!(seed["from"]["commit"], "abc");
	assert_eq!(seed["files"]["forever/horde/01-pinewood.guide"], sha256(&read(&d, "forge/seed/guides/forever/horde/01-pinewood.guide")));
	let check = Command::new(env!("CARGO_BIN_EXE_forge")).current_dir(&d).args(["guide", "check-generated"]).output().unwrap();
	assert!(check.status.success(), "{}", String::from_utf8_lossy(&check.stderr));
	// A second run: nothing to change.
	git(&d, &["add", "-A"]);
	git(&d, &["commit", "-q", "-m", "renumbered"]);
	let again = forge(&d, &["--map", "renames.json"]);
	assert_eq!(again.status, 0, "{}", again.stderr);
	assert!(again.stderr.contains("nothing to change, the table is applied"), "{}", again.stderr);
	assert!(again.stdout.lines().all(|l| l.starts_with("done   ") || l.starts_with("left   ")), "{}", again.stdout);
	assert_eq!(git(&d, &["status", "--porcelain"]), "");
}

#[test]
fn a_table_that_cannot_apply_writes_nothing() {
	let d = checkout("refused");
	let table = |pairs: &[(&str, &str)]| {
		let body: Vec<String> = pairs.iter().map(|(a, b)| format!("\"{a}\": \"{b}\"")).collect();
		write(&d, "bad.json", &format!("{{\"renames\": {{{}}}}}", body.join(", ")));
		forge(&d, &["--map", "bad.json"])
	};
	let moved = table(&[("forever/horde/03-pinewood", "forever/horde/30-40/03-pinewood")]);
	assert!(moved.status == 1 && moved.stderr.contains("a renumber keeps a guide in its folder"), "{}", moved.stderr);
	let swap = table(&[("forever/horde/03-pinewood", "forever/horde/02-plains"), ("forever/horde/02-plains", "forever/horde/03-pinewood")]);
	assert!(swap.status == 1 && swap.stderr.contains("another guide's old id"), "{}", swap.stderr);
	let retired = table(&[("forever/horde/orc/01-valley", "forever/horde/orc/02-old")]);
	assert!(retired.status == 1 && retired.stderr.contains("is in guides/retired.json"), "{}", retired.stderr);
	// A hand edit to a generated guide: the new hashes would bless it.
	std::fs::write(d.join("guides/forever/horde/02-plains.guide"), "# hand edit\n").unwrap();
	let edited = table(&TABLE);
	assert!(edited.status == 1 && edited.stderr.contains("check-generated fails before the renumber"), "{}", edited.stderr);
	git(&d, &["checkout", "--", "guides/forever/horde/02-plains.guide"]);
	assert_eq!(git(&d, &["status", "--porcelain"]), "?? bad.json\n", "nothing written");
}
