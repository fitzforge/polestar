//! Polestar's own pack written for memory (format 8; project.rs build_pack_files, emit.rs pack_spots): each
//! faction's guides in a load-on-demand part beside the pack, and a goal's spawn spots as one string. A
//! community pack is written as before. Loading and reading back: forge-addontest's guides-memory.rs.

use crate::common;
use common::*;
use forge_guide::format::{needs, PACKED_FORMAT};
use serde_json::json;

fn guide(id: &str, faction: Option<&str>) -> forge_guide::js::V {
	let mut g = json!({
		"id": id, "pack": "guides", "title": "Elwynn Forest", "category": "Leveling", "minLevel": 1, "maxLevel": 10,
		"steps": [{ "title": "Wolves", "goals": [
			{ "t": "kill", "npc": 299, "npcName": "Young Wolf", "count": 6, "map": 1429, "x": 43.5, "y": 9.2,
				"spots": [{ "x": 43.5, "y": 9.2, "r": 110, "n": 19 }, { "x": 47.4, "y": 9.7, "z": -12.5, "r": 4, "alt": true }, { "x": 50, "y": 50.25, "r": 15, "n": 2 }] },
			{ "t": "accept", "quest": 7, "title": "Kobold Camp Cleanup", "npc": 197, "map": 1429, "x": 48.17, "y": 42.95 },
		] }],
	});
	if let Some(f) = faction {
		g["faction"] = json!(f);
	}
	v(&g)
}

fn manifest(id: &str, folder: &str) -> forge_guide::js::V {
	v(&json!({ "id": id, "title": "Polestar Guides", "author": "Polestar", "version": "1.0.0", "license": "GPL-3.0-only", "folder": folder }))
}

fn guides() -> Vec<forge_guide::js::V> {
	vec![guide("forever/class/any", None), guide("forever/alliance/elwynn", Some("Alliance")), guide("forever/horde/durotar", Some("Horde"))]
}

#[test]
fn our_pack_ships_each_faction_s_guides_in_a_part_and_packs_spawn_spots_in_format_8() {
	let files = pack_files(&guides(), &manifest("guides", "Polestar_Guides"), &fixture_data());
	let main = &files["Guides.lua"];
	assert_match(main, r#"id = "forever/class/any""#);
	assert_no_match(main, "forever/alliance/elwynn|forever/horde/durotar");
	assert_match(&files["../Polestar_Guides_Alliance/Guides.lua"], r#"id = "forever/alliance/elwynn""#);
	assert_no_match(&files["../Polestar_Guides_Alliance/Guides.lua"], "forever/horde|forever/class");
	assert_match(&files["../Polestar_Guides_Horde/Guides.lua"], r#"id = "forever/horde/durotar""#);
	assert_match(
		&files["../Polestar_Guides_Horde/Polestar_Guides_Horde.toc"],
		r"## LoadOnDemand: 1\n## Dependencies: Polestar, Polestar_Guides\n## X-Polestar-Part: guides\n## X-Polestar-Faction: Horde\n## X-License: GPL-3.0-only\n# Generated by `forge guide compile`[^\n]*\n\nGuides.lua\n$",
	);
	// Spots: x, y, z, r, n, alt (as 1); absent values empty, trailing ones dropped.
	for text in [main, &files["../Polestar_Guides_Alliance/Guides.lua"]] {
		assert_match(text, r#"x = 43\.5, y = 9\.2, spotsPacked = "43\.5,9\.2,,110,19;47\.4,9\.7,-12\.5,4,,1;50,50\.25,,15,2" \}"#);
		assert_no_match(text, r"spots = \{");
	}
	assert_eq!(PACKED_FORMAT, 8);
	assert_eq!(needs(PACKED_FORMAT), Some("0.3.0"));
	assert_match(&files["Polestar_Guides.toc"], r"## X-Polestar-Format: 8\n## X-Polestar-Needs: 0\.3\.0\n");
	assert_match(&files["Pack.lua"], r"format = 8,");
}

#[test]
fn a_community_pack_keeps_its_guides_together_and_its_spots_as_tables() {
	let files = pack_files(&guides(), &manifest("joe-routes", "PolestarPack_JoesRoutes"), &fixture_data());
	assert!(files.keys().all(|k| !k.starts_with("../")), "no part: {:?}", files.keys().collect::<Vec<_>>());
	let main = &files["Guides.lua"];
	assert_match(main, "forever/alliance/elwynn");
	assert_match(main, r"spots = \{ \{ x = 43\.5, y = 9\.2, r = 110, n = 19 \}, \{ x = 47\.4, y = 9\.7, z = -12\.5, r = 4, alt = true \}");
	assert_no_match(main, "spotsPacked");
	assert_no_match(&files["PolestarPack_JoesRoutes.toc"], "X-Polestar-Format: 8");
}

#[test]
fn our_pack_with_baked_legs_is_format_8_its_legs_in_the_race_parts_beside_the_faction_part() {
	let list = guides();
	list[1].set_hidden("_legs", v(&json!({ "1": "CgA" })));
	list[1].set_hidden("_legsGrid", "test");
	let files = pack_files(&list, &manifest("guides", "Polestar_Guides"), &fixture_data());
	assert_match(&files["Polestar_Guides.toc"], r"## X-Polestar-Format: 8\n");
	assert_match(&files["Pack.lua"], r"format = 8,");
	assert_match(&files["../Polestar_Guides_Alliance/Guides.lua"], r#"id = "forever/alliance/elwynn""#);
	// The faction's guide has no race part: each Alliance race gets one with Legs.lua only.
	assert_match(&files["../Polestar_Guides_Human/Polestar_Guides_Human.toc"], r"## X-Polestar-Race: Human\n[\s\S]*\n\nLegs\.lua\n$");
	// Like the faction parts: in Polestar's AddOns-list category and group, named in every client language.
	let human = &files["../Polestar_Guides_Human/Polestar_Guides_Human.toc"];
	assert_match(human, r"\n## Title-deDE: Polestar Guides \(Mensch\)\n## Notes-deDE: [^\n]*Mensch[^\n]*\n");
	assert_match(human, r"\n## Title-zhTW: Polestar 指南（人類）\n");
	assert_match(human, r"\n## Category: Polestar\n## Group: Polestar\n## LoadOnDemand: 1\n");
	for race in forge_guide::races::RACE_FILES {
		assert_eq!(forge_guide::toc::toc_lines(&format!("Polestar_Guides_{race}")).len(), 18, "{race}");
	}
	assert!(!files.contains_key("../Polestar_Guides_Human/Guides.lua"));
	assert_match(&files["../Polestar_Guides_Human/Legs.lua"], r#"Polestar\.RegisterLegs\("guides", "test", \{\n\t\["forever/alliance/elwynn"\] = \{ \[1\] = "CgA" \},\n\}\)"#);
	assert!(!files.contains_key("../Polestar_Guides_Orc/Legs.lua"), "no Horde race carries the Alliance guide's legs");
	assert_match(&files["LICENSE-DATA.txt"], r"Credit: Leffe's navigation maps\.");
	// Each faction part carries the same notice as Polestar_Guides, the Leffe credit included.
	assert_eq!(files["../Polestar_Guides_Alliance/LICENSE-DATA.txt"], files["LICENSE-DATA.txt"]);
}

#[test]
fn a_faction_part_the_build_no_longer_has_is_removed_another_folder_of_that_name_is_refused() {
	let addons = scratch("faction-parts-addons");
	let out = addons.join("Polestar_Guides");
	let write = |guides: &[forge_guide::js::V]| {
		let files = forge_guide::project::build_pack_files(guides, &manifest("guides", "Polestar_Guides"), &fixture_data(), None, &forge_guide::js::V::obj(), &[], "16001", Vec::new());
		forge_guide::project::write_pack_dir(&out, &files)
	};
	write(&guides()).unwrap();
	assert!(addons.join("Polestar_Guides_Horde/Guides.lua").exists());
	write(&guides()[..2]).unwrap();
	assert!(!addons.join("Polestar_Guides_Horde").exists(), "no Horde guide left: the Horde part goes");
	assert!(addons.join("Polestar_Guides_Alliance/Guides.lua").exists());
	std::fs::create_dir(addons.join("Polestar_Guides_Horde")).unwrap();
	std::fs::write(addons.join("Polestar_Guides_Horde/mine.lua"), "-- someone else").unwrap();
	assert_match(&write(&guides()).unwrap_err(), "not a generated faction part");
}
