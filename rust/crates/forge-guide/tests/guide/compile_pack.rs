//! A pack compiles to a self-contained addon folder: the generated TOC, Pack.lua with the credits,
//! MapFrames.lua, Guides.lua with one function per guide, LICENSE-DATA.txt; and the generated-folder guard
//! (write_pack_dir, pack_dir_refusal). Loading the built folder in the addon is an addon test.

use crate::common;
use common::*;
use forge_guide::project::{core_interface, find_guide_files, pack_dir_refusal, write_pack_dir, FileContent};
use std::collections::BTreeMap;
use std::path::Path;

fn build() -> (forge_guide::js::V, BTreeMap<String, String>) {
	let dir = pack_fixture("mini");
	let (manifest, diags) = forge_guide::manifest::read_manifest(&dir, false);
	assert!(diags.is_empty());
	let manifest = manifest.unwrap();
	let data = fixture_data();
	let p = forge_guide::project::compile_project(&dir, &manifest, &data, forge_guide::diag::Diagnostics::new(), false, None);
	assert!(!p.diag.has_errors(), "{:?}", p.diag.sorted());
	let files = pack_files(&p.guides, &manifest, &data);
	(manifest, files)
}

fn as_files(files: &BTreeMap<String, String>) -> Vec<(String, FileContent)> {
	files.iter().map(|(k, v)| (k.clone(), FileContent::Text(v.clone()))).collect()
}

fn listing(dir: &Path) -> Vec<String> {
	let mut l: Vec<String> = std::fs::read_dir(dir).unwrap().flatten().map(|e| e.file_name().to_string_lossy().into_owned()).collect();
	l.sort();
	l
}

#[test]
fn the_mini_pack_builds_exactly_the_fixed_file_set() {
	let (manifest, files) = build();
	assert_eq!(manifest.get("folder").to_js_string(), "PolestarPack_MiniPack");
	assert_eq!(files.keys().collect::<Vec<_>>(), ["Guides.lua", "LICENSE-DATA.txt", "MapFrames.lua", "Pack.lua", "PolestarPack_MiniPack.toc"]);
}

