#[test]
fn write_pack_dir_refuses_a_folder_it_did_not_generate() {
	let (_, files) = build();
	let dir = scratch("cp-refuse");
	std::fs::write(dir.join("PolestarPack_MiniPack.toc"), "## Title: Mine\n\nMine.lua\n").unwrap();
	std::fs::write(dir.join("Mine.lua"), "-- mine\n").unwrap();
	let e = write_pack_dir(&dir, &as_files(&files)).unwrap_err();
	assert_match(&e, "not a generated community addon");
	assert_eq!(std::fs::read_to_string(dir.join("PolestarPack_MiniPack.toc")).unwrap(), "## Title: Mine\n\nMine.lua\n");
	assert!(!dir.join("Pack.lua").exists());
}

#[test]
fn write_pack_dir_replaces_the_old_pack_xml_layout() {
	let (_, files) = build();
	let dir = scratch("cp-oldlayout");
	std::fs::create_dir_all(dir.join("Guides/forever")).unwrap();
	std::fs::write(dir.join("Guides/forever/old.lua"), "-- old\n").unwrap();
	std::fs::write(dir.join("Pack.xml"), "<Ui>\n\t<!-- Generated by `node tools/polestar.js compile`. Do not edit. -->\n</Ui>\n").unwrap();
	std::fs::write(dir.join("PolestarPack_MiniPack.toc"), "## Title: Old\n\nPack.xml\n").unwrap();
	write_pack_dir(&dir, &as_files(&files)).unwrap();
	assert!(!dir.join("Pack.xml").exists());
	assert!(!dir.join("Guides").exists());
	assert_eq!(listing(&dir), files.keys().cloned().collect::<Vec<_>>());
	for (name, content) in &files {
		assert_eq!(&std::fs::read_to_string(dir.join(name)).unwrap(), content);
	}
}

#[test]
fn write_pack_dir_replaces_stale_files_in_a_generated_folder_and_drops_a_license_txt_the_build_no_longer_has() {
	let (_, files) = build();
	let dir = scratch("cp-stale");
	let mut stale = files.clone();
	stale.insert("Guides.lua".into(), "-- stale\n".into());
	stale.insert("Pack.lua".into(), "-- stale\n".into());
	stale.insert("LICENSE.txt".into(), "a licence the pack no longer has\n".into());
	write_pack_dir(&dir, &as_files(&stale)).unwrap();
	write_pack_dir(&dir, &as_files(&files)).unwrap();
	assert_eq!(listing(&dir), files.keys().cloned().collect::<Vec<_>>());
	for (name, content) in &files {
		assert_eq!(&std::fs::read_to_string(dir.join(name)).unwrap(), content);
	}
}

#[test]
fn one_folder_rule_an_absent_or_empty_folder_or_a_generated_one_may_be_replaced_anything_else_is_refused() {
	let (_, files) = build();
	let root = scratch("cp-rule");
	assert_eq!(pack_dir_refusal(&root.join("absent"), None), None);
	let empty = root.join("empty");
	std::fs::create_dir(&empty).unwrap();
	assert_eq!(pack_dir_refusal(&empty, None), None);
	write_pack_dir(&empty, &as_files(&files)).unwrap();
	assert_eq!(pack_dir_refusal(&empty, None), None, "a generated folder");
	let mine = root.join("mine");
	std::fs::create_dir(&mine).unwrap();
	std::fs::write(mine.join("notes.txt"), "mine\n").unwrap();
	assert_match(&pack_dir_refusal(&mine, None).unwrap(), r#"^it is not a generated community addon \(no TOC with the ".*" line\); move it away first$"#);
	let file = root.join("file");
	std::fs::write(&file, "x").unwrap();
	assert_eq!(pack_dir_refusal(&file, None).as_deref(), Some("it is not a folder"));
	assert_match(&write_pack_dir(&file, &as_files(&files)).unwrap_err(), r"refusing to write into .*file: it is not a folder");
	// A folder the JS compiler built (the legacy marker, in released packs) is ours too.
	let legacy = root.join("legacy");
	std::fs::create_dir(&legacy).unwrap();
	std::fs::write(legacy.join("X.toc"), "# Generated by `node tools/polestar.js compile` from pack.json and the .guide files. Do not edit: rebuild with that command.\n## X-Polestar-Pack: mini\n")
		.unwrap();
	assert_eq!(pack_dir_refusal(&legacy, Some("mini")), None);
	assert_match(&pack_dir_refusal(&legacy, Some("other")).unwrap(), r#"it holds the community addon "mini", not "other""#);
}

#[test]
fn a_guide_without_an_author_is_credited_to_its_packs_author_one_with_author_keeps_it() {
	let dir = scratch("cp-author");
	let header = |id: &str| format!("guide ann-routes/{id}\ntitle {id}\nfaction Alliance\nlevels 1-6\nzone Elwynn Forest\n");
	write_tree(
		&dir,
		&[
			("pack.json", r#"{"id":"ann-routes","title":"Ann Routes","author":"Ann","version":"1.0.0","license":"CC0-1.0"}"#),
			("a.guide", &format!("{}\nstep Kobold camp\n  goto 47.6,35.1 \"Kobold camp\"\n", header("a"))),
			("b.guide", &format!("{}author Bob\n\nstep Kobold camp\n  goto 47.6,35.1 \"Kobold camp\"\n", header("b"))),
		],
	);
	let (manifest, diags) = forge_guide::manifest::read_manifest(&dir, false);
	assert!(diags.is_empty(), "{diags:?}");
	let manifest = manifest.unwrap();
	let data = fixture_data();
	let p = forge_guide::project::compile_project(&dir, &manifest, &data, forge_guide::diag::Diagnostics::new(), false, None);
	assert!(!p.diag.has_errors(), "{:?}", p.diag.sorted());
	let authors: BTreeMap<String, String> = p.guides.iter().map(|g| (g.get("id").to_js_string(), g.get("author").to_js_string())).collect();
	assert_eq!(authors, BTreeMap::from([("ann-routes/a".into(), "Ann".into()), ("ann-routes/b".into(), "Bob".into())]));
	let lua = &pack_files(&p.guides, &manifest, &data)["Guides.lua"];
	assert_match(lua, r#"author = "Ann""#);
	assert_no_match(lua, r#"author = "Polestar""#);
}

#[test]
fn core_interface_keeps_a_multi_version_interface_line_whole() {
	let root = scratch("cp-iface");
	let toc = root.join("addon/Polestar/Polestar.toc");
	std::fs::create_dir_all(toc.parent().unwrap()).unwrap();
	std::fs::write(&toc, "## Title: Polestar\n## Interface: 11507, 16001  \n## Version: 1\n").unwrap();
	assert_eq!(core_interface(&root).unwrap(), "11507, 16001");
	std::fs::write(&toc, "## Interface:16001\r\n").unwrap();
	assert_eq!(core_interface(&root).unwrap(), "16001");
}

#[test]
fn a_pack_compiles_the_guides_under_its_folder_skipping_dist_drafts_node_modules_and_hidden_folders() {
	let dir = scratch("cp-skip");
	let mini = pack_fixture("mini");
	write_tree(&dir, &[("pack.json", &std::fs::read_to_string(mini.join("pack.json")).unwrap())]);
	for f in find_guide_files(&mini, true) {
		write_tree(&dir, &[(&f, &std::fs::read_to_string(mini.join(&f)).unwrap())]);
	}
	for sub in ["dist", "drafts", "node_modules", ".git", "guides/node_modules", "guides/.cache"] {
		write_tree(&dir, &[(&format!("{sub}/x.guide"), "this is not a guide\n")]);
	}
	// Only the top-level dist/ and drafts/ are skipped: a nested one is the author's own folder.
	write_tree(&dir, &[("guides/dist/c.guide", "guide mini/c\ntitle Mini C\nfaction Alliance\nlevels 2-6\nzone Elwynn Forest\n\nstep S\n  goto 47.6,35.1 \"Camp\"\n")]);
	let p = forge_guide::project::compile_project(&dir, &manifest_of(&dir), &fixture_data(), forge_guide::diag::Diagnostics::new(), false, None);
	assert!(p.diag.errors().is_empty(), "{:?}", p.diag.sorted());
	let mut ids: Vec<String> = p.guides.iter().map(|g| g.get("id").to_js_string()).collect();
	ids.sort();
	assert_eq!(ids, ["mini/a", "mini/b", "mini/c"]);
}
