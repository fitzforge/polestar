#[test]
fn guides_lua_builds_each_guide_in_its_own_function_sorted_by_id_with_its_source() {
	let (_, files) = build();
	let lua = &files["Guides.lua"];
	let blocks: Vec<(String, String)> = re(r"-- Source: (\S+)\ndo\n\tlocal function register\(\)\n\t\tPolestar\.RegisterGuide\(\{\n([\s\S]*?)\n\t\t\}\)\n\tend\n\tregister\(\)\nend\n")
		.captures_iter(lua)
		.map(|c| (c[1].to_string(), c[2].to_string()))
		.collect();
	assert_eq!(blocks.iter().map(|b| b.0.as_str()).collect::<Vec<_>>(), ["guides/a.guide", "guides/b.guide"]);
	assert_match(&blocks[0].1, r#"id = "mini/a""#);
	assert_match(&blocks[0].1, r#"pack = "mini""#);
	assert_match(&blocks[1].1, r#"id = "mini/b""#);
	assert_eq!(lua.matches("RegisterGuide(").count(), 2);
}

