//! Port of tools/lib/dsl/emit.js, generated.js.
//!
//! Emitter: compiled guides -> Lua source for a guide pack addon
//! (docs/ARCHITECTURE.md, "Guide data"). Output is deterministic: fixed key
//! order, stable number formatting, sorted guides. No file system here;
//! generated.js's syncFiles/reportSync (file writers) belong to the CLI.
//!
//! JS `throw new Error(...)` on data the emitter cannot write (a non-finite
//! number, a non-scalar) is a panic with the same message.

use crate::format::{needs, toc_marker, LEGACY_TOC_TITLE_PREFIX, TOC_TITLE_PREFIX};
