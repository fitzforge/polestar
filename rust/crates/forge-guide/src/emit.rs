/// Texts.lua: t = { pack: { english: translation }, guides: { [id]: { ... } } },
/// registered for the pack in `locale`. Each guide's table is built in its own
/// function: Lua 5.1 limits the constants of one.
pub fn emit_texts(pack_id: &str, locale: &str, t: &V) -> String {
	let entries = |o: &V| -> Vec<String> { sorted_keys(o).iter().map(|k| format!("\t[{}] = {},", lua_string(k), lua_str_v(&o.get(k)))).collect() };
	let mut out = vec![header("lua", crate::format::COMPILE_COMMAND, &format!("the pack's locales/{locale}/ files")), String::new(), "local t = { guides = {} }".into(), "t.pack = {".into()];
	out.extend(entries(&t.get("pack")));
	out.push("}".into());
	let guides = t.get("guides");
	for id in sorted_keys(&guides) {
		out.push(format!("t.guides[{}] = (function() return {{", lua_string(&id)));
		out.extend(entries(&guides.get(&id)).into_iter().map(|l| format!("\t{l}")));
		out.push("} end)()".into());
	}
	out.push(String::new());
	out.push(format!("Polestar.RegisterGuideTexts({}, {}, t)", lua_string(locale), lua_string(pack_id)));
	out.push(String::new());
	out.join("\n")
}

