/// `a.localeCompare(b)` (ICU root collation) for the source names: whitespace,
/// then punctuation and symbols in ICU's order, then digits, then letters
/// compared without case; ties go lower case first, then by code unit.
fn locale_compare(a: &str, b: &str) -> Ordering {
	const PUNCT: &str = "_-,;:!?.'\"()[]{}@*/\\&#%`^+<=>|~$";
	let primary = |c: char| -> (u32, u32) {
		if c.is_whitespace() {
			(0, c as u32)
		} else if let Some(i) = PUNCT.find(c) {
			(1, i as u32)
		} else if c.is_ascii_digit() {
			(3, c as u32)
		} else if c.is_alphabetic() {
			let l = c.to_lowercase().next().unwrap_or(c);
			(4, l as u32)
		} else {
			(2, c as u32)
		}
	};
	let pa: Vec<(u32, u32)> = a.chars().map(primary).collect();
	let pb: Vec<(u32, u32)> = b.chars().map(primary).collect();
	pa.cmp(&pb)
		.then_with(|| {
			// Tertiary: lower case before upper case.
			let ta: Vec<bool> = a.chars().map(|c| c.is_uppercase()).collect();
			let tb: Vec<bool> = b.chars().map(|c| c.is_uppercase()).collect();
			ta.cmp(&tb)
		})
		.then_with(|| cmp_utf16(a, b))
}

