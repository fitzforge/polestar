/// The first line of every generated file: the command that rebuilds it and
/// what it is built from, as a comment in the file's language ('lua', 'guide'
/// for guides and TOCs, 'svg'). An XML comment cannot hold "--", so an SVG's
/// header names the command without its options. Panics where the JS throws.
pub fn header(lang: &str, command: &str, sources: &str) -> String {
	let (open, close) = match lang {
		"lua" => ("-- ", ""),
		"guide" => ("# ", ""),
		"svg" => ("<!-- ", " -->"),
		_ => panic!("generated.header: unknown language \"{lang}\""),
	};
	// A forge command is named as it is; the others are still the JS tools' subcommands.
	let text = if command.starts_with("forge ") {
		format!("Generated by `{command}` from {sources}. Do not edit: rebuild with that command.")
	} else {
		format!("Generated by `node tools/polestar.js {command}` from {sources}. Do not edit: rebuild with that command.")
	};
	if lang == "svg" && text.contains("--") {
		panic!("generated.header: an SVG's header cannot contain \"--\" (XML comments forbid it): {text}");
	}
	format!("{open}{text}{close}")
}

