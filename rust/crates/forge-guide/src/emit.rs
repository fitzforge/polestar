pub fn lua_string(s: &str) -> String {
	let mut out = String::with_capacity(s.len() + 2);
	out.push('"');
	for ch in s.chars() {
		let c = ch as u32;
		match ch {
			'\\' => out.push_str("\\\\"),
			'"' => out.push_str("\\\""),
			'\n' => out.push_str("\\n"),
			'\r' => out.push_str("\\r"),
			'\t' => out.push_str("\\t"),
			_ if c < 32 || c == 127 => out.push_str(&format!("\\{c:03}")),
			_ => out.push(ch),
		}
	}
	out.push('"');
	out
}

/// `luaString(v)` of any value (`String(v)` first).
fn lua_str_v(v: &V) -> String {
	lua_string(&v.to_js_string())
}

/// Stable numbers: integers as-is, others rounded to `decimals` with no
/// exponent and no trailing zeros. (`decimals` defaults to 2 in the JS.)
pub fn lua_number(n: f64, decimals: usize) -> String {
	if !n.is_finite() {
		panic!("cannot emit non-finite number {}", num_str(n));
	}
	if n.fract() == 0.0 {
		return num_str(n);
	}
	let mut s = to_fixed(n, decimals);
	if s.contains('.') {
		s = s.trim_end_matches('0').to_string();
		if s.ends_with('.') {
			s.pop();
		}
	}
	if s == "-0" {
		s = "0".into();
	}
	s
}

fn type_of(v: &V) -> &'static str {
	match v {
		V::Undef => "undefined",
		V::Bool(_) => "boolean",
		V::Num(_) => "number",
		V::Str(_) => "string",
		_ => "object",
	}
}

fn scalar(v: &V, decimals: usize) -> String {
	match v {
		V::Str(s) => lua_string(s),
		V::Num(n) => lua_number(*n, decimals),
		V::Bool(b) => {
			if *b {
				"true".into()
			} else {
				"false".into()
			}
		}
		_ => panic!("cannot emit {} as a scalar", type_of(v)),
	}
}

/// `Object.keys(v).sort()`.
fn sorted_keys(v: &V) -> Vec<String> {
	let mut keys: Vec<String> = v.keys().iter().map(|k| k.to_string()).collect();
	keys.sort_by(|a, b| cmp_utf16(a, b));
	keys
}

/// `Object.keys(v).map(Number).sort((a, b) => a - b)`.
fn numeric_keys(v: &V) -> Vec<f64> {
	let mut keys: Vec<f64> = v.keys().iter().map(|k| str_to_num(k)).collect();
	keys.sort_by(|a, b| (a - b).partial_cmp(&0.0).unwrap_or(Ordering::Equal));
	keys
}

/// Keys for `inline`: fixed ones, or the value's own sorted.
enum Keys {
	Fixed(&'static [&'static str]),
	Sorted,
}

fn key_list(keys: &Keys, v: &V) -> Vec<String> {
	match keys {
		Keys::Fixed(k) => k.iter().map(|s| s.to_string()).collect(),
		Keys::Sorted => sorted_keys(v),
	}
}

fn fixed_or_sorted(k: Option<&'static [&'static str]>) -> Keys {
	k.map_or(Keys::Sorted, Keys::Fixed)
}

/// Arrays of scalars, or of tables (reagents) with a fixed key order.
fn list(arr: &V, keys: Option<&'static [&'static str]>, decimals: usize) -> String {
	list_with(arr, keys, decimals, None)
}

/// `list` with a guide's shared candidate records (Shared, #574), emitted as
/// references; two entries of one list stay distinct tables (ranking keys by
/// identity), so a record is referenced at most once per list.
fn list_with(arr: &V, keys: Option<&'static [&'static str]>, decimals: usize, records: Option<&Indexed>) -> String {
	let mut used: Vec<usize> = Vec::new();
	let parts: Vec<String> = arr
		.items()
		.iter()
		.map(|v| {
			let value = if v.is_object() { inline(v, &fixed_or_sorted(keys), decimals) } else { scalar(v, 2) };
			match records.and_then(|r| r.get(&value)) {
				Some(i) if !used.contains(&i) => {
					used.push(i);
					format!("candidateRecords[{i}]")
				}
				_ => value,
			}
		})
		.collect();
	format!("{{ {} }}", parts.join(", "))
}

/// Integer-keyed map (e.g. preTitles: quest id -> title), keys ascending.
fn id_map(obj: &V) -> String {
	let parts: Vec<String> = numeric_keys(obj).into_iter().map(|k| format!("[{}] = {}", num_str(k), scalar(&obj.get(&num_str(k)), 2))).collect();
	format!("{{ {} }}", parts.join(", "))
}

fn sub_keys(k: &str) -> Keys {
	match k {
		"only" => Keys::Fixed(&ONLY_KEYS),
		"lvl" => Keys::Fixed(&LVL_KEYS),
		_ => Keys::Sorted,
	}
}

fn inline(obj: &V, keys: &Keys, decimals: usize) -> String {
	inline_with(obj, keys, decimals, None)
}

/// `inline` of a goal with its guide's Shared, for its candidate lists (and,
/// in a packed guide, its spawn spots as one string).
fn inline_with(obj: &V, keys: &Keys, decimals: usize, shared: Option<&Shared>) -> String {
	let mut parts = Vec::new();
	for k in key_list(keys, obj) {
		let v = obj.get(&k);
		if v.is_nullish() {
			continue;
		}
		if k == "spots" && v.is_arr() && shared.is_some_and(|s| s.packed) {
			parts.push(format!("spotsPacked = {}", lua_string(&pack_spots(&v))));
		} else if v.is_arr() {
			let shared = if k == "candidates" { shared } else { None };
			let value = list_with(&v, list_keys(&k), list_decimals(&k), shared.map(|s| &s.records));
			match shared.and_then(|s| s.lists.get(&value)) {
				Some(i) => parts.push(format!("{k} = candidateLists[{i}]")),
				None => parts.push(format!("{k} = {value}")),
			}
		} else if k == "preTitles" {
			parts.push(format!("{k} = {}", id_map(&v)));
		} else if v.is_obj() {
			parts.push(format!("{k} = {}", inline(&v, &sub_keys(&k), decimals)));
		} else {
			parts.push(format!("{k} = {}", scalar(&v, decimals)));
		}
	}
	if parts.is_empty() {
		"{}".into()
	} else {
		format!("{{ {} }}", parts.join(", "))
	}
}

/// Values in first-seen order, numbered from 1 (a JS Map of value -> index).
#[derive(Default)]
struct Indexed {
	order: Vec<String>,
	index: std::collections::HashMap<String, usize>,
}

impl Indexed {
	fn get(&self, value: &str) -> Option<usize> {
		self.index.get(value).copied()
	}
	fn push(&mut self, value: String) {
		self.index.insert(value.clone(), self.order.len() + 1);
		self.order.push(value);
	}
}

/// Candidate lists and records repeated inside one guide, built once and
/// referenced (#574, HershelW), and the Lua lines declaring them. Candidates
/// are read-only; a goal's pick and ranking are its own. Nothing is shared
/// across guides (a guide of the other faction keeps none of this one's
/// data), nor spawn spots (visits key by identity). `packed`: the guide's
/// spawn spots are written as strings (pack_spots).
struct Shared {
	records: Indexed,
	lists: Indexed,
	lines: Vec<String>,
	packed: bool,
}

/// A goal's spawn spots as one string, `spotsPacked` (format 8, Polestar's
/// own pack; docs/PACK_FORMAT.md, "Format 8"): each spot's SPOT_KEYS values
/// in that order, separated by `,`, numbers as lua_number writes them, `alt`
/// as `1`, an absent value empty and trailing empty values dropped; spots
/// separated by `;`. Core/Guides.lua (Own.unpackSpots) builds the same tables
/// from it when the goal's `spots` is first read: a table per spot costs
/// about 250 bytes in the client, its text about 16.
pub fn pack_spots(spots: &V) -> String {
	let dec = list_decimals("spots");
	let records: Vec<String> = spots
		.items()
		.iter()
		.map(|s| {
			let mut fields: Vec<String> = SPOT_KEYS
				.iter()
				.map(|k| match s.get(k) {
					v if v.is_nullish() => String::new(),
					V::Num(n) if *k != "alt" => lua_number(n, dec),
					V::Bool(true) if *k == "alt" => "1".into(),
					v => panic!("cannot pack spawn spot field {k} = {}", v.to_js_string()),
				})
				.collect();
			while fields.last().is_some_and(String::is_empty) {
				fields.pop();
			}
			fields.join(",")
		})
		.collect();
	records.join(";")
}

fn sharing(steps: &V) -> Shared {
	let cand_keys = Some(&CANDIDATE_KEYS[..]);
	let dec = list_decimals("candidates");
	// Distinct lists in first-seen order with their use count and a goal holding them.
	let mut lists: Vec<(String, usize, V)> = Vec::new();
	let mut list_at: std::collections::HashMap<String, usize> = std::collections::HashMap::new();
	let mut records: Vec<(String, usize)> = Vec::new();
	let mut record_at: std::collections::HashMap<String, usize> = std::collections::HashMap::new();
	for step in steps.items() {
		for goal in step.get("goals").items() {
			let c = goal.get("candidates");
			if c.is_nullish() {
				continue;
			}
			let value = list(&c, cand_keys, dec);
			let at = match list_at.get(&value) {
				Some(&at) => at,
				None => {
					// Each distinct list counts its records once: a repeated list is shared whole.
					for r in c.items() {
						let record = inline(&r, &Keys::Fixed(&CANDIDATE_KEYS), dec);
						match record_at.get(&record) {
							Some(&i) => records[i].1 += 1,
							None => {
								record_at.insert(record.clone(), records.len());
								records.push((record, 1));
							}
						}
					}
					list_at.insert(value.clone(), lists.len());
					lists.push((value, 0, c.clone()));
					lists.len() - 1
				}
			};
			lists[at].1 += 1;
		}
	}
	let mut shared = Shared { records: Indexed::default(), lists: Indexed::default(), lines: Vec::new(), packed: false };
	for (value, n) in records {
		if n > 1 {
			shared.records.push(value);
		}
	}
	for (_, n, c) in &lists {
		if *n > 1 {
			let value = list_with(c, cand_keys, dec, Some(&shared.records));
			shared.lists.push(value);
		}
	}
	for (name, ix) in [("candidateRecords", &shared.records), ("candidateLists", &shared.lists)] {
		if ix.order.is_empty() {
			continue;
		}
		shared.lines.push(format!("local {name} = {{"));
		shared.lines.extend(ix.order.iter().map(|v| format!("\t{v},")));
		shared.lines.push("}".into());
	}
	shared
}

/// One guide's block of Guides.lua: its table is built inside its own
/// function, so Lua 5.1's per-function constant limit applies per guide.
/// A guide's steps as Lua table source lines, each line indented by `ind`.
fn step_lines(steps: &V, ind: &str, shared: &Shared) -> Vec<String> {
	let mut out = vec![format!("{ind}{{")];
	for step in steps.items() {
		out.push(format!("{ind}\t{{"));
		for sk in STEP_KEYS {
			let sv = step.get(sk);
			if sv.is_nullish() {
				continue;
			}
			match sk {
				"goals" => {
					out.push(format!("{ind}\t\tgoals = {{"));
					for goal in sv.items() {
						out.push(format!("{ind}\t\t\t{},", inline_with(&goal, &Keys::Fixed(&GOAL_KEYS), 2, Some(shared))));
					}
					out.push(format!("{ind}\t\t}},"));
				}
				"only" => out.push(format!("{ind}\t\tonly = {},", inline(&sv, &Keys::Fixed(&ONLY_KEYS), 2))),
				"image" => out.push(format!("{ind}\t\timage = {},", inline(&sv, &Keys::Fixed(&IMAGE_KEYS), 2))),
				"when" => out.push(format!("{ind}\t\twhen = {},", list(&sv, Some(&WHEN_KEYS), 2))),
				// `skipto` (format 5): each jump's label, then its one predicate.
				"skipto" => {
					let jumps: Vec<String> = sv.items().iter().map(|k| format!("{{ to = {}, when = {} }}", lua_str_v(&k.get("to")), inline(&k.get("when"), &Keys::Fixed(&WHEN_KEYS), 2))).collect();
					out.push(format!("{ind}\t\tskipto = {{ {} }},", jumps.join(", ")));
				}
				_ => out.push(format!("{ind}\t\t{sk} = {},", scalar(&sv, 2))),
			}
		}
		out.push(format!("{ind}\t}},"));
	}
	out.push(format!("{ind}}}"));
	out
}

/// `deferred` (a race part's guide, docs/PACK_FORMAT.md "Race parts"): the
/// steps as one source string (`stepsSrc`, `return { ... }`, run on first
/// read) with `stepCount`, and the guide registers only for a character of
/// one of its classes (Polestar.PartWants). `packed`: spawn spots as strings
/// (pack_spots, format 8).
fn emit_guide(guide: &V, source_rel: &V, deferred: bool, packed: bool) -> String {
	let mut out: Vec<String> = Vec::new();
	if source_rel.truthy() {
		out.push(format!("-- Source: {}", source_rel.to_js_string().replace(['\r', '\n'], " ")));
	}
	let mut shared = sharing(&guide.get("steps"));
	shared.packed = packed;
	out.extend(["do", "\tlocal function register()"].map(String::from));
	// Deferred steps carry their shared candidates inside their own source.
	if !deferred {
		out.extend(shared.lines.iter().map(|l| format!("\t\t{l}")));
	}
	out.push("\t\tPolestar.RegisterGuide({".into());
	for k in GUIDE_KEYS {
		let v = guide.get(k);
		if v.is_nullish() {
			continue;
		}
		if k == "steps" && deferred {
			out.push(format!("\t\t\tstepCount = {},", v.len()));
			// The group quests its steps ask about (`when group`), for the
			// options' list without reading the steps (Engine.GroupQuests).
			let mut groups: Vec<(V, V)> = Vec::new();
			for step in v.items() {
				for p in step.get("when").items() {
					let q = p.get("q");
					if p.get("k").as_str() != Some("group") || groups.iter().any(|x| x.0.strict_eq(&q)) {
						continue;
					}
					let goal = step.get("goals").items().into_iter().find(|g| g.get("quest").strict_eq(&q) && g.get("title").truthy());
					let title = match goal {
						Some(g) => g.get("title"),
						None => step.get("title"),
					};
					groups.push((q, title));
				}
			}
			if !groups.is_empty() {
				let parts: Vec<String> = groups
					.iter()
					.map(|(quest, title)| {
						let t = if title.truthy() { format!(", title = {}", lua_str_v(title)) } else { String::new() };
						format!("{{ quest = {}{t} }}", quest.to_js_string())
					})
					.collect();
				out.push(format!("\t\t\tgroupQuests = {{ {} }},", parts.join(", ")));
			}
			let mut src = shared.lines.clone();
			src.push(format!("return {}", step_lines(&v, "", &shared).join("\n")));
			out.push(format!("\t\t\tstepsSrc = {},", lua_string(&src.join("\n"))));
		} else if k == "steps" {
			let lines = step_lines(&v, "\t\t\t", &shared);
			out.push("\t\t\tsteps = {".into());
			out.extend_from_slice(&lines[1..lines.len() - 1]);
			out.push("\t\t\t},".into());
		} else if k == "nextWhen" {
			// guide id -> its predicates, in the order of nextChoices.
			let parts: Vec<String> = v.keys().iter().map(|id| format!("[{}] = {}", lua_string(id), list(&v.get(id), Some(&WHEN_KEYS), 2))).collect();
			out.push(format!("\t\t\tnextWhen = {{ {} }},", parts.join(", ")));
		} else if k == "names" || k == "written" {
			// The English of the texts' name tokens (tools/lib/dsl/tokens.js), "kind:id" -> name;
			// written: the author's words of a text that spells a name otherwise, tokenised text -> words.
			let parts: Vec<String> = sorted_keys(&v).iter().map(|t| format!("[{}] = {}", lua_string(t), lua_str_v(&v.get(t)))).collect();
			out.push(format!("\t\t\t{k} = {{ {} }},", parts.join(", ")));
		} else if v.is_arr() {
			out.push(format!("\t\t\t{k} = {},", list(&v, list_keys(k), 2)));
		} else {
			out.push(format!("\t\t\t{k} = {},", scalar(&v, 2)));
		}
	}
	let classes = guide.get("classes");
	let classes = if deferred && classes.as_arr().is_some_and(|a| !a.is_empty()) { Some(classes) } else { None };
	out.push("\t\t})".into());
	out.push("\tend".into());
	out.push(match classes {
		Some(c) => format!("\tif Polestar.PartWants({}) then register() end", list(&c, None, 2)),
		None => "\tregister()".into(),
	});
	out.push("end".into());
	format!("{}\n", out.join("\n"))
}

// The data emitGuide writes, as plain JSON values instead of Lua source: the
// same keys in the same places, numbers rounded as luaNumber rounds them, so
// a guide carried another way (an import string, tools/lib/pack/importstring.js)
// registers exactly as Guides.lua registers it. `pack` is left out: the
// carrier names the pack. preTitles keeps its quest ids as the object's keys.
fn data_scalar(v: &V, decimals: usize) -> V {
	match v {
		V::Num(n) => V::Num(str_to_num(&lua_number(*n, decimals))),
		V::Str(_) | V::Bool(_) => v.clone(),
		_ => panic!("cannot write {} as a scalar", type_of(v)),
	}
}

fn data_list(arr: &V, keys: Option<&'static [&'static str]>, decimals: usize) -> V {
	let items: Vec<V> = arr.items().iter().map(|v| if v.is_object() { data_inline(v, &fixed_or_sorted(keys), decimals) } else { data_scalar(v, 2) }).collect();
	V::from(items)
}

fn data_inline(obj: &V, keys: &Keys, decimals: usize) -> V {
	let out = Obj::new();
	for k in key_list(keys, obj) {
		let v = obj.get(&k);
		if v.is_nullish() {
			continue;
		}
		if v.is_arr() {
			out.set(&k, data_list(&v, list_keys(&k), list_decimals(&k)));
		} else if k == "preTitles" {
			let ids = Obj::new();
			for id in numeric_keys(&v) {
				ids.set(&num_str(id), data_scalar(&v.get(&num_str(id)), 2));
			}
			out.set(&k, ids);
		} else if v.is_obj() {
			out.set(&k, data_inline(&v, &sub_keys(&k), decimals));
		} else {
			out.set(&k, data_scalar(&v, decimals));
		}
	}
	V::Obj(out)
}

/// The data `emit_guide` writes, as JSON values (see above).
pub fn guide_data(guide: &V) -> V {
	let out = Obj::new();
	for k in GUIDE_KEYS {
		let v = guide.get(k);
		if v.is_nullish() || k == "pack" {
			continue;
		}
		if k == "steps" {
			let steps: Vec<V> = v
				.items()
				.iter()
				.map(|step| {
					let s = Obj::new();
					for sk in STEP_KEYS {
						let sv = step.get(sk);
						if sv.is_nullish() {
							continue;
						}
						match sk {
							"goals" => s.set("goals", V::from(sv.items().iter().map(|goal| data_inline(goal, &Keys::Fixed(&GOAL_KEYS), 2)).collect::<Vec<_>>())),
							"only" => s.set("only", data_inline(&sv, &Keys::Fixed(&ONLY_KEYS), 2)),
							"image" => s.set("image", data_inline(&sv, &Keys::Fixed(&IMAGE_KEYS), 2)),
							"when" => s.set("when", data_list(&sv, Some(&WHEN_KEYS), 2)),
							"skipto" => s.set(
								"skipto",
								V::from(sv.items().iter().map(|k| V::Obj(crate::obj! { "to" => k.get("to"), "when" => data_inline(&k.get("when"), &Keys::Fixed(&WHEN_KEYS), 2) })).collect::<Vec<_>>()),
							),
							_ => s.set(sk, data_scalar(&sv, 2)),
						}
					}
					V::Obj(s)
				})
				.collect();
			out.set("steps", V::from(steps));
		} else if k == "nextWhen" {
			let m = Obj::new();
			for id in v.keys() {
				m.set(&id, data_list(&v.get(&id), Some(&WHEN_KEYS), 2));
			}
			out.set(k, m);
		} else if k == "names" || k == "written" {
			let m = Obj::new();
			for t in sorted_keys(&v) {
				m.set(&t, v.get(&t).to_js_string());
			}
			out.set(k, m);
		} else if v.is_arr() {
			out.set(k, data_list(&v, list_keys(k), 2));
		} else {
			out.set(k, data_scalar(&v, 2));
		}
	}
	V::Obj(out)
}

