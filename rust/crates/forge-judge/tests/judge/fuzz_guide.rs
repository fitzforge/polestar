#[test]
#[ignore = "needs POLESTAR_CHECKOUT (guides, data/forever) and lua5.1"]
fn fuzz_guide_agrees() {
	assert!(have_world(), "guide fuzzing needs POLESTAR_CHECKOUT (guides/forever, data/forever) and lua5.1");
	let out = std::env::var_os("POLESTAR_FUZZ_OUT").map(PathBuf::from);
	COUNTS.with(|c| c.set([0; 4]));
	check!().with_type::<Case>().with_test_time(Duration::from_secs(1)).for_each(|case| {
		with_world(|w| {
			let text = render(w, case);
			let v = judge(&w.data, &text);
			COUNTS.with(|c| {
				let [n, asked, refused, lint] = c.get();
				c.set([n + 1, asked + v.addon.is_some() as usize, refused + matches!(v.addon, Some(Err(_))) as usize, lint + (v.lint_errors == Some(0)) as usize]);
			});
			for sig in signatures(&v) {
				if let Some(dir) = &out {
					record(&w.data, dir, &text, &sig);
				} else if !KNOWN.contains(&sig.as_str()) {
					panic!("{sig}\n--- input ---\n{text}");
				}
			}
		})
	});
	let c = COUNTS.with(Cell::get);
	eprintln!("fuzz: {} inputs, {} compiled clean and asked the addon, {} of those refused by it, {} of those clean in lint too", c[0], c[1], c[2], c[3]);
}

#[test]
#[ignore = "needs POLESTAR_CHECKOUT (guides, data/forever) and lua5.1"]
fn fuzz_guide_regressions() {
	assert!(have_world(), "guide fuzzing needs POLESTAR_CHECKOUT (guides/forever, data/forever) and lua5.1");
	with_world(regressions);
}

fn regressions(w: &World) {
	let dir = crate_dir().join("tests/fuzz");
	let mut files: Vec<PathBuf> = std::fs::read_dir(&dir).unwrap().flatten().map(|e| e.path()).filter(|p| p.extension().is_some_and(|e| e == "guide")).collect();
	files.sort();
	let mut failures = Vec::new();
	for path in &files {
		let name = path.file_name().unwrap().to_string_lossy().into_owned();
		let text = std::fs::read_to_string(path).unwrap();
		let sigs = signatures(&judge(&w.data, &text));
		// The leading `# fuzz: <signature>` lines: what a gap-* input shows, all of it.
		let wants: Vec<&str> = text.lines().map_while(|l| l.strip_prefix("# fuzz: ")).collect();
		if name.starts_with("gap-") {
			assert!(!wants.is_empty(), "{name}: starts with `# fuzz: <signature>` lines");
			for want in &wants {
				if !KNOWN.contains(want) {
					failures.push(format!("{name}: `{want}` is not in KNOWN"));
				}
			}
			if sigs.iter().map(String::as_str).collect::<Vec<_>>() != wants {
				failures.push(format!("{name}: shows {sigs:?}, pinned {wants:?} (fixed? rename it ok-*, drop it from KNOWN)"));
			}
		} else if !sigs.is_empty() {
			failures.push(format!("{name}: {sigs:?}"));
		}
	}
	assert!(failures.is_empty(), "{}", failures.join("\n"));
	eprintln!("fuzz regressions: {} inputs", files.len());
}

/// The oracle's sanity: every seed (as the fuzzer cuts it) compiles clean and the addon registers it.
#[test]
#[ignore = "needs POLESTAR_CHECKOUT (guides, data/forever) and lua5.1"]
