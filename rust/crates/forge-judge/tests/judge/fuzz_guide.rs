#[derive(Debug, Default)]
struct Verdict {
	/// Panic messages (compile, emit, lint).
	panics: Vec<String>,
	/// Compile error diagnostics, "line: message".
	compile_errors: Vec<String>,
	/// Lint's error count, when lint ran: only for what compile accepted and the addon refused, to tell a
	/// lint gap from a compile-only one.
	lint_errors: Option<usize>,
	/// The addon's answer for what compile accepted (None: compile refused, nothing asked).
	addon: Option<Result<usize, String>>,
}

/// Panic payload as text.
fn panic_text(e: Box<dyn std::any::Any + Send>) -> String {
	e.downcast_ref::<String>().cloned().or_else(|| e.downcast_ref::<&str>().map(|s| s.to_string())).unwrap_or_else(|| "panic".into())
}

fn source(text: &str) -> Vec<Source> {
	vec![Source { source: "fuzz.guide".into(), file: "fuzz.guide".into(), text: text.into() }]
}

/// The emitted Guides.lua of the compiled guides as build_pack_files writes them: the main file's
/// guides, then each race part's (deferred steps).
fn emit(guides: &[V]) -> String {
	let entry = |g: &V| {
		let loc = g.hidden("_localised");
		V::Obj(forge_guide::obj! { "guide" => if loc.truthy() { loc } else { g.clone() }, "source" => "fuzz.guide" })
	};
	let main: Vec<V> = guides.iter().filter(|g| race_part(g).is_none()).map(entry).collect();
	let parts: Vec<V> = guides.iter().filter(|g| race_part(g).is_some()).map(entry).collect();
	let mut out = forge_guide::emit::emit_guides(&main, false);
	if !parts.is_empty() {
		out.push_str(&forge_guide::emit::emit_guides(&parts, true));
	}
	out
}

fn errors_of(diag: &Diagnostics) -> Vec<String> {
	diag.errors().iter().map(|d| format!("{}: {}", d.line, d.message)).collect()
}

/// Compile, emit, ask the addon. compile_sources = resolve + the pack's ownership check + validate + the
/// name tokens (about 0.3 s a call: tokenise_guides indexes the whole data each time), so resolve and
/// validate run first on their own: their errors are compile's errors already, and most inputs stop there.
fn judge(data: &Data, text: &str) -> Verdict {
	let mut v = Verdict::default();
	let sources = source(text);
	let quick = catch_unwind(AssertUnwindSafe(|| {
		let mut diag = Diagnostics::new();
		let guides = resolve_sources(&sources, data, &mut diag, Some("guides"), None);
		validate_guides(&guides, data, &mut diag);
		errors_of(&diag)
	}));
	match quick {
		Err(e) => {
			v.panics.push(format!("compile panics: {}", panic_text(e)));
			return v;
		}
		Ok(errors) if !errors.is_empty() => {
			v.compile_errors = errors;
			return v;
		}
		Ok(_) => {}
	}
	let compiled = catch_unwind(AssertUnwindSafe(|| {
		let mut diag = Diagnostics::new();
		let opts = CompileOpts { pack: Some("guides".into()), author: None, context: None, pack_dir: None };
		let c = compile_sources(&sources, data, &mut diag, &opts);
		(c.guides, errors_of(&diag))
	}));
	match compiled {
		Err(e) => v.panics.push(format!("compile panics: {}", panic_text(e))),
		Ok((guides, errors)) => {
			let clean = errors.is_empty();
			v.compile_errors = errors;
			if clean {
				match catch_unwind(AssertUnwindSafe(|| emit(&guides))) {
					Err(e) => v.panics.push(format!("emit panics: {}", panic_text(e))),
					Ok(lua) => v.addon = Some(ask_addon(&lua)),
				}
			}
		}
	}
	if matches!(v.addon, Some(Err(_))) {
		match catch_unwind(AssertUnwindSafe(|| lint_sources(&sources, data, &V::obj()))) {
			Err(e) => v.panics.push(format!("lint panics: {}", panic_text(e))),
			Ok(d) => v.lint_errors = Some(d.iter().filter(|d| d.severity == "error").count()),
		}
	}
	v
}

/// Digits to N, the guide id before the addon's reason dropped: what tells two findings apart.
fn normalise(s: &str) -> String {
	let s = match s.find(": ") {
		Some(i) if s[..i].contains('/') && !s[..i].contains(' ') => &s[i + 2..],
		_ => s,
	};
	let mut out = String::new();
	let mut digits = false;
	for c in s.chars().take(160) {
		if c.is_ascii_digit() {
			if !digits {
				out.push('N');
			}
			digits = true;
		} else {
			digits = false;
			out.push(c);
		}
	}
	out
}

/// The disagreements of a verdict, as signatures. The lint gap is only told apart when the compile
/// (with the pack's ownership check lint does not run) agrees, since both see the same guides.
fn signatures(v: &Verdict) -> Vec<String> {
	let mut out: Vec<String> = v.panics.iter().map(|p| normalise(p)).collect();
	if let Some(Err(why)) = &v.addon {
		out.push(format!("compile accepts: {}", normalise(why)));
		if v.lint_errors == Some(0) && !why.contains("id outside pack") {
			out.push(format!("lint accepts: {}", normalise(why)));
		}
	}
	out
}

