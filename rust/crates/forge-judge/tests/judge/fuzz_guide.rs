#[derive(Debug, Clone, TypeGenerator)]
enum Edit {
	Delete(u16),
	Duplicate(u16),
	Swap(u16, u16),
	/// A body line inserted (indented as a step's) or, with `header`, a header line in column 0.
	Insert {
		at: u16,
		header: bool,
		line: Line,
	},
	/// A line of a seed guide inserted (crossover).
	Splice {
		at: u16,
		seed: u8,
		line: u16,
	},
	ReplaceWord(u16, u8, Word),
	InsertWord(u16, u8, Word),
	DeleteWord(u16, u8),
	/// A character of a line replaced by one of a few that matter to the lexer.
	Char(u16, u16, u8),
	Indent(u16, u8),
	Truncate(u16),
}

#[derive(Debug, Clone, TypeGenerator)]
struct Case {
	base: Base,
	#[generator(produce::<Vec<Edit>>().with().len(0usize..=6))]
	edits: Vec<Edit>,
}

const CHARS: &[char] = &['"', '\\', '|', '#', '@', ',', '.', '-', ' ', '\t', '!', '<', '>', '=', 'x', '0', '9', '\0', 'é', '\r', '/', '+', '\'', '\u{a0}'];

fn word(w: &World, x: &Word) -> String {
	match x {
		Word::Token(i) => w.tokens[*i as usize % w.tokens.len()].clone(),
		Word::Num(k, v) => match k % 7 {
			0 => (v % 10).to_string(),
			1 => (v % 70).to_string(),
			2 | 3 => (v % 30000).to_string(),
			4 => v.to_string(),
			5 => format!("-{}", v % 100),
			_ => format!("{}.{}", v % 100, v / 100 % 100),
		},
		Word::Name(i) => NAMES[*i as usize % NAMES.len()].to_string(),
		Word::Weird(i) => WEIRD[*i as usize % WEIRD.len()].to_string(),
		Word::Edge(i) => EDGE[*i as usize % EDGE.len()].to_string(),
	}
}

fn line(w: &World, l: &Line, templates: &[&str]) -> String {
	templates[l.template as usize % templates.len()].replace("$a", &word(w, &l.a)).replace("$b", &word(w, &l.b)).replace("$c", &word(w, &l.c))
}

fn body_line(w: &World, l: &Line) -> String {
	let s = line(w, l, BODY);
	if s.starts_with("step") {
		s
	} else {
		format!("  {s}")
	}
}

fn render(w: &World, case: &Case) -> String {
	let mut lines: Vec<String> = match &case.base {
		Base::Seed(i) => w.seeds[*i as usize % w.seeds.len()].clone(),
		Base::Built { header, body } => {
			let mut l: Vec<String> = ["guide forever/fuzz/built", "title Fuzz", "levels 1-10", "zone Durotar"].map(String::from).to_vec();
			l.extend(header.iter().map(|h| line(w, h, HEADER)));
			l.push(String::new());
			l.push("step Start".into());
			l.push("  note Start".into());
			l.extend(body.iter().map(|b| body_line(w, b)));
			l
		}
		Base::Edgy(list) => {
			let mut l: Vec<String> = ["guide forever/fuzz/edgy", "title Fuzz", "levels 1-10", "zone Durotar", "", "step Start", "  note Start"].map(String::from).to_vec();
			let e = |i: &u8| EDGE[*i as usize % EDGE.len()];
			for (t, a, b, c) in list {
				let s = EDGY[*t as usize % EDGY.len()].replace("${a}", e(a)).replace("${b}", e(b)).replace("$a", e(a)).replace("$b", e(b)).replace("$c", e(c));
				l.push(format!("  {s}"));
			}
			l
		}
	};
	for e in &case.edits {
		let n = lines.len().max(1);
		let at = |i: &u16| *i as usize % n;
		let words_of = |s: &str| s.split(' ').map(str::to_string).collect::<Vec<_>>();
		match e {
			Edit::Delete(i) if !lines.is_empty() => {
				lines.remove(at(i));
			}
			Edit::Duplicate(i) if !lines.is_empty() => {
				let l = lines[at(i)].clone();
				lines.insert(at(i), l);
			}
			Edit::Swap(i, j) if !lines.is_empty() => lines.swap(at(i), at(j)),
			Edit::Insert { at: i, header, line: l } => {
				let s = if *header { line(w, l, HEADER) } else { body_line(w, l) };
				let i = (*i as usize) % (lines.len() + 1);
				lines.insert(i, s);
			}
			Edit::Splice { at: i, seed, line: k } => {
				let s = &w.seeds[*seed as usize % w.seeds.len()];
				let l = s[*k as usize % s.len()].clone();
				let i = (*i as usize) % (lines.len() + 1);
				lines.insert(i, l);
			}
			Edit::ReplaceWord(i, k, x) | Edit::InsertWord(i, k, x) if !lines.is_empty() => {
				let i = at(i);
				let mut ws = words_of(&lines[i]);
				let k = *k as usize % (ws.len() + 1);
				let x = word(w, x);
				if matches!(e, Edit::ReplaceWord(..)) && k < ws.len() {
					ws[k] = x;
				} else {
					ws.insert(k, x);
				}
				lines[i] = ws.join(" ");
			}
			Edit::DeleteWord(i, k) if !lines.is_empty() => {
				let i = at(i);
				let mut ws = words_of(&lines[i]);
				let k = *k as usize % ws.len();
				ws.remove(k);
				lines[i] = ws.join(" ");
			}
			Edit::Char(i, k, c) if !lines.is_empty() => {
				let i = at(i);
				let mut cs: Vec<char> = lines[i].chars().collect();
				let c = CHARS[*c as usize % CHARS.len()];
				if cs.is_empty() {
					cs.push(c);
				} else {
					let k = *k as usize % cs.len();
					cs[k] = c;
				}
				lines[i] = cs.into_iter().collect();
			}
			Edit::Indent(i, k) if !lines.is_empty() => {
				let i = at(i);
				let t = lines[i].trim_start().to_string();
				lines[i] = format!("{}{t}", ["", "  ", "\t", "    ", " "][*k as usize % 5]);
			}
			Edit::Truncate(i) => lines.truncate(*i as usize % (lines.len() + 1)),
			_ => {}
		}
	}
	let mut text = lines.join("\n");
	text.push('\n');
	text
}

// ---------------------------------------------------------------------------
// Minimising and recording findings.
// ---------------------------------------------------------------------------

/// Shortest input still showing `sig`: line chunks dropped (ddmin-style halving), then single words.
fn minimise(data: &Data, text: &str, sig: &str) -> String {
	let holds = |t: &str| signatures(&judge(data, t)).iter().any(|s| s == sig);
	let mut lines: Vec<String> = text.lines().map(str::to_string).collect();
	let mut chunk = lines.len().div_ceil(2).max(1);
	loop {
		let mut i = 0;
		let mut changed = false;
		while i < lines.len() {
			let end = (i + chunk).min(lines.len());
			let mut cand = lines.clone();
			cand.drain(i..end);
			if !cand.is_empty() && holds(&(cand.join("\n") + "\n")) {
				lines = cand;
				changed = true;
			} else {
				i += chunk;
			}
		}
		if chunk == 1 && !changed {
			break;
		}
		if !changed {
			chunk = chunk.div_ceil(2);
		}
	}
	for li in 0..lines.len() {
		let mut k = 0;
		loop {
			let ws: Vec<&str> = lines[li].split(' ').collect();
			if k >= ws.len() || ws.len() == 1 {
				break;
			}
			let cand_line = ws.iter().enumerate().filter(|(j, _)| *j != k).map(|(_, w)| *w).collect::<Vec<_>>().join(" ");
			let mut cand = lines.clone();
			cand[li] = cand_line;
			if holds(&(cand.join("\n") + "\n")) {
				lines = cand;
			} else {
				k += 1;
			}
		}
	}
	lines.join("\n") + "\n"
}

fn slug(sig: &str) -> String {
	let mut s: String = sig.chars().map(|c| if c.is_ascii_alphanumeric() { c.to_ascii_lowercase() } else { '-' }).collect();
	while s.contains("--") {
		s = s.replace("--", "-");
	}
	s.trim_matches('-').chars().take(80).collect()
}

/// Collect mode: a new signature's input minimised and written to `dir`.
fn record(data: &Data, dir: &Path, text: &str, sig: &str) {
	let new = SEEN.with(|seen| {
		let mut seen = seen.borrow_mut();
		let new = !seen.iter().any(|s| s == sig);
		if new {
			seen.push(sig.to_string());
		}
		new
	});
	if !new {
		return;
	}
	let min = minimise(data, text, sig);
	std::fs::create_dir_all(dir).unwrap();
	let path = dir.join(format!("{}.guide", slug(sig)));
	std::fs::write(&path, format!("# fuzz: {sig}\n{min}")).unwrap();
	eprintln!("fuzz: {sig}\n  -> {}", path.display());
}

