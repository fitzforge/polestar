struct World {
	data: Data,
	seeds: Vec<Vec<String>>,
	tokens: Vec<String>,
}

thread_local! {
	/// Per test thread: Data holds Rc values. None when the inputs are absent.
	static WORLD: Option<World> = load_world();
	/// The Lua oracle, one process per test thread.
	static ORACLE: RefCell<Option<Oracle>> = const { RefCell::new(None) };
	/// Signatures already recorded (collect mode).
	static SEEN: RefCell<Vec<String>> = const { RefCell::new(Vec::new()) };
	/// fuzz_guide_agrees: inputs, compiled without an error (asked the addon), refused by it, with lint errors.
	static COUNTS: Cell<[usize; 4]> = const { Cell::new([0; 4]) };
}

fn load_world() -> Option<World> {
	let Some(checkout) = std::env::var_os("POLESTAR_CHECKOUT").map(PathBuf::from) else {
		eprintln!("note: POLESTAR_CHECKOUT unset: guide fuzzing skipped");
		return None;
	};
	let (guides, data_dir) = (checkout.join("guides/forever"), checkout.join("data/forever"));
	if !data_dir.is_dir() || !guides.is_dir() || Command::new("lua5.1").arg("-v").output().is_err() {
		eprintln!("note: POLESTAR_CHECKOUT's data or guides, or lua5.1 missing: guide fuzzing skipped");
		return None;
	}
	let data = load_data(&data_dir).expect("data loads");
	// `next` lines name guides outside the one-file pack: dropped, so a seed compiles clean on its own.
	let seeds: Vec<Vec<String>> = SEEDS
		.iter()
		.map(|rel| {
			let text = std::fs::read_to_string(guides.join(rel)).expect("seed guide");
			text.lines().filter(|l| !l.starts_with("next ")).take(SEED_LINES).map(str::to_string).collect()
		})
		.collect();
	let mut tokens: Vec<String> = seeds.iter().flatten().flat_map(|l| l.split_whitespace().map(str::to_string)).collect();
	tokens.sort();
	tokens.dedup();
	Some(World { data, seeds, tokens })
}

fn have_world() -> bool {
	WORLD.with(Option::is_some)
}

fn with_world<R>(f: impl FnOnce(&World) -> R) -> R {
	WORLD.with(|w| f(w.as_ref().expect("world loaded")))
}

struct Oracle {
	child: Child,
	stdin: ChildStdin,
	stdout: BufReader<ChildStdout>,
}

fn spawn_oracle() -> Oracle {
	let mut child = Command::new("lua5.1")
		.arg(crate_dir().join("tests/fuzz/oracle.lua"))
		.arg(root().join("addon/Polestar/Core/Guides.lua"))
		.stdin(Stdio::piped())
		.stdout(Stdio::piped())
		.spawn()
		.expect("lua5.1 runs");
	let stdin = child.stdin.take().unwrap();
	let stdout = BufReader::new(child.stdout.take().unwrap());
	Oracle { child, stdin, stdout }
}

/// The addon's answer for one Guides.lua chunk: Ok(guides registered) or Err(why it refuses).
fn ask_addon(chunk: &str) -> Result<usize, String> {
	ORACLE.with(|cell| {
		let mut slot = cell.borrow_mut();
		for _ in 0..2 {
			let o = slot.get_or_insert_with(spawn_oracle);
			let mut line = String::new();
			let ok = write!(o.stdin, "{}\n{}", chunk.len(), chunk).is_ok() && o.stdin.flush().is_ok() && o.stdout.read_line(&mut line).map(|n| n > 0).unwrap_or(false);
			if ok {
				let line = line.trim_end();
				return match line.strip_prefix("ok ") {
					Some(n) => Ok(n.parse().unwrap()),
					None => Err(line.strip_prefix("refuse ").unwrap_or(line).to_string()),
				};
			}
			if let Some(mut dead) = slot.take() {
				let _ = dead.child.kill();
			}
		}
		panic!("the Lua oracle died twice");
	})
}

