//! Parity with the JS writer (tools/lib/nav/pack.js through `nav pack`): the nav-pack golden (the
//! nav-grid golden's synthetic grid, its README), and opt-in a real grid against a folder the JS packed.

use super::{files_under, golden_dir, tmp};
use forge_nav::pack::{check_pack, pack_nav, ship_pack, PackIn};
use std::path::{Path, PathBuf};

const JS: &str = "node tools/polestar.js nav pack";

fn pack_golden(cells: usize, out: &Path, generator: &str) {
	let g = golden_dir();
	let p = g.join("nav-pack");
	let log = |_: &str| {};
	let pack = pack_nav(&PackIn {
		grid: &g.join("nav-grid/nav4"),
		layers: &p.join("nav-layers"),
		area_table: &p.join("data/AreaTable.csv"),
		zones: &p.join("data/zones.json"),
		map_frames: &p.join("data/map-frames.json"),
		aids: Some(&p.join("aids.json")),
		cells,
		date: "2026-10-23",
		continents: &[0],
		generator,
		log: &log,
	})
	.unwrap();
	ship_pack(&pack, out).unwrap();
}

fn same_tree(got: &Path, want: &Path) {
	assert_eq!(files_under(got), files_under(want), "the same files");
	for f in files_under(want) {
		let (a, b) = (std::fs::read(got.join(&f)).unwrap(), std::fs::read(want.join(&f)).unwrap());
		assert!(a == b, "{f} differs from the JS's ({} vs {} bytes)", a.len(), b.len());
	}
}

#[test]
fn golden_pack_matches_the_js_at_128_and_32_cells() {
	for (cells, dir) in [(128, "Polestar_Nav"), (32, "Polestar_Nav-32")] {
		let out = tmp(&format!("golden-{cells}"));
		pack_golden(cells, &out, JS);
		same_tree(&out, &golden_dir().join("nav-pack").join(dir));
		assert!(check_pack(&out).is_empty());
	}
}

#[test]
fn forge_names_itself_in_the_headers_pack_json_and_nav_xml() {
	let out = tmp("forge-name");
	pack_golden(32, &out, "forge nav pack");
	let meta = std::fs::read_to_string(out.join("Nav/Nav0.lua")).unwrap();
	assert!(meta.starts_with("-- Generated by `forge nav pack --cells 32` from the navigation grid (null null, built 2026-10-23) on 2026-10-23."));
	assert!(std::fs::read_to_string(out.join("PACK.json")).unwrap().contains("\"generator\": \"forge nav pack\""));
	assert!(std::fs::read_to_string(out.join("Nav/Nav.xml")).unwrap().contains("Written by forge nav pack:"));
	assert!(check_pack(&out).is_empty());
}

/// PACK_GRID=<grid> PACK_ROOT=<checkout: data/forever, data/sources/wago> PACK_LAYERS=<nav-layers>
/// PACK_REF=<the JS's Polestar_Nav of that grid> PACK_DATE=<its date> cargo test --profile quick -p forge-nav
/// --test pack -- --ignored real_grid (Eastern Kingdoms, Kalimdor, Zephras Isle: about 2 min; every file
/// identical on 2026-10-23's 1.60.1.70532 grid). A grid with area sidecars (maps format 3) differs from the last
/// JS writer (baked-legs 73e0ebbc8) by design: forge packs only the rows with a name (pack_nav's `named`).
#[test]
#[ignore = "needs PACK_GRID, PACK_ROOT, PACK_LAYERS, PACK_REF and PACK_DATE"]
fn real_grid_matches_the_js() {
	let env = |k: &str| PathBuf::from(std::env::var(k).unwrap_or_else(|_| panic!("needs {k}")));
	let (grid, root, layers, want) = (env("PACK_GRID"), env("PACK_ROOT"), env("PACK_LAYERS"), env("PACK_REF"));
	let date = std::env::var("PACK_DATE").expect("needs PACK_DATE");
	let wago = root.join("data/sources/wago");
	let mut builds: Vec<String> = std::fs::read_dir(&wago).unwrap().flatten().map(|e| e.file_name().to_string_lossy().into_owned()).filter(|b| wago.join(b).join("AreaTable.csv").is_file()).collect();
	builds.sort_by_key(|b| b.split('.').map(|p| p.parse::<u64>().unwrap_or(0)).collect::<Vec<_>>());
	let aids = grid.join("aids.json");
	let log = |m: &str| eprintln!("{m}");
	let pack = pack_nav(&PackIn {
		grid: &grid,
		layers: &layers,
		area_table: &wago.join(builds.last().unwrap()).join("AreaTable.csv"),
		zones: &root.join("data/forever/zones.json"),
		map_frames: &root.join("data/forever/map-frames.json"),
		aids: aids.is_file().then_some(aids.as_path()),
		cells: 128,
		date: &date,
		continents: &forge_nav::pack::MAPS,
		generator: JS,
		log: &log,
	})
	.unwrap();
	let out = tmp("real");
	ship_pack(&pack, &out).unwrap();
	for f in files_under(&want.join("Nav")) {
		assert!(std::fs::read(out.join("Nav").join(&f)).unwrap() == std::fs::read(want.join("Nav").join(&f)).unwrap(), "Nav/{f} differs");
	}
	assert_eq!(std::fs::read_to_string(out.join("PACK.json")).unwrap(), std::fs::read_to_string(want.join("PACK.json")).unwrap());
	let _ = std::fs::remove_dir_all(&out);
}
