/// A uiMap's (width, height) in yards; None for maps not in the table.
pub fn size(map: u32) -> Option<(f64, f64)> {
	MAP_SIZES.binary_search_by_key(&map, |(id, _, _)| *id).ok().map(|i| (MAP_SIZES[i].1, MAP_SIZES[i].2))
}

#[cfg(test)]
mod tests {
	use super::*;

	#[test]
	fn sorted_and_positive() {
		assert!(MAP_SIZES.windows(2).all(|w| w[0].0 < w[1].0));
		assert!(MAP_SIZES.iter().all(|(_, w, h)| *w > 0.0 && *h > 0.0));
		let (w, h) = size(1411).unwrap();
		assert!((w - 5287.5).abs() < 0.01 && (h - 3525.0).abs() < 0.01, "Durotar {w} {h}");
		assert_eq!(size(1), None);
	}
}
