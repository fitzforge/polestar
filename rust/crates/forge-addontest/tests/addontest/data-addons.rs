//! The addon reading what `forge data itemdb` and `forge data maps build` write: the committed
//! Polestar_ItemDB loads on demand, stays within its budget and decodes as forge-data encodes it; the
//! item data addon is loaded on the first lookup, once, never in combat; ZoneLevels.lua registers the
//! ranges and the world map colours them for the player.

use forge_addontest::{emitted, Addon, RunAddon};

fn root() -> std::path::PathBuf {
	std::path::Path::new(env!("CARGO_MANIFEST_DIR")).join("../../..").canonicalize().unwrap()
}
use serde_json::{json, Value};

fn item_files() -> Addon {
	Addon::files("Polestar", &["Core/Init.lua", "Gear/ItemDB.lua"])
}

fn lua_path(p: &std::path::Path) -> String {
	forge_addontest::lua_string(&p.to_string_lossy().replace('\\', "/"))
}

#[test]
fn the_generated_item_data_loads_on_demand_within_budget_and_reads_as_forge_encodes_it() {
	let file = root().join("addon/Polestar_ItemDB/Items.lua");
	let text = std::fs::read_to_string(&file).unwrap();
	assert!(text.len() <= forge_data::itemdb::SIZE_BUDGET, "Items.lua over the budget");
	assert!(text.starts_with("-- Generated by `forge data itemdb`"));
	// A sample of entries, decoded the way forge-data encodes them, against the addon's parser.
	let entries: Vec<(i64, String)> = text
		.lines()
		.filter_map(|l| {
			let (id, rest) = l.strip_prefix('[')?.split_once("]=\"")?;
			Some((id.parse().ok()?, rest.trim_end_matches("\",").to_string()))
		})
		.step_by(47)
		.collect();
	let ids: Vec<String> = entries.iter().map(|e| e.0.to_string()).collect();
	let out = emitted(&RunAddon {
		addons: vec![item_files()],
		script: format!(
			r#"local before = Polestar.ItemDB.IsLoaded()
			dofile({})
			emit({{ before, Polestar.ItemDB.IsLoaded() }})
			emit(Polestar.ItemDB.Get(1482))
			emit(Polestar.ItemDB.Meta().count)
			local got = {{}}
			for _, id in ipairs({{ {} }}) do got[tostring(id)] = Polestar.ItemDB.Get(id) end
			emit(got)"#,
			lua_path(&file),
			ids.join(", ")
		),
		..Default::default()
	});
	assert_eq!(out[0], json!([false, true]));
	let sword = &out[1];
	assert_eq!([&sword["inv"], &sword["req"], &sword["class"], &sword["subclass"], &sword["stats"]["dps"]], [&json!(21), &json!(19), &json!(2), &json!(7), &json!(17.8)], "Shadowfang");
	assert!(out[2].as_f64().unwrap() > 5000.0);
	for (id, s) in &entries {
		let rec = forge_data::gear::leveling::decode(*id as f64, s).unwrap();
		let lua = &out[3][id.to_string()];
		let mut want: serde_json::Map<String, Value> = rec.stats.iter().map(|(k, v)| (k.clone(), json!(v))).collect();
		if let (Some(lo), Some(hi), Some(sp)) = (rec.dmin, rec.dmax, rec.speed) {
			want.insert("dps".into(), json!(forge_data::jsv::math_round((lo + hi) / 2.0 / (sp / 1000.0) * 10.0) / 10.0));
		}
		let got: serde_json::Map<String, Value> = lua["stats"].as_object().cloned().unwrap_or_default().into_iter().map(|(k, v)| (k, json!(v.as_f64().unwrap()))).collect();
		let want: serde_json::Map<String, Value> = want.into_iter().map(|(k, v)| (k, json!(v.as_f64().unwrap()))).collect();
		assert_eq!(got, want, "item {id}");
		let n = |v: &forge_guide::js::V| json!(v.num());
		assert_eq!(
			[&lua["inv"], &lua["ilvl"], &lua["req"], &lua["quality"], &lua["class"], &lua["subclass"]].map(|v| json!(v.as_f64().unwrap())),
			[n(&rec.inv), n(&rec.ilvl), n(&rec.req), n(&rec.quality), n(&rec.cls), n(&rec.sub)],
			"item {id}"
		);
		assert_eq!((json!(lua["allow"].as_f64().unwrap_or(0.0)), lua["unique"].as_bool().unwrap_or(false)), (n(&rec.allow), rec.unique), "item {id}");
	}
}

#[test]
fn the_item_data_addon_is_loaded_on_the_first_lookup_once_and_never_in_combat() {
	let out = emitted(&RunAddon {
		addons: vec![item_files()],
		script: r#"local calls = 0
			C_AddOns.LoadAddOn = function(name)
				calls = calls + 1
				if name == "Polestar_ItemDB" then Polestar.ItemDB.Register({ count = 1 }, { [5] = "1 5 1 1 4 1 sta1" }) end
				return true
			end
			stub.inCombat = true
			local inCombat = Polestar.ItemDB.Get(5) == nil
			stub.inCombat = false
			local after = Polestar.ItemDB.Get(5).stats.sta
			Polestar.ItemDB.Get(6)
			emit({ inCombat, after, calls })"#
			.into(),
		..Default::default()
	});
	assert_eq!(out[0], json!([true, 1, 1]));
}

#[test]
fn zone_levels_register_and_the_world_map_colours_them_for_the_player() {
	let dir = std::env::temp_dir().join(format!("forge-addontest-zonelevels-{}", std::process::id()));
	std::fs::create_dir_all(&dir).unwrap();
	let pts = |n: usize, x: f64, y: f64| json!((0..n).map(|i| [x + (i % 5) as f64, y + (i / 5) as f64]).collect::<Vec<_>>());
	let sp = |zone: u32, p: Value| json!({ zone.to_string(): { "f": "e", "pts": p } });
	let npcs = json!({
		"100": { "id": 100, "name": "Wolf", "level": 10, "levelMax": 11, "faction": null, "spawns": sp(1, pts(40, 20.0, 20.0)) },
		"101": { "id": 101, "name": "Bandit", "level": 14, "faction": null, "spawns": sp(1, pts(60, 40.0, 40.0)) },
		"102": { "id": 102, "name": "Ogre", "level": 18, "levelMax": 20, "faction": null, "spawns": sp(1, pts(30, 60.0, 60.0)) },
		"200": { "id": 200, "name": "Citizen", "level": 30, "faction": "A", "spawns": sp(2, pts(300, 10.0, 10.0)) }
	});
	std::fs::write(dir.join("npcs.json"), npcs.to_string()).unwrap();
	std::fs::write(dir.join("zones.json"), r#"{"1":{"id":1,"name":"Greenvale","type":3},"2":{"id":2,"name":"Capital","type":3}}"#).unwrap();
	let (_, lua) = forge_data::worldmap::zone_levels(&dir).unwrap();
	assert!(lua.contains("\t[1] = { 10, 19, "), "{lua}");
	let file = dir.join("ZoneLevels.lua");
	std::fs::write(&file, &lua).unwrap();
	let out = emitted(&RunAddon {
		stubs: vec!["stub_world.lua"],
		addons: vec![Addon::files("Polestar", &["Core/Core.xml", "Theme/Theme.xml", "Nav/Nav.xml", "Maps/Maps.lua", "Maps/WorldMap.lua"])],
		login: true,
		script: format!(
			r#"assert(loadfile({}))("Polestar", Polestar)
			local M = Polestar.Maps
			local lo, hi = M.GetZoneLevels(1)
			local each, agree = {{}}, true
			for id, a, b in M.EachZoneLevels() do
				each[#each + 1] = id
				local x, y = M.GetZoneLevels(id)
				if x ~= a or y ~= b then agree = false end
			end
			emit({{ lo = lo, hi = hi, none = M.GetZoneLevels(2) or false, text = M.FormatLevels(lo, hi),
				colors = {{ M.LevelColor(lo, hi, 5), M.LevelColor(lo, hi, 9), M.LevelColor(lo, hi, 12), M.LevelColor(lo, hi, 22), M.LevelColor(lo, hi, 40) }},
				each = each, agree = agree }})"#,
			lua_path(&file)
		),
		..Default::default()
	});
	std::fs::remove_dir_all(&dir).unwrap();
	assert_eq!(out[0], json!({ "lo": 10, "hi": 19, "none": false, "text": "10–19", "colors": ["danger", "warning", "quest", "success", "textMuted"], "each": [1], "agree": true }));
}

/// ClassTrainers.lua as `forge data trainers` writes it on the compiler's fixture data: the training
/// reminder picks the nearest trainer of the character's class, with the frames to place it.
#[test]
fn class_trainers_register_where_they_stand_and_the_nearest_of_the_class_is_picked() {
	let tmp = std::env::temp_dir().join(format!("forge-addontest-trainers-{}", std::process::id()));
	let (guides, recs, data) = (tmp.join("guides"), tmp.join("recs"), tmp.join("data"));
	for d in [&guides, &recs, &data] {
		std::fs::create_dir_all(d).unwrap();
	}
	for e in std::fs::read_dir(root().join("tests/fixtures/dsl/data")).unwrap().flatten() {
		std::fs::copy(e.path(), data.join(e.file_name())).unwrap();
	}
	std::fs::write(guides.join("a.guide"), "guide t/main\ntitle Test\nfaction Alliance\nlevels 1-10\nzone Elwynn Forest\n\nstep S\n  train 3153 only Warrior\n").unwrap();
	let (_, lua, _) = forge_data::trainers::run(&data, Some(&guides), &recs).unwrap();
	let file = tmp.join("ClassTrainers.lua");
	std::fs::write(&file, lua).unwrap();
	let nearest = |race: &str, faction: &str, map: u32, x: f64, y: f64| {
		emitted(&RunAddon {
			stubs: vec!["stub_world.lua"],
			before: format!(r#"stub.world.race, stub.world.faction, stub.world.class = "{race}", "{faction}", "WARRIOR"; stub.world.moveTo({map}, {x}, {y})"#),
			addons: vec![Addon::files("Polestar", &["Core/Core.xml"])],
			script: format!(
				"assert(loadfile({}))(\"Polestar\", Polestar)\nstub.login()\nlocal t = Polestar.Engine.NearestClassTrainer()\nemit({{ npc = t and t.npc, faction = t and t.faction }})",
				lua_path(&file)
			),
			..Default::default()
		})[0]
			.clone()
	};
	assert_eq!(nearest("Human", "Alliance", 1429, 48.0, 42.0), json!({ "npc": 911, "faction": "A" }));
	assert_eq!(nearest("Orc", "Horde", 1411, 43.0, 68.0), json!({ "npc": 3153, "faction": "H" }));
	std::fs::remove_dir_all(&tmp).unwrap();
}
