'use strict';
// A pack compiles to a self-contained addon folder: the
// generated TOC, Pack.lua with the credits, MapFrames.lua, Guides.lua with one
// function per guide, LICENSE-DATA.txt; and the generated-folder guard.

const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { runAddon } = require('./helpers/lua');
const { DATA_DIR } = require('./helpers/dsl');
const { tmpdir } = require('./helpers/tmp');
const { readManifest } = require('../tools/lib/pack/manifest');
const { compileProject, buildPackFiles, writePackDir, packDirRefusal, coreInterface } = require('../tools/lib/dsl/project');

const MINI = path.join(__dirname, 'fixtures', 'packs', 'mini');

function build() {
	const { manifest, diags } = readManifest(MINI);
	assert.deepEqual(diags, []);
	const { guides, diag, data } = compileProject({ packDir: MINI, manifest, dataDir: DATA_DIR });
	assert.equal(diag.hasErrors(), false);
	return { manifest, files: buildPackFiles({ guides, manifest, data }) };
}

test('the mini pack builds exactly the fixed file set', () => {
	const { manifest, files } = build();
	assert.equal(manifest.folder, 'PolestarPack_MiniPack');
	assert.deepEqual(Object.keys(files).sort(), ['Guides.lua', 'LICENSE-DATA.txt', 'PolestarPack_MiniPack.toc', 'MapFrames.lua', 'Pack.lua'].sort());
});

test('the TOC is generated with the credits, the format and the marker', () => {
	const { files } = build();
	assert.equal(coreInterface(), '16001');
	assert.equal(
		files['PolestarPack_MiniPack.toc'],
		[
			'## Interface: 16001',
			'## Title: Polestar Community: Mini Pack',
			'## Notes: Community addon for Polestar by Ann',
			'## Author: Ann',
			'## Version: 0.3.0',
			'## Category: Quests',
			'## Group: Polestar',
			'## Dependencies: Polestar',
			'## X-Polestar-Pack: mini',
			'## X-Polestar-Format: 3',
			'## X-Polestar-Needs: 0.2.5',
			'## X-License: CC0-1.0',
			'## X-Website: https://example.org/mini',
			'# Generated by `node tools/polestar.js compile` from pack.json and the .guide files. Do not edit: rebuild with that command.',
			'',
			'Pack.lua',
			'MapFrames.lua',
			'Guides.lua',
			'',
		].join('\n'),
	);
});

test('a title already carrying the new or the legacy prefix is kept as written', () => {
	const { manifest } = build();
	const { emitToc } = require('../tools/lib/dsl/emit');
	for (const title of ['Polestar Community: Mini Pack', 'Polestar Pack: Mini Pack']) {
		assert.match(emitToc({ ...manifest, title }, '16001'), new RegExp(`^## Title: ${title}$`, 'm'));
	}
});

test('Pack.lua registers the pack with its credits', () => {
	const { files } = build();
	assert.equal(
		files['Pack.lua'],
		'-- Generated by `node tools/polestar.js compile` from pack.json. Do not edit: rebuild with that command.\nlocal ADDON = ...\n\n' +
			'Polestar.RegisterPack({ addon = ADDON, id = "mini", format = 3, title = "Mini Pack", author = "Ann", version = "0.3.0", license = "CC0-1.0", website = "https://example.org/mini" })\n',
	);
});

test('Guides.lua builds each guide in its own function, sorted by id, with its source', () => {
	const { files } = build();
	const lua = files['Guides.lua'];
	const blocks = [...lua.matchAll(/-- Source: (\S+)\ndo\n\tlocal function register\(\)\n\t\tPolestar\.RegisterGuide\(\{\n([\s\S]*?)\n\t\t\}\)\n\tend\n\tregister\(\)\nend\n/g)];
	assert.deepEqual(
		blocks.map((m) => m[1]),
		['guides/a.guide', 'guides/b.guide'],
	);
	assert.match(blocks[0][2], /id = "mini\/a"/);
	assert.match(blocks[0][2], /pack = "mini"/);
	assert.match(blocks[1][2], /id = "mini\/b"/);
	assert.equal((lua.match(/RegisterGuide\(/g) || []).length, 2);
});

test('MapFrames.lua registers the frames under the pack id', () => {
	const { files } = build();
	assert.match(files['MapFrames.lua'], /\nPolestar\.RegisterMapFrames\(\{\n\tera = \{\n\t\t\[1429\] = \{[^\n]+\},\n\t\},\n\}, "mini"\)\n$/);
});

test('the built folder loads through its TOC and registers both guides', () => {
	const { manifest, files } = build();
	const dir = path.join(tmpdir(), manifest.folder);
	writePackDir(dir, files);
	const [out] = runAddon({
		addons: [{ name: 'Polestar', files: ['Core/Core.xml'] }, { name: manifest.folder, dir }],
		script: 'emit({ a = Polestar.Guides.Get("mini/a") ~= nil, b = Polestar.Guides.Get("mini/b") ~= nil, next = Polestar.Guides.Get("mini/a").next })',
	}).emitted;
	assert.deepEqual(out, { a: true, b: true, next: 'mini/b' });
});

test('two builds produce identical bytes', () => {
	assert.deepEqual(build().files, build().files);
});

test('writePackDir refuses a folder it did not generate', () => {
	const { files } = build();
	const dir = tmpdir();
	fs.writeFileSync(path.join(dir, 'PolestarPack_MiniPack.toc'), '## Title: Mine\n\nMine.lua\n');
	fs.writeFileSync(path.join(dir, 'Mine.lua'), '-- mine\n');
	assert.throws(() => writePackDir(dir, files), /not a generated community addon/);
	assert.equal(fs.readFileSync(path.join(dir, 'PolestarPack_MiniPack.toc'), 'utf8'), '## Title: Mine\n\nMine.lua\n');
	assert.equal(fs.existsSync(path.join(dir, 'Pack.lua')), false);
});

test('writePackDir replaces the old Pack.xml layout', () => {
	const { files } = build();
	const dir = tmpdir();
	fs.mkdirSync(path.join(dir, 'Guides', 'forever'), { recursive: true });
	fs.writeFileSync(path.join(dir, 'Guides', 'forever', 'old.lua'), '-- old\n');
	fs.writeFileSync(path.join(dir, 'Pack.xml'), '<Ui>\n\t<!-- Generated by `node tools/polestar.js compile`. Do not edit. -->\n</Ui>\n');
	fs.writeFileSync(path.join(dir, 'PolestarPack_MiniPack.toc'), '## Title: Old\n\nPack.xml\n');
	writePackDir(dir, files);
	assert.equal(fs.existsSync(path.join(dir, 'Pack.xml')), false);
	assert.equal(fs.existsSync(path.join(dir, 'Guides')), false);
	assert.deepEqual(fs.readdirSync(dir).sort(), Object.keys(files).sort());
	for (const [name, content] of Object.entries(files)) assert.equal(fs.readFileSync(path.join(dir, name), 'utf8'), content);
});

test('writePackDir replaces stale files in a generated folder, and drops a LICENSE.txt the build no longer has', () => {
	const { files } = build();
	const dir = tmpdir();
	writePackDir(dir, { ...files, 'Guides.lua': '-- stale\n', 'Pack.lua': '-- stale\n', 'LICENSE.txt': 'a licence the pack no longer has\n' });
	writePackDir(dir, files);
	assert.deepEqual(fs.readdirSync(dir).sort(), Object.keys(files).sort());
	for (const [name, content] of Object.entries(files)) assert.equal(fs.readFileSync(path.join(dir, name), 'utf8'), content);
});

test('one folder rule: an absent or empty folder, or a generated one, may be replaced; anything else is refused', () => {
	const { files } = build();
	const root = tmpdir();
	const absent = path.join(root, 'absent');
	assert.equal(packDirRefusal(absent), null);
	const empty = path.join(root, 'empty');
	fs.mkdirSync(empty);
	assert.equal(packDirRefusal(empty), null);
	writePackDir(empty, files);
	assert.equal(packDirRefusal(empty), null, 'a generated folder');
	const mine = path.join(root, 'mine');
	fs.mkdirSync(mine);
	fs.writeFileSync(path.join(mine, 'notes.txt'), 'mine\n');
	assert.match(packDirRefusal(mine), /^it is not a generated community addon \(no TOC with the ".*" line\); move it away first$/);
	const file = path.join(root, 'file');
	fs.writeFileSync(file, 'x');
	assert.equal(packDirRefusal(file), 'it is not a folder');
	assert.throws(() => writePackDir(file, files), /refusing to write into .*file: it is not a folder/);
});

test("a guide without an author is credited to its pack's author; one with `author` keeps it", () => {
	const dir = tmpdir();
	fs.writeFileSync(path.join(dir, 'pack.json'), JSON.stringify({ id: 'ann-routes', title: 'Ann Routes', author: 'Ann', version: '1.0.0', license: 'CC0-1.0' }));
	const header = (id) => [`guide ann-routes/${id}`, `title ${id}`, 'faction Alliance', 'levels 1-6', 'zone Elwynn Forest'];
	fs.writeFileSync(path.join(dir, 'a.guide'), [...header('a'), '', 'step Kobold camp', '  goto 47.6,35.1 "Kobold camp"', ''].join('\n'));
	fs.writeFileSync(path.join(dir, 'b.guide'), [...header('b'), 'author Bob', '', 'step Kobold camp', '  goto 47.6,35.1 "Kobold camp"', ''].join('\n'));
	const { manifest, diags } = readManifest(dir);
	assert.deepEqual(diags, []);
	const { guides, diag, data } = compileProject({ packDir: dir, manifest, dataDir: DATA_DIR });
	assert.equal(diag.hasErrors(), false);
	assert.deepEqual(Object.fromEntries(guides.map((g) => [g.id, g.author])), { 'ann-routes/a': 'Ann', 'ann-routes/b': 'Bob' });
	const lua = buildPackFiles({ guides, manifest, data })['Guides.lua'];
	assert.match(lua, /author = "Ann"/);
	assert.doesNotMatch(lua, /author = "Polestar"/);
});

test('coreInterface keeps a multi-version Interface line whole', () => {
	const toc = path.join(tmpdir(), 'Polestar.toc');
	fs.writeFileSync(toc, '## Title: Polestar\n## Interface: 11507, 16001  \n## Version: 1\n');
	assert.equal(coreInterface(toc), '11507, 16001');
	fs.writeFileSync(toc, '## Interface:16001\r\n');
	assert.equal(coreInterface(toc), '16001');
});

test('a pack compiles the guides under its folder, skipping dist/, drafts/, node_modules/ and hidden folders', () => {
	const dir = tmpdir();
	fs.cpSync(MINI, dir, { recursive: true });
	const broken = 'this is not a guide\n';
	for (const sub of ['dist', 'drafts', 'node_modules', '.git', path.join('guides', 'node_modules'), path.join('guides', '.cache')]) {
		fs.mkdirSync(path.join(dir, sub), { recursive: true });
		fs.writeFileSync(path.join(dir, sub, 'x.guide'), broken);
	}
	// Only the top-level dist/ and drafts/ are skipped: a nested one is the author's own folder.
	fs.mkdirSync(path.join(dir, 'guides', 'dist'));
	fs.writeFileSync(path.join(dir, 'guides', 'dist', 'c.guide'), ['guide mini/c', 'title Mini C', 'faction Alliance', 'levels 2-6', 'zone Elwynn Forest', '', 'step S', '  goto 47.6,35.1 "Camp"', ''].join('\n'));
	const { manifest } = readManifest(dir);
	const { guides, diag } = compileProject({ packDir: dir, manifest, dataDir: DATA_DIR });
	assert.deepEqual(diag.errors, []);
	assert.deepEqual(guides.map((g) => g.id).sort(), ['mini/a', 'mini/b', 'mini/c']);
});
