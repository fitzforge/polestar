'use strict';
// tools/lib/dsl/classspells.js: the spells a class trainer teaches, from the
// Forever client's SkillLineAbility, SkillLine, SpellLevels and SpellName
// (rows shaped as wago.tools' CSV; spell ids and levels from build
// 1.60.1.70450, the warlock's first ranks).

const { test } = require('node:test');
const assert = require('node:assert/strict');
const { buildClassSpells, emitClassSpells } = require('../tools/lib/dsl/classspells');

const WARLOCK = '256';
const sla = (Spell, SkillLine, extra = {}) => ({ Spell, SkillLine, ClassMask: WARLOCK, AcquireMethod: '0', SupercedesSpell: '0', RaceMasks_0: '0', ...extra });
const lvl = (SpellID, SpellLevel, BaseLevel = SpellLevel) => ({ SpellID, SpellLevel: String(SpellLevel), BaseLevel: String(BaseLevel), DifficultyID: '0' });

const TABLES = {
	SkillLine: [
		{ ID: '354', CategoryID: '7', Flags: '1040' }, // Demonology
		{ ID: '593', CategoryID: '7', Flags: '1040' }, // Destruction
		{ ID: '2851', CategoryID: '7', Flags: '146' }, // Engraving
		{ ID: '188', CategoryID: '7', Flags: '0' }, // Pet - Imp
	],
	SkillLineAbility: [
		sla('348', '593'), // Immolate 1
		sla('707', '593'), // Immolate 2
		sla('1094', '593'), // Immolate 3
		sla('5697', '354'), // Unending Breath: BaseLevel 0, SpellLevel 16
		sla('403919', '2851'), // Engrave Gloves - Haunt
		sla('3110', '188'), // Firebolt (the imp's)
		sla('17877', '593', { AcquireMethod: '0' }), // Shadowburn: no level row
		sla('6201', '354', { AcquireMethod: '3' }), // not learned at a trainer
		sla('116', '593', { ClassMask: '128' }), // another class's
	],
	SpellLevels: [lvl('348', 1), lvl('707', 10), lvl('1094', 20), lvl('5697', 16, 0), lvl('403919', 1, 0), lvl('3110', 1), lvl('6201', 10), lvl('116', 4)],
	SpellName: ['348', '707', '1094', '5697', '403919', '3110', '17877', '6201', '116'].map((ID) => ({
		ID, Name_lang: { 348: 'Immolate', 707: 'Immolate', 1094: 'Immolate', 5697: 'Unending Breath' }[ID] || `Spell ${ID}`,
	})),
};

test('a class\'s trainer spells: its specialisation lines only, learned at a trainer, with a level, ranks linked by name', () => {
	const out = buildClassSpells(TABLES);
	assert.deepEqual(out.WARLOCK, [
		{ spell: 348, level: 1, prev: null, races: null },
		{ spell: 707, level: 10, prev: 348, races: null },
		{ spell: 5697, level: 16, prev: null, races: null },
		{ spell: 1094, level: 20, prev: 707, races: null },
	]);
	assert.deepEqual(out.MAGE, [{ spell: 116, level: 4, prev: null, races: null }]);
});

test('the Lua names its source and lists rows per class in order', () => {
	const lua = emitClassSpells(buildClassSpells(TABLES), '1.60.1.70450');
	assert.match(lua, /^-- Generated by `node tools\/polestar.js trainers spells`.*1\.60\.1\.70450/);
	assert.match(lua, /WARLOCK = \{\n\t\t\{ 348, 1, 0, 0 \},\n\t\t\{ 707, 10, 348, 0 \},/);
	assert.doesNotMatch(lua, /WARRIOR = /, 'a class with no spells is left out');
});
