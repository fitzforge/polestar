'use strict';
// The generator behind addon/Polestar/Core/GatherData.lua (tools/lib/professions/gathering/spots.js): where each
// gathering node can spawn, for While you're here's gathering spots (Core/Gather.lua). On synthetic data: the kinds
// and the skills they ask, what is left out, the spots and their encoding; then (with data/forever built) that the
// committed file is the one the data makes.

const { test } = require('node:test');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');

const S = require('../tools/lib/professions/gathering/spots');
const { makeProjector } = require('../tools/lib/route/geo');

const ROOT = path.resolve(__dirname, '..');
const DATA = path.join(ROOT, 'data', 'forever');
const hasData = fs.existsSync(path.join(DATA, 'objects.json')) && fs.existsSync(path.join(DATA, 'map-frames.json'));

// Elwynn 3000 x 2000 yd: 30 yd a map percent across, 20 down.
const FRAMES = { era: { 1429: { c: 0, left: 1500, right: -1500, top: 500, bottom: -1500 } }, forever: {} };
const spawns = (pts) => ({ 1429: { f: 'e', pts } });
const OBJECTS = {
	1618: { id: 1618, name: 'Peacebloom', roles: ['herb'], spawns: spawns([[40, 50], [40.5, 50], [60, 50]]) },
	3724: { id: 3724, name: 'Peacebloom', roles: ['herb'], spawns: spawns([[40.2, 50.3]]) },
	1731: { id: 1731, name: 'Copper Vein', roles: ['mine'], spawns: spawns([[20, 20]]) },
	1620: { id: 1620, name: 'Mageroyal', roles: ['herb'], spawns: spawns([[30, 30]]) },
	656160: { id: 656160, name: 'Wilted Peacebloom', spawns: spawns([[10, 10]]) },
	180655: { id: 180655, name: 'Floating Wreckage', roles: ['fishing'], spawns: spawns([[50, 90]]) },
	123309: { id: 123309, name: 'Ooze Covered Gold Vein', roles: ['mine'], spawns: spawns([[70, 70]]) },
	1610: { id: 1610, name: 'Incendicite Mineral Vein', roles: ['mine'], spawns: {} },
	2843: { id: 2843, name: 'Battered Chest', roles: ['chest'], spawns: spawns([[80, 80]]) },
};

test('the kinds: herbs and ore by their skill, Forever\'s own nodes by name, pools for fishers; no oozes, chests or kinds without spawns', () => {
	const kinds = S.kindsOf(OBJECTS).map((k) => [k.name, k.line, k.skill, k.ids]);
	assert.deepEqual(kinds, [
		['Peacebloom', 182, 1, [1618, 3724]],
		['Wilted Peacebloom', 182, 1, [656160]],
		['Mageroyal', 182, 50, [1620]],
		['Copper Vein', 186, 1, [1731]],
		['Floating Wreckage', 356, 1, [180655]],
	]);
});

test('points of a kind within 40 yards are one spot at their middle; each spot is four base-60 digits, never an x or a z', () => {
	const project = makeProjector(FRAMES);
	const peace = S.kindsOf(OBJECTS)[0];
	const spots = S.spotsOf(peace, project).get(1429).spots.map((p) => [Math.round(p.x * 100) / 100, Math.round(p.y * 100) / 100, p.n]);
	// 40,50 and 40.5,50 (15 yd apart) and the other object's 40.2,50.3 (8 yd): one spot; 60,50: another.
	assert.deepEqual(spots, [[40.23, 50.1, 3], [60, 50, 1]]);
	assert.equal(S.enc(0), '00');
	assert.equal(S.enc(100), '//');
	assert.equal(S.enc(40) + S.enc(50), 'O0U0');
	assert.equal(S.DIGITS.length, 60);
	assert.doesNotMatch(S.DIGITS, /[xz]/i, 'the data can never spell a word with an x or a z');
	const text = S.render({ data: { objects: OBJECTS }, project });
	assert.match(text, /^-- Generated by `node tools\/polestar\.js profession gathering spots` from /);
	assert.match(text, /\n\t\t\{ "Peacebloom", 182, 1, 1618, 3724 \},\n/);
	const spot = (x, y) => (S.enc(x) + S.enc(y)).replace(/[+/]/g, '\\$&');
	assert.match(text, new RegExp(`\\n\\t\\t\\[1429\\] = "e;1:${spot(40.23, 50.1)}${spot(60, 50)};2:`));
	assert.doesNotMatch(text, /Ooze|Battered Chest|Incendicite/);
});

test('the committed gathering spots are the ones the data makes', { skip: hasData ? false : 'data/forever not built' }, () => {
	let objects = JSON.parse(fs.readFileSync(path.join(DATA, 'objects.json'), 'utf8'));
	if (objects.objects) objects = objects.objects;
	const project = makeProjector(JSON.parse(fs.readFileSync(path.join(DATA, 'map-frames.json'), 'utf8')));
	const text = S.render({ data: { objects }, project });
	assert.equal(fs.readFileSync(path.join(S.OUT_DIR, S.OUT_FILE), 'utf8'), text, 'run node tools/polestar.js profession gathering spots');
	for (const m of text.matchAll(/^\t\t\[\d+\] = "([^"]*)",$/gm)) assert.doesNotMatch(m[1], /[xz]/i);
});
